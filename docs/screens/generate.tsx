/** Начало блока тёмной темы. Разбор ищет ровно это и внутрь скобок заходит по счёту. */
const ТЁМНЫЙ_ЗАПРОС = /@media\s*\(prefers-color-scheme:\s*dark\)\s*\{/g

/**
 * Величины светлой и тёмной темы, вынутые из таблицы стилей.
 *
 * Светлые берутся **вне** блока `@media (prefers-color-scheme: dark)`, тёмные — **внутри** него.
 * Прежняя редакция считала «тёмной областью» всё от начала медиазапроса до конца файла, и любой
 * `:root`, стоящий после блока, молча уезжал в тёмную тему. Найдено проверкой кода.
 *
 * Границы разбора названы в тексте отказа `сверитьЕдинственность` — там, где их и прочтут.
 */
export function величиныТемы(css: string): { светлая: string; тёмная: string } {
  const чистый = css.replace(/\/\*[\s\S]*?\*\//g, (м) => ' '.repeat(м.length))
  const дляСкобок = гаситьКавычки(чистый)

  const запросы = [...дляСкобок.matchAll(ТЁМНЫЙ_ЗАПРОС)]
  сверитьЕдинственность('блоков `@media (prefers-color-scheme: dark)`', запросы.length)

  const открывающая = дляСкобок.indexOf('{', запросы[0].index)
  const конец = конецБлока(дляСкобок, открывающая)
  const светлая = блокВеличин('светлая тема', чистый, дляСкобок, [
    [0, запросы[0].index],
    [конец + 1, чистый.length],
  ])
  const тёмная = блокВеличин('тёмная тема', чистый, дляСкобок, [[открывающая + 1, конец]])

  сверитьВеличиныТем('таблица стилей', светлая, тёмная)
  return { светлая, тёмная }
}

/**
 * Гасит содержимое кавычек, сохраняя длину строки.
 *
 * Нужно ровно для счёта скобок: `--q: "}"` прежде обрывал набор величин посреди объявления, и
 * обрывал **молча**. Гашение идёт по отдельной копии — величины на снимок берутся из настоящей,
 * иначе шрифтовой стек `'Segoe UI'` уехал бы в снимок пробелами.
 */
function гаситьКавычки(css: string): string {
  return css.replace(/"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'/g, (м) => ' '.repeat(м.length))
}

/**
 * Содержимое единственного `:root { … }` в области. Два блока или ни одного — отказ.
 *
 * Область задаётся отрезками исходного текста: искать надо по копии с погашенными кавычками, а
 * возвращать — из настоящей, и потому оба текста ходят рядом с одинаковыми смещениями.
 */
function блокВеличин(
  область: string,
  чистый: string,
  дляСкобок: string,
  отрезки: Array<[number, number]>,
): string {
  const начала: number[] = []
  for (const [от, до] of отрезки) {
    const кусок = дляСкобок.slice(от, до)
    for (const м of кусок.matchAll(/(?:^|[\s};])(:root)\s*\{/g)) {
      начала.push(от + м.index + м[0].indexOf(':root'))
    }
  }
  сверитьЕдинственность(`блоков величин \`:root\` в области «${область}»`, начала.length)

  const открывающая = дляСкобок.indexOf('{', начала[0])
  return чистый.slice(открывающая + 1, конецБлока(дляСкобок, открывающая)).trim()
}

/** Место закрывающей скобки для скобки, открытой в `открывающая`. Скобки считаются. */
function конецБлока(текст: string, открывающая: number): number {
  let глубина = 0
  for (let i = открывающая; i < текст.length; i += 1) {
    if (текст[i] === '{') глубина += 1
    if (текст[i] === '}') {
      глубина -= 1
      if (глубина === 0) return i
    }
  }
  сверитьЕдинственность('закрывающих скобок у блока величин', 0)
  return текст.length
}

/**
 * Разметка страницы — то, что стоит между тегами тела.
 *
 * Открывающий тег ищется вместе с возможными признаками (`<body class="…">`). Если тегов тела не
 * нашлось, возвращается страница целиком: тогда сверка с эталоном заведомо не совпадёт и прогон
 * встанет. Отказывать здесь нечем и незачем — молчаливого пропуска не получится по построению.
 */
export function разметкаСтраницы(страница: string): string {
  const открывающий = /<body[^>]*>/i.exec(страница)
  const до = страница.lastIndexOf('</body>')
  if (открывающий === null || до < открывающий.index) return страница
  return страница.slice(открывающий.index + открывающий[0].length, до)
}

/** Готовая страница снимка: разметка состояния плюс вклеенная таблица стилей с пришпиленной темой. */
export function страница(
  имя: string,
  разметка: string,
  css: string,
  величины: { светлая: string; тёмная: string },
  тёмная: boolean,
): string {
  const схема = тёмная ? 'dark' : 'light'
  return (
    `<!doctype html><html lang="ru" style="color-scheme:${схема}"><head><meta charset="utf-8">\n` +
    `<meta name="viewport" content="width=device-width, initial-scale=1"><title>${имя}</title>\n` +
    `<style>${css}\n:root{${тёмная ? величины.тёмная : величины.светлая}}</style></head>` +
    `<body>${разметка}</body></html>\n`
  )
}

/** Готовые страницы. Ничего никуда не пишет. */
export function готовыеСтраницы(
  css: string,
  величины: { светлая: string; тёмная: string },
  состояния: Состояние[],
): Готовая[] {
  const готовые: Готовая[] = []
  for (const состояние of состояния) {
    const разметка = renderToStaticMarkup(состояние.разметка)
    for (const тёмная of [false, true]) {
      готовые.push({
        имя: `${состояние.имя}${тёмная ? '-dark' : ''}.html`,
        состояние: состояние.имя,
        тёмная,
        текст: страница(состояние.имя, разметка, css, величины, тёмная),
        разметка,
      })
    }
  }
  return готовые
}

/**
 * У каждой страницы обязан быть эталон, и разметка обязана с ним совпасть.
 *
 * Эталон — ранее закоммиченная страница из `docs/screens`. Первую такую страницу этот же кусок и
 * положил, и потому называть её «принятой владельцем» было бы шире того, что даёт механизм:
 * механизм отличает «есть в репозитории» от «нет», и только.
 */
export function сверитьГотовые(готовые: Готовая[], эталоны: Map<string, string | null>): void {
  for (const готовая of готовые) {
    const эталон = сверитьЭталон(готовая.имя, эталоны.get(готовая.имя) ?? null)
    сверитьРазметку(готовая.имя, разметкаСтраницы(эталон), готовая.разметка)
  }
}

/** Каждая страница обязана быть свёрстана на запрошенной ширине. */
export function сверитьШирины(замеры: Замер[]): void {
  for (const замер of замеры) сверитьШирину(замер.файл, замер.запрошено, замер.сообщено)
}

/**
 * Светлая и тёмная картинки одного состояния и одного размера обязаны различаться байтами, и хотя
 * бы одна такая пара обязана быть объявлена.
 *
 * Размер входит в ключ нарочно: у обычного экрана есть светлая широкая и светлая узкая, и
 * сравнивать их между собой бессмысленно.
 */
export function сверитьРазличиеКартинок(хеши: ХешКартинки[]): void {
  const по = new Map<string, { светлая?: string; тёмная?: string }>()
  for (const хеш of хеши) {
    const ключ = `${хеш.состояние} ${хеш.размер}`
    const пара = по.get(ключ) ?? {}
    if (хеш.тёмная) пара.тёмная = хеш.хеш
    else пара.светлая = хеш.хеш
    по.set(ключ, пара)
  }

  const полные = [...по].filter(([, п]) => п.светлая !== undefined && п.тёмная !== undefined)
  сверитьНаличиеПар(полные.length)
  for (const [ключ, пара] of полные) сверитьКартинки(ключ, пара.светлая as string, пара.тёмная as string)
}

/** Настоящий заход в браузер. Его отказ — наш отказ, с видом и с советом человеку. */
export const настоящийБраузер: Браузер = (зачем, доводы) => {
  const итог = spawnSync(
    ИСПОЛНИМЫЙ,
    ['--headless', '--disable-gpu', '--hide-scrollbars', '--virtual-time-budget=2000', ...доводы],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  )
  сверитьВыходБраузера(
    зачем,
    итог.error === undefined ? итог.status : null,
    итог.error?.message ?? итог.stderr ?? undefined,
  )
  return итог.stdout ?? ''
}

/**
 * Ширина, о которой сообщает сама страница.
 *
 * Спрашивается у копии во временном каталоге: файл снимка обязан остаться чистым. Неудавшийся
 * замер — свой отказ, а не подставленное число: подставленное число сделало бы сторожа ширины
 * бессмысленным.
 */
function ширинаСтраницы(браузер: Браузер, файл: string, путь: string, ширина: number, высота: number): number {
  const каталог = mkdtempSync(join(tmpdir(), 'снимки-проба-'))
  const проба = join(каталог, 'проба.html')
  writeFileSync(
    проба,
    readFileSync(путь, 'utf8').replace(
      '</body>',
      '<script>document.title=String(document.documentElement.clientWidth)</script></body>',
    ),
  )
  try {
    const вывод = браузер(`замер ширины «${файл}»`, [
      '--dump-dom',
      `--window-size=${ширина},${высота}`,
      `file://${проба}`,
    ])
    const найдено = /<title>(\d+)<\/title>/.exec(вывод)
    сверитьЗамер(файл, найдено !== null)
    return Number((найдено as RegExpExecArray)[1])
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/**
 * Нижний край водопада и ряда по дням, о котором сообщает сама страница, — в пикселях от верха
 * документа, на той же ширине и высоте окна, что у снимка. Спрашивается у копии во временном каталоге,
 * как и ширина. Не нашлось ни одного из двух разделов или страница не ответила — свой отказ «кадр не
 * замерен», а не ноль: ноль прошёл бы сторожа кадра на любой высоте. Свой, а не сторож замера ширины:
 * проверка обязана отличать свой отказ от чужого.
 *
 * **Что здесь не доказывается, и это названо.** Принятые проверки генератора подставляют браузер,
 * который на любой замер отвечает шириной окна: на замер кадра он отвечает не краем разделов. Сторож
 * кадра доказывает своя проверка — `__tests__/screens/frame-guard.test.ts`, с подставным браузером,
 * который отвечает на этот замер отдельно.
 */
function низРазделов(браузер: Браузер, файл: string, путь: string, ширина: number, высота: number): number {
  const каталог = mkdtempSync(join(tmpdir(), 'снимки-кадр-'))
  const проба = join(каталог, 'проба.html')
  writeFileSync(
    проба,
    readFileSync(путь, 'utf8').replace(
      '</body>',
      '<script>var n=0;document.querySelectorAll(".waterfall, .daily").forEach(function(e){' +
        'var b=e.getBoundingClientRect().bottom+window.scrollY;if(b>n)n=b});' +
        'document.title=String(Math.ceil(n))</script></body>',
    ),
  )
  try {
    const вывод = браузер(`замер кадра «${файл}»`, [
      '--dump-dom',
      `--window-size=${ширина},${высота}`,
      `file://${проба}`,
    ])
    const найдено = /<title>(\d+)<\/title>/.exec(вывод)
    сверитьЗамерКадра(файл, найдено !== null && Number(найдено[1]) > 0)
    return Number((найдено as RegExpExecArray)[1])
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Хеш содержимого файла. */
function хешФайла(путь: string): string {
  return createHash('sha256').update(readFileSync(путь)).digest('hex').slice(0, 16)
}

/**
 * Собрать снимки.
 *
 * Всё, что можно подставить, подставляется ради проверки настоящего пути: браузер, каталог
 * эталонов, путь к таблице стилей. Значения по умолчанию — настоящие, и на них работает
 * `npm run screens`.
 */
export function собратьСнимки({
  куда = СНИМКИ,
  эталоныИз = СНИМКИ,
  стили = СТИЛИ,
  толькоПары = false,
  толькоНовый = false,
  браузер = настоящийБраузер,
}: {
  куда?: string
  эталоныИз?: string
  стили?: string
  толькоПары?: boolean
  толькоНовый?: boolean
  браузер?: Браузер
} = {}): { страницы: string[]; картинки: string[] } {
  if (толькоНовый) сверитьПерезапись(куда, existsSync(куда) && readdirSync(куда).length > 0)

  const css = readFileSync(стили, 'utf8')
  const величины = величиныТемы(css)

  const картинки = КАРТИНКИ.filter((к) => !толькоПары || ПАРЫ.has(к.файл))
  const нужны = new Set(картинки.map((к) => к.состояние))
  const готовые = готовыеСтраницы(css, величины, СОСТОЯНИЯ.filter((с) => нужны.has(с.имя)))

  сверитьГотовые(
    готовые,
    new Map(готовые.map((г) => [г.имя, эталон(join(эталоныИз, г.имя))])),
  )

  const временный = mkdtempSync(join(tmpdir(), 'снимки-'))
  try {
    for (const готовая of готовые) writeFileSync(join(временный, готовая.имя), готовая.текст)

    сверитьШирины(
      картинки.map((к) => ({
        файл: к.файл,
        запрошено: к.ширина,
        сообщено: ширинаСтраницы(браузер, к.файл, страницаКартинки(временный, к), к.ширина, к.высота),
      })),
    )

    for (const к of картинки.filter((к) => к.кадр === true)) {
      сверитьКадр(к.файл, низРазделов(браузер, к.файл, страницаКартинки(временный, к), к.ширина, к.высота), к.высота)
    }

    for (const к of картинки) {
      браузер(`снимок «${к.файл}»`, [
        `--screenshot=${join(временный, к.файл)}`,
        `--window-size=${к.ширина},${к.высота}`,
        `file://${страницаКартинки(временный, к)}`,
      ])
      сверитьФайлСнят(к.файл, existsSync(join(временный, к.файл)))
    }

    сверитьРазличиеКартинок(
      картинки.map((к) => ({
        файл: к.файл,
        состояние: к.состояние,
        тёмная: к.тёмная,
        размер: `${к.ширина}×${к.высота}`,
        хеш: хешФайла(join(временный, к.файл)),
      })),
    )

    // Сошлось всё — только теперь на диск, и переносом в два шага.
    //
    // Сперва весь набор ложится рядом под временными именами, и лишь потом переименовывается на
    // свои места. Копирование прямо на место оставляло бы при сбое посередине каталог из части
    // нового набора и части старого, а полупереписанная опись хуже пустой. Остаток риска назван:
    // сбой между переименованиями — окно в доли секунды, и от него защиты нет.
    перенести(временный, куда, [...готовые.map((г) => г.имя), ...картинки.map((к) => к.файл)])
  } finally {
    rmSync(временный, { recursive: true, force: true })
  }

  return { страницы: готовые.map((г) => г.имя), картинки: картинки.map((к) => к.файл) }
}

/**
 * Перенос набора файлов «либо всё, либо ничего».
 *
 * Сперва копии кладутся рядом с местом назначения под временными именами — на том же
 * устройстве, — и только когда легли все, переименовываются. Отказ на копировании не оставляет
 * ни одного файла под настоящим именем: временные снимаются в `finally`.
 */
function перенести(откуда: string, куда: string, имена: string[]): void {
  mkdirSync(куда, { recursive: true })
  const временные = имена.map((имя) => join(куда, `${имя}.новое`))
  try {
    имена.forEach((имя, i) => copyFileSync(join(откуда, имя), временные[i]))
    имена.forEach((имя, i) => renameSync(временные[i], join(куда, имя)))
  } finally {
    for (const путь of временные) rmSync(путь, { force: true })
  }
}

/** Эталон страницы. Отсутствие отдаётся сторожу как есть. */
function эталон(путь: string): string | null {
  return existsSync(путь) ? readFileSync(путь, 'utf8') : null
}

/** Путь к странице, с которой снимается картинка. */
function страницаКартинки(каталог: string, к: Картинка): string {
  return join(каталог, `${к.состояние}${к.тёмная ? '-dark' : ''}.html`)
}
