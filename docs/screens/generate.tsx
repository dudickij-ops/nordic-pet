/**
 * Генератор снимков экрана — кусок S10.
 *
 * **Зачем он в репозитории.** Прежде снимки делались руками, а обе ловушки, на которых они
 * спотыкались, были записаны словами в описи рядом. Владелец потребовал обратного: генератор,
 * который только документирует ловушку, наследует её.
 *
 * **Как он устроен после проверки кода.** Работа разложена на чистых распорядителей и на заходы
 * браузера. Распорядители — `величиныТемы`, `сверитьГотовые`, `сверитьШирины`,
 * `сверитьРазличиеКартинок` — зовут сторожей и не делают больше ничего; до них дотягивается
 * обычный прогон проверок, и потому у каждого сторожа есть слом, который красит и его
 * собственную проверку, и проверку распорядителя. Второе и доказывает, что сторож позван.
 *
 * **Порядок жёсткий: сперва сверить, потом писать.** Прежняя редакция переписывала файл до
 * сравнения, и один упавший прогон стирал собственный эталон. Теперь эталоны читаются заранее,
 * все сверки проходят целиком, и только после этого на диск уходит хоть один байт.
 *
 * **Почему он запускается через vitest, а не `node`.** Снимок обязан показывать **настоящую**
 * разметку приложения, значит генератор ввозит её компоненты. Разметка написана на JSX, а `node`
 * снимает с файлов только типы и JSX не разбирает; кроме того, приложение ввозит себя через
 * `@/…`, а такого разрешения путей у `node` нет. Отдельная настройка `vitest.screens.config.ts`
 * держит генератор в стороне от `npm test`: обычный прогон проверок ничего не пишет.
 *
 * **Чего этот файл не делает.** Он не считает ни одного числа. Числа приходят раскладкой из
 * `fixture.ts`, а раскладка сверяется с принятыми снимками.
 */

