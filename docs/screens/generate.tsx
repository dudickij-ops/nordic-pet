/**
 * Величины светлой и тёмной темы, вынутые из таблицы стилей.
 *
 * **Разбор нарочно мелкий, и вот его граница.** Он выбрасывает комментарии, ищет начало правила
 * `:root {` и считает скобки до его конца. Правил языка стилей он не понимает: ни вложенности,
 * ни условий, ни того, что величина может быть переопределена ниже. Если блоков величин в области
 * окажется не один — он **отказывает**, а не берёт первый попавшийся.
 *
 * Глубже он и не нужен: утверждение, ради которого он написан, звучит как «в тёмный снимок уехали
 * не светлые величины», и на это хватает блока, прочитанного как блок.
 */
export function величиныТемы(css: string): { светлая: string; тёмная: string } {
  const чистый = css.replace(/\/\*[\s\S]*?\*\//g, ' ')
  const тёмнаяОбласть = чистый.indexOf('@media (prefers-color-scheme: dark)')
  сверитьЕдинственностьВеличин('тёмная тема', тёмнаяОбласть < 0 ? 0 : 1)

  const светлая = блокВеличин('светлая тема', чистый.slice(0, тёмнаяОбласть))
  const тёмная = блокВеличин('тёмная тема', чистый.slice(тёмнаяОбласть))
  сверитьВеличиныТем('таблица стилей', светлая, тёмная)

  return { светлая, тёмная }
}

/** Содержимое единственного `:root { … }` в области. Два блока или ни одного — отказ. */
function блокВеличин(область: string, кусок: string): string {
  const начала = [...кусок.matchAll(/(?:^|[\s};])(:root)\s*\{/g)].map((м) => м.index + м[0].indexOf(':root'))
  сверитьЕдинственностьВеличин(область, начала.length)

  const открывающая = кусок.indexOf('{', начала[0])
  let глубина = 0
  for (let i = открывающая; i < кусок.length; i += 1) {
    if (кусок[i] === '{') глубина += 1
    if (кусок[i] === '}') {
      глубина -= 1
      if (глубина === 0) return кусок.slice(открывающая + 1, i).trim()
    }
  }
  сверитьЕдинственностьВеличин(область, 0)
  return ''
}

/**
 * Разметка страницы — то, что стоит между `<body>` и `</body>`.
 *
 * Если разметок не нашлось, возвращается страница целиком: тогда сверка с эталоном заведомо не
 * совпадёт и прогон встанет. Отказывать наружу здесь нечем и незачем — молчаливого пропуска не
 * получится по построению.
 */
export function разметкаСтраницы(страница: string): string {
  const от = страница.indexOf('<body>')
  const до = страница.lastIndexOf('</body>')
  return от < 0 || до < от ? страница : страница.slice(от + '<body>'.length, до)
}

/** Готовая страница снимка: разметка состояния плюс вклеенная таблица стилей с пришпиленной темой. */
export function страница(
  имя: string,
  разметка: string,
  css: string,
  величины: { светлая: string; тёмная: string },
  тёмная: boolean,
): string {
  const схема = тёмная ? 'dark' : 'light'
  return (
    `<!doctype html><html lang="ru" style="color-scheme:${схема}"><head><meta charset="utf-8">\n` +
    `<meta name="viewport" content="width=device-width, initial-scale=1"><title>${имя}</title>\n` +
    `<style>${css}\n:root{${тёмная ? величины.тёмная : величины.светлая}}</style></head>` +
    `<body>${разметка}</body></html>\n`
  )
}

/** Десять готовых страниц (или две, когда нужны только пары). Ничего никуда не пишет. */
export function готовыеСтраницы(
  css: string,
  величины: { светлая: string; тёмная: string },
  состояния: Состояние[],
): Готовая[] {
  const готовые: Готовая[] = []
  for (const состояние of состояния) {
    const разметка = renderToStaticMarkup(состояние.разметка)
    for (const тёмная of [false, true]) {
      const имя = `${состояние.имя}${тёмная ? '-dark' : ''}.html`
      готовые.push({
        имя,
        состояние: состояние.имя,
        тёмная,
        текст: страница(состояние.имя, разметка, css, величины, тёмная),
        разметка,
      })
    }
  }
  return готовые
}

/**
 * Распорядитель сверки страниц: у каждой обязан быть эталон, и разметка обязана с ним совпасть.
 *
 * Ветки «эталона нет — пропустим» здесь нет и быть не может: отсутствие эталона отдаётся
 * сторожу, а сторож отказывает.
 */
export function сверитьГотовые(готовые: Готовая[], эталоны: Map<string, string | null>): void {
  for (const готовая of готовые) {
    const эталон = сверитьЭталон(готовая.имя, эталоны.get(готовая.имя) ?? null)
    сверитьРазметку(готовая.имя, разметкаСтраницы(эталон), готовая.разметка)
  }
}

/** Распорядитель сверки ширин: каждая страница обязана быть свёрстана на запрошенной ширине. */
export function сверитьШирины(замеры: Замер[]): void {
  for (const замер of замеры) сверитьШирину(замер.файл, замер.запрошено, замер.сообщено)
}

/**
 * Распорядитель сверки картинок: светлая и тёмная одного состояния и одного размера обязаны
 * различаться байтами.
 *
 * Размер входит в ключ нарочно: у обычного экрана есть и широкая светлая, и узкая светлая, и
 * сравнивать их между собой бессмысленно — они и должны различаться по другой причине.
 */
export function сверитьРазличиеКартинок(хеши: ХешКартинки[]): void {
  const по = new Map<string, { светлая?: string; тёмная?: string }>()
  for (const хеш of хеши) {
    const ключ = `${хеш.состояние} ${хеш.размер}`
    const пара = по.get(ключ) ?? {}
    if (хеш.тёмная) пара.тёмная = хеш.хеш
    else пара.светлая = хеш.хеш
    по.set(ключ, пара)
  }

  for (const [ключ, пара] of по) {
    if (пара.светлая === undefined || пара.тёмная === undefined) continue
    сверитьКартинки(ключ, пара.светлая, пара.тёмная)
  }
}

/** Один заход браузера. Его отказ — наш отказ, с видом и с советом человеку. */
function браузер(зачем: string, доводы: string[]): string {
  const итог = spawnSync(
    БРАУЗЕР,
    ['--headless', '--disable-gpu', '--hide-scrollbars', '--virtual-time-budget=2000', ...доводы],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  )
  сверитьВыходБраузера(
    зачем,
    итог.error === undefined ? итог.status : null,
    итог.error?.message ?? итог.stderr ?? undefined,
  )
  return итог.stdout ?? ''
}

/**
 * Ширина, о которой сообщает сама страница.
 *
 * Спрашивается у копии во временном каталоге, а не у файла снимка: снимок в репозитории обязан
 * остаться чистым, а брошенный посреди работы прогон — не оставить мусора в каталоге снимков.
 */
function ширинаСтраницы(путь: string, ширина: number, высота: number): number {
  const каталог = mkdtempSync(join(tmpdir(), 'снимки-'))
  const проба = join(каталог, 'проба.html')
  const текст = readFileSync(путь, 'utf8').replace(
    '</body>',
    '<script>document.title=String(document.documentElement.clientWidth)</script></body>',
  )
  writeFileSync(проба, текст)
  try {
    const вывод = браузер(`замер ширины «${путь}»`, [
      '--dump-dom',
      `--window-size=${ширина},${высота}`,
      `file://${проба}`,
    ])
    const найдено = /<title>(\d+)<\/title>/.exec(вывод)
    if (найдено === null) return -1
    return Number(найдено[1])
  } finally {
    rmSync(каталог, { recursive: true, force: true })
  }
}

/** Хеш содержимого файла. */
function хешФайла(путь: string): string {
  return createHash('sha256').update(readFileSync(путь)).digest('hex').slice(0, 16)
}

/** Эталон страницы — принятый снимок из `docs/screens`. Отсутствие отдаётся сторожу как есть. */
function эталон(имя: string): string | null {
  const путь = join(СНИМКИ, имя)
  return existsSync(путь) ? readFileSync(путь, 'utf8') : null
}

/**
 * Собрать снимки.
 *
 * `куда` — каталог; `толькоПары` оставляет три картинки, по которым владелец сравнивает «до» и
 * «после», и две страницы, из которых они сняты. Эталоны в обоих случаях берутся из
 * `docs/screens`: эталон — это принятое, а не то, что случайно лежит в каталоге назначения.
 */
export function собратьСнимки({ куда, толькоПары = false }: { куда?: string; толькоПары?: boolean } = {}): {
  страницы: string[]
  картинки: string[]
} {
  const каталог = куда ?? СНИМКИ
  const css = readFileSync(СТИЛИ, 'utf8')
  const величины = величиныТемы(css)

  const картинки = КАРТИНКИ.filter((к) => !толькоПары || ПАРЫ.has(к.файл))
  const нужны = new Set(картинки.map((к) => к.состояние))
  const готовые = готовыеСтраницы(css, величины, СОСТОЯНИЯ.filter((с) => нужны.has(с.имя)))

  сверитьГотовые(готовые, new Map(готовые.map((г) => [г.имя, эталон(г.имя)])))

  mkdirSync(каталог, { recursive: true })
  for (const готовая of готовые) writeFileSync(join(каталог, готовая.имя), готовая.текст)

  сверитьШирины(
    картинки.map((к) => ({
      файл: к.файл,
      запрошено: к.ширина,
      сообщено: ширинаСтраницы(страницаКартинки(каталог, к), к.ширина, к.высота),
    })),
  )

  for (const к of картинки) {
    браузер(`снимок «${к.файл}»`, [
      `--screenshot=${join(каталог, к.файл)}`,
      `--window-size=${к.ширина},${к.высота}`,
      `file://${страницаКартинки(каталог, к)}`,
    ])
  }

  сверитьРазличиеКартинок(
    картинки.map((к) => ({
      файл: к.файл,
      состояние: к.состояние,
      тёмная: к.тёмная,
      размер: `${к.ширина}×${к.высота}`,
      хеш: хешФайла(join(каталог, к.файл)),
    })),
  )

  return { страницы: готовые.map((г) => г.имя), картинки: картинки.map((к) => к.файл) }
}

/** Путь к странице, с которой снимается картинка. */
function страницаКартинки(каталог: string, к: Картинка): string {
  return join(каталог, `${к.состояние}${к.тёмная ? '-dark' : ''}.html`)
}
