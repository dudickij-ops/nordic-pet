import { expect, test, vi } from 'vitest'

/**
 * Полный набор снимков — двадцать страниц и двадцать восемь картинок: каждое состояние в обеих темах.
 *
 * Запускается отдельной командой (`npm run screens`) и отдельной настройкой vitest: обычный
 * прогон проверок (`npm test`) этот файл не собирает и в репозиторий ничего не пишет.
 *
 * `next/cache` подменяется по той же причине, что и в принятой проверке вида устаревших чисел:
 * панель кнопки ввозит серверное действие, а оно — `revalidatePath`, которого вне Next нет.
 * На снимок это не влияет: действие не зовётся, рисуется только разметка.
 */
vi.mock('next/cache', () => ({ revalidatePath: vi.fn() }))

const { собратьСнимки } = await import('./generate.tsx')

test('снимки собраны: двадцать страниц и двадцать восемь картинок', () => {
  const { страницы, картинки } = собратьСнимки()

  expect(страницы).toHaveLength(20)
  expect(картинки).toHaveLength(28)
}, 180_000)
