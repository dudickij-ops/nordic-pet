/**
 * Отказы генератора снимков — кусок S10.
 *
 * **Как этот файл получился таким.** Первая редакция держала три отказа, и два из них на
 * настоящем пути молчали. Сверка тем сравнивала файлы целиком, а в каждый файл вшита пометка
 * темы, — значит светлый и тёмный отличались **всегда**, и сверка не могла покраснеть ни на
 * одном входе. Сверка текста зналась только тогда, когда файл уже лежал на диске, и файл
 * переписывался **до** сравнения: один упавший прогон стирал собственный эталон, а первый прогон
 * в новый каталог не сверялся вовсе. Оба нашла проверка кода.
 *
 * Владелец назвал это вторым кругом одного класса дефекта за кусок и потребовал менять
 * устройство, а не добавлять сторожа. Устройство теперь такое: **сторожа зовут чистые
 * распорядители**, до которых дотягивается обычный прогон проверок, и **у каждого сторожа есть
 * свой слом**. Слом выедает тело сторожа; краснеют и его собственная проверка, и проверка
 * распорядителя — второе и доказывает, что сторож вправду позван, а не просто написан.
 *
 * **Ветки «пропустить» нет ни у одного отказа.** Ни переменной среды, ни флага, ни «а если файла
 * нет». Отсутствие эталона — тоже отказ: сторож, которого можно обойти, не сторож.
 *
 * Файл держится **без единого ввоза** нарочно: его проверки не тащат за собой ни разметку, ни
 * слой метрик, ни драйвер базы.
 */

/** Вид отказа. По нему проверка отличает наш отказ от любой другой ошибки по дороге. */
export type ВидОтказаСнимка =
  | 'нет эталона'
  | 'разметка разошлась'
  | 'величины не разобраны'
  | 'темы совпали'
  | 'ширина не та'
  | 'замер не удался'
  | 'картинки совпали'
  | 'пар тем не объявлено'
  | 'браузер отказал'

/**
 * Отказ генератора снимков.
 *
 * Вид лежит отдельным полем, а не читается из текста сообщения: проверка, сверяющая текст,
 * покраснела бы от правки формулировки и позеленела бы от чужой ошибки с похожими словами.
 */
export class ОтказСнимка extends Error {
  readonly вид: ВидОтказаСнимка

  constructor(вид: ВидОтказаСнимка, message: string) {
    super(message)
    this.name = 'ОтказСнимка'
    this.вид = вид
  }
}

/**
 * Видимый текст страницы, по порядку.
 *
 * Живёт здесь, а не в генераторе, потому что нужен отказу: когда разметка разошлась, человеку
 * показывается первая разошедшаяся **видимая** строка — по ней понятно, что случилось на экране.
 *
 * Отличается от переписи экрана (`__tests__/screen/census.test.tsx`) одним: сначала выбрасываются
 * `<script>` и `<style>` целиком. Перепись работает с разметкой компонента, где ни того ни
 * другого нет; в файле снимка таблица стилей вклеена внутрь.
 *
 * **Сверкой она не является.** Видимый текст слеп к числам, живущим в атрибутах: доля честности
 * уходит в полосу величиной `--share`, месяц — адресом ссылки, устаревание — признаком `data-`.
 * Поэтому разметка сверяется побайтно, а видимый текст служит только тем, чтобы отказ был
 * читаемым.
 */
export function видимыйТекст(страница: string): string[] {
  return страница
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<[^>]*>/g, '\n')
    .split('\n')
    .map((кусок) => разэкранировать(кусок).trim())
    .filter((кусок) => кусок !== '')
}

/** Обратный перевод шести сущностей, которые ставит отрисовка. Больше в этих файлах не бывает. */
function разэкранировать(кусок: string): string {
  return кусок
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#x27;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
}

/**
 * Эталон обязан быть.
 *
 * Эталон — это **принятая** страница снимка, уже лежащая в `docs/screens/`. Отсутствие эталона
 * не значит «сверять нечего»: оно значит, что снимок появился мимо приёмки. Прежняя редакция на
 * этом месте молча пропускала сверку, и три пары «до» вышли непроверенными.
 */
export function сверитьЭталон(снимок: string, эталон: string | null): string {
  if (эталон !== null) return эталон

  throw new ОтказСнимка(
    'нет эталона',
    `снимок «${снимок}»: эталона нет в docs/screens. Эталон — это принятая владельцем страница, ` +
      'и генератор их не заводит: он умеет только пересобирать принятое. Если состояние новое — ' +
      'его надо сперва внести в опись и показать владельцу, а если имя файла изменилось — вернуть ' +
      'прежнее.',
  )
}

/**
 * Разметка пересобранной страницы обязана побайтно совпасть с эталоном.
 *
 * Это главный сторож куска: оформление меняет только то, **как** показано. Разметку кусок не
 * открывает вовсе, значит тело страницы обязано совпасть до символа — вместе с атрибутами.
 *
 * Прежняя редакция сверяла только видимый текст, и этого было мало: доля честности уходит в
 * полосу величиной `--share`, месяц — адресом ссылки, устаревание — признаком `data-stale`.
 * Правка, переносящая число из текста в геометрию, проходила ту сверку насквозь.
 */
export function сверитьРазметку(снимок: string, было: string, стало: string): void {
  if (было === стало) return

  const текстБыло = видимыйТекст(было)
  const текстСтало = видимыйТекст(стало)
  const строка = перваяРазная(текстБыло, текстСтало)

  const место = первыйРазныйСимвол(было, стало)
  const подробность =
    строка === null
      ? 'Видимый текст тот же — разошлись атрибуты или порядок тегов. ' +
        `Первое расхождение на символе ${место}: было ${кусок(было, место)}, ` +
        `стало ${кусок(стало, место)}.`
      : `Первая разошедшаяся видимая строка — ${строка.номер}: было ${показать(строка.было)}, ` +
        `стало ${показать(строка.стало)}.`

  throw new ОтказСнимка(
    'разметка разошлась',
    `снимок «${снимок}»: разметка не совпала с эталоном. ${подробность} ` +
      'Кусок оформления не имеет права двигать показанное. Если разметка изменена сознательно — ' +
      'это находка к владельцу, а не строка, которую поправляют в снимке.',
  )
}

/**
 * Величины светлой и тёмной темы обязаны различаться.
 *
 * Сравниваются **наборы величин**, а не файлы: пометка темы вшита в каждый файл, и файлы
 * различаются всегда. Ломается здесь ровно одно — подстановка величин, — и сторож смотрит именно
 * на неё.
 */
export function сверитьВеличиныТем(где: string, светлые: string, тёмные: string): void {
  if (светлые !== тёмные) return

  throw new ОтказСнимка(
    'темы совпали',
    `${где}: величины светлой и тёмной темы вышли одинаковыми. Тема снимка задаётся дописыванием ` +
      'набора величин в конец вклеенной таблицы стилей, и одинаковые наборы значат, что тёмный ' +
      'снимок выйдет светлым. Разбор берёт величины светлой темы вне блока ' +
      '`@media (prefers-color-scheme: dark)`, а тёмной — внутри него; одинаковые наборы значат, ' +
      'что внутри блока либо пусто, либо те же значения, что снаружи.',
  )
}

/**
 * Того, что разбор ищет в таблице стилей, обязано найтись ровно по одному.
 *
 * **Граница разбора названа здесь, потому что здесь её и прочтут.** Разбор умеет ровно две вещи:
 * выбросить комментарии и прочитать блок `:root { … }` как блок. Правил языка стилей он не
 * понимает вовсе, и величины, объявленные **не** на `:root`, он не видит совсем — ни на `html`,
 * ни на классе, ни во вложенном правиле. Два блока вместо одного — не «возьмём первый», а отказ:
 * молча взятая половина величин дала бы снимок, у которого часть цветов из другой темы.
 */
export function сверитьЕдинственность(что: string, сколько: number): void {
  if (сколько === 1) return

  throw new ОтказСнимка(
    'величины не разобраны',
    `${что}: найдено ${сколько}, а нужно ровно одно. Разбор в генераторе намеренно мелкий — он ` +
      'выбрасывает комментарии и читает блок `:root { … }` как блок, а правил языка стилей не ' +
      'понимает: величины, объявленные не на `:root`, он не видит вовсе. Держите величины каждой ' +
      'темы одним блоком `:root` внутри своей области, либо научите разбор — но тогда напишите в ' +
      'нём прямо, чего он по-прежнему не понимает.',
  )
}

/**
 * Страница обязана быть свёрстана на той ширине, которую попросили.
 *
 * Ширину сообщает сама страница (`clientWidth`), а не браузер: браузер отвечает тем, что у него
 * попросили, и потому его ответ ничего не доказывает.
 */
export function сверитьШирину(снимок: string, запрошено: number, сообщено: number): void {
  if (запрошено === сообщено) return

  throw new ОтказСнимка(
    'ширина не та',
    `снимок «${снимок}»: запрошено ${запрошено} пикселей, а страница свёрстана при ${сообщено}. ` +
      'Безголовый браузер на этой машине не открывает окно уже 500 пикселей: на просьбу о ' +
      'меньшем он верстает при 500 и обрезает картинку до запрошенной ширины. Просите 500 или ' +
      'шире, а поведение на 375 и 390 пикселях проверяйте замером в настоящем браузере, а не ' +
      'снимком.',
  )
}

/**
 * Светлая и тёмная картинки одного состояния обязаны различаться байтами.
 *
 * Это тот самый случай, ради которого сторож заводился: однажды «светлый» и «тёмный» снимки
 * вышли **побайтно одинаковыми** — тема машины подменила светлый тёмным. Ловушка случилась
 * именно с картинками, и потому сравниваются они, а не только величины.
 */
export function сверитьКартинки(состояние: string, хешСветлой: string, хешТёмной: string): void {
  if (хешСветлой !== хешТёмной) return

  throw new ОтказСнимка(
    'картинки совпали',
    `состояние «${состояние}»: светлая и тёмная картинки вышли побайтно одинаковыми ` +
      `(${хешСветлой}). Так уже было однажды: тема машины подменила светлый снимок тёмным. ` +
      'Проверьте, что в тёмную страницу вправду уехали тёмные величины, и что браузер берёт ' +
      'именно её файл, а не светлый.',
  )
}

/**
 * Замер ширины обязан удаться.
 *
 * Прежде на неудавшемся замере возвращалось `-1`, и оно уезжало в сторожа ширины: человек читал
 * «страница свёрстана при -1» и совет про окно уже 500 пикселей — причину, которой нет, и
 * действие, которое не поможет. Неудавшийся замер — своя беда, и говорить о ней надо своими
 * словами.
 */
export function сверитьЗамер(снимок: string, получилось: boolean): void {
  if (получилось) return

  throw new ОтказСнимка(
    'замер не удался',
    `снимок «${снимок}»: страница не сообщила свою ширину. Ширина снимается отдельным заходом ` +
      'браузера: во временную копию страницы дописывается строка, кладущая `clientWidth` в ' +
      'заголовок окна, и заголовок вычитывается из выгруженной разметки. Заголовка в выгрузке не ' +
      'оказалось — смотрите, работает ли в этом режиме браузера дописанная строка и хватает ли ' +
      'ей отведённого времени. Ширину на глаз подставлять нельзя: тогда сторож ширины перестанет ' +
      'что-либо значить.',
  )
}

/**
 * Пар «светлая — тёмная» обязана быть хотя бы одна.
 *
 * Без этого сторож картинок молчит на пустом месте: убери из описи тёмную картинку — и сравнивать
 * станет нечего, отказа не будет, а ловушка «тема машины подменила светлый снимок тёмным»
 * перестанет сторожиться. Пустой обход — та же ветка «пропустить», только включаемая составом
 * данных, а не переменной среды.
 */
export function сверитьНаличиеПар(сколько: number): void {
  if (сколько > 0) return

  throw new ОтказСнимка(
    'пар тем не объявлено',
    'в описи картинок нет ни одной пары «светлая — тёмная» одного состояния и одного размера. ' +
      'Сравнивать нечего, и значит ловушка с подменённой темой не сторожится ничем. Верните в ' +
      'опись тёмную картинку к какой-нибудь светлой — иначе сторож картинок держится на честном ' +
      'слове.',
  )
}

/**
 * Браузер обязан отработать. Его отказ — наш отказ, а не чужая ошибка по дороге.
 *
 * Без этого проверка, ловящая «наш отказ», зазеленела бы от ненайденного браузера: прогон падал
 * бы обычной ошибкой, и никто бы не сказал человеку, что делать.
 */
export function сверитьВыходБраузера(зачем: string, код: number | null, беда?: string): void {
  if (код === 0) return

  const причина = беда === undefined ? '' : ` Браузер сказал: ${беда.slice(0, 300)}`
  throw new ОтказСнимка(
    'браузер отказал',
    `${зачем}: браузер вернул ${код === null ? 'ничего' : код}.${причина} Снимки делаются Chrome ` +
      'по вшитому пути `/Applications/Google Chrome.app/Contents/MacOS/Google Chrome`. Поставьте ' +
      'Chrome туда или поправьте путь в генераторе — другого браузера у снимков нет.',
  )
}

/** Номер и содержимое первой разошедшейся видимой строки, либо `null`, если текст тот же. */
function перваяРазная(
  было: string[],
  стало: string[],
): { номер: number; было?: string; стало?: string } | null {
  const предел = Math.max(было.length, стало.length)
  for (let i = 0; i < предел; i += 1) {
    if (было[i] !== стало[i]) return { номер: i + 1, было: было[i], стало: стало[i] }
  }
  return null
}

/** Номер первого разошедшегося символа — когда видимый текст тот же, а разметка нет. */
function первыйРазныйСимвол(было: string, стало: string): number {
  const предел = Math.min(было.length, стало.length)
  for (let i = 0; i < предел; i += 1) if (было[i] !== стало[i]) return i + 1
  return предел + 1
}

/**
 * Кусок разметки вокруг расхождения — чтобы человеку не искать глазами.
 *
 * Двадцать символов **до** места расхождения берутся нарочно: расхождение почти всегда приходится
 * на значение, а понять, что случилось, можно только по имени рядом — `--share`, `data-stale`,
 * `href`. Кусок, начатый ровно с расхождения, показывает голое значение и не говорит ничего.
 */
function кусок(текст: string, место: number): string {
  const от = Math.max(0, место - 21)
  return место - 1 >= текст.length ? 'ничего' : `«${текст.slice(от, от + 60)}»`
}

/** Строка в кавычках или слово «ничего», когда строки на этом месте нет вовсе. */
function показать(строка: string | undefined): string {
  return строка === undefined ? 'ничего' : `«${строка}»`
}
