/**
 * Три отказа генератора снимков — кусок S10.
 *
 * Два из них закрывают ловушки, на которых снимки уже спотыкались; третий сторожит главное
 * обязательство куска — что оформление не сдвинуло на экране ни одной подписи и ни одного числа.
 *
 * Снимки этого проекта уже дважды выходили правдоподобными и неверными. Первый раз тёмная тема
 * машины подменила «светлый» снимок тёмным, и два файла вышли побайтно одинаковыми; глазом это
 * не ловится — оба выглядят правильно. Второй раз безголовый браузер не открыл окно уже
 * 500 пикселей: на просьбу о 390 он сверстал при 500 и обрезал картинку, и на снимке появился
 * дефект, которого в коде нет. Оба раза ошибку нашли измерением, а не взглядом, и оба раза её
 * записали словами в опись рядом со снимками.
 *
 * Слов оказалось мало: **генератор, который только документирует ловушку, наследует её**. Оба
 * случая теперь ловятся здесь, и ловятся отказом — ненулевым кодом возврата, а не строкой в
 * выводе, которую не читает тот, кто смотрит на картинку.
 *
 * **Ветки «пропустить» здесь нет ни у одного отказа.** Ни переменной среды, ни флага, ни
 * условия «а на этой машине можно»: сторож, которого можно отключить, — не сторож. Если
 * когда-нибудь понадобится снять один из них, снимать придётся код, и это будет видно в диффе.
 *
 * Файл держится **без единого ввоза** нарочно: его проверки не должны тащить за собой ни
 * разметку, ни слой метрик, ни драйвер базы.
 */

/** Вид отказа. По нему проверка отличает наш отказ от любой другой ошибки по дороге. */
export type ВидОтказаСнимка = 'темы совпали' | 'ширина не та' | 'текст разошёлся'

/**
 * Отказ генератора снимков.
 *
 * Вид лежит отдельным полем, а не читается из текста сообщения: проверка, сверяющая текст,
 * покраснела бы от правки формулировки и позеленела бы от чужой ошибки с похожими словами.
 */
export class ОтказСнимка extends Error {
  readonly вид: ВидОтказаСнимка

  constructor(вид: ВидОтказаСнимка, message: string) {
    super(message)
    this.name = 'ОтказСнимка'
    this.вид = вид
  }
}

/**
 * Светлый и тёмный снимок одного состояния обязаны различаться.
 *
 * Тема в этом генераторе задаётся **в самом файле снимка** — величины темы дописываются в конец
 * вклеенной таблицы стилей, — и потому настройка машины подменить её не может по построению.
 * Этот отказ сторожит другое: что подстановка величин вообще сработала. Совпавшие хеши значат,
 * что в оба файла уехал один и тот же набор величин.
 */
export function сверитьТемы(состояние: string, хешСветлого: string, хешТёмного: string): void {
  if (хешСветлого !== хешТёмного) return

  throw new ОтказСнимка(
    'темы совпали',
    `состояние «${состояние}»: светлый и тёмный снимки вышли побайтно одинаковыми (${хешСветлого}). ` +
      'Тема задаётся в самом файле снимка, а не настройкой машины, — значит не сработала ' +
      'подстановка величин. Смотрите, как генератор вынимает величины тёмной темы из ' +
      '`app/globals.css` (блок `@media (prefers-color-scheme: dark)`), а не на браузер и не на ' +
      'настройки системы.',
  )
}

/**
 * Страница обязана быть свёрстана на той ширине, которую попросили.
 *
 * Ширину сообщает сама страница (`clientWidth`), а не браузер: браузер отвечает тем, что у него
 * попросили, и потому его ответ ничего не доказывает.
 */
export function сверитьШирину(снимок: string, запрошено: number, сообщено: number): void {
  if (запрошено === сообщено) return

  throw new ОтказСнимка(
    'ширина не та',
    `снимок «${снимок}»: запрошено ${запрошено} пикселей, а страница свёрстана при ${сообщено}. ` +
      'Безголовый браузер на этой машине не открывает окно уже 500 пикселей: на просьбу о ' +
      'меньшем он верстает при 500 и обрезает картинку до запрошенной ширины. Просите 500 или ' +
      'шире, а поведение на 375 и 390 пикселях проверяйте замером в настоящем браузере, а не ' +
      'снимком.',
  )
}

/**
 * Видимый текст пересобранного снимка обязан совпасть с тем, что был в нём до пересборки.
 *
 * Это главный сторож куска на стороне снимков: кусок меняет только то, **как** показано.
 * Стоило одной подписи, одному числу или одной строке съехать — и сравнение краснеет.
 *
 * Сверяются **только страницы**: у файла `.png` видимого текста нет, и картинка этим не
 * проверяется вовсе. Картинку смотрит глаз по паре «до / после», и больше ничто.
 */
export function сверитьТекст(снимок: string, было: string[], стало: string[]): void {
  if (было.length === стало.length && было.every((строка, i) => строка === стало[i])) return

  const первое = поискПервогоРасхождения(было, стало)
  throw new ОтказСнимка(
    'текст разошёлся',
    `снимок «${снимок}»: видимый текст изменился. Было строк ${было.length}, стало ${стало.length}. ` +
      `Первое расхождение на строке ${первое.номер}: было ${показать(первое.было)}, ` +
      `стало ${показать(первое.стало)}. ` +
      'Кусок оформления не имеет права двигать показанное. Если текст изменён сознательно — ' +
      'это находка к владельцу, а не строка, которую поправляют в снимке.',
  )
}

/** Номер и содержимое первой разошедшейся строки — чтобы человеку не искать глазами. */
function поискПервогоРасхождения(
  было: string[],
  стало: string[],
): { номер: number; было?: string; стало?: string } {
  const предел = Math.max(было.length, стало.length)
  for (let i = 0; i < предел; i += 1) {
    if (было[i] !== стало[i]) return { номер: i + 1, было: было[i], стало: стало[i] }
  }
  return { номер: предел }
}

/** Строка в кавычках или слово «ничего», когда строки на этом месте нет вовсе. */
function показать(строка: string | undefined): string {
  return строка === undefined ? 'ничего' : `«${строка}»`
}
