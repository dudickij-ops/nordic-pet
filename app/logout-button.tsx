import { logoutAction } from './logout-action'

/**
 * Кнопка выхода — задача 3 куска S8.
 *
 * Форма, а не ссылка: выход меняет состояние (убирает cookie), а по ссылке ходят и предзагрузчики
 * браузера.
 *
 * Вид — кусок S9. Свою форму эта кнопка держит нарочно, и обёртки вокруг неё на странице отчёта
 * нет: формы в HTML не вкладываются друг в друга, а страница отчёта уже завёрнута в форму кнопки
 * «Обновить данные». Поэтому верхняя полоса собирается стилями по классу самой формы, а не
 * обёрткой в разметке страницы, — заодно цитата слома прошлого куска остаётся нетронутой.
 *
 * Класс висит на форме, а не на кнопке, и содержимое кнопки — по-прежнему одно слово без
 * единого вложенного тега: принятая проверка прошлого куска утверждает форму этой разметки
 * целиком, вплоть до того, что между открывающим тегом кнопки и словом ничего нет.
 */
export function LogoutButton() {
  return (
    <form action={logoutAction} className="logout">
      <button type="submit">Выйти</button>
    </form>
  )
}
