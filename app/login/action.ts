'use server'

import { cookies, headers } from 'next/headers'
import { redirect } from 'next/navigation'

import { адресПосетителя, войтиЧерезЗамок, счётВБазе } from '@/lib/auth/attempts'
import { type ИсходВхода } from '@/lib/auth/login'

/**
 * Серверное действие входа — тонкая обёртка, тем же приёмом, что `app/refresh-action.ts`.
 *
 * Здесь только четыре вещи: достать два поля формы, узнать адрес посетителя, отдать настоящее
 * хранилище cookie и настоящий счёт попыток, и увести вошедшего на отчёт. Сверка, замок на
 * подбор, тексты отказов и настройки cookie живут в `lib/auth/`; ни одного решения эта обёртка
 * не принимает.
 *
 * Действие зовётся как `action` формы в `useActionState`: React подставляет туда
 * `(прежнийИсход, formData)`. Прежний исход здесь не нужен — каждая попытка сама по себе.
 *
 * Пароль живёт ровно до конца этой функции: он не пишется в журнал, не кладётся в cookie и
 * не возвращается наружу ни в каком виде — наружу уходит либо переход на отчёт, либо текст
 * отказа.
 *
 * Соединение счёта закрывается в `finally`: `redirect` работает броском своей ошибки перехода,
 * и без `finally` удачный вход оставлял бы соединение открытым.
 */
export async function loginAction(_прежний: ИсходВхода, форма: FormData): Promise<ИсходВхода> {
  const хранилище = await cookies()
  const заголовки = await headers()
  const счёт = await счётВБазе()

  let исход: ИсходВхода
  try {
    исход = await войтиЧерезЗамок(строкой(форма.get('login')), строкой(форма.get('password')), {
      счёт,
      env: process.env,
      now: Date.now(),
      адрес: адресПосетителя(заголовки.get('x-forwarded-for')),
      cookies: {
        set: (имя, значение, настройки) => {
          хранилище.set(имя, значение, настройки)
        },
      },
    })
  } finally {
    await счёт.закрыть()
  }

  // `redirect` бросает свою ошибку перехода — так она и работает; поэтому она стоит после
  // выдачи cookie, а не до, и в `try` её заворачивать нельзя.
  if (исход.ok) redirect('/')

  return исход
}

/** Поле формы может прийти файлом или не прийти вовсе. И то и другое — не пароль. */
function строкой(поле: FormDataEntryValue | null): string {
  return typeof поле === 'string' ? поле : ''
}
