'use server'

import { cookies } from 'next/headers'
import { redirect } from 'next/navigation'

import { SESSION_COOKIE } from '@/lib/auth/session'

/**
 * Выход — задача 3 куска S8.
 *
 * Тонкая обёртка, как и вход: удалить cookie и увести на страницу входа. Ни одного решения
 * здесь нет.
 *
 * Почему это серверное действие, а не ссылка. Справочник Next говорит про удаление cookie
 * прямо: метод `.delete` «can only be called: In a Server Function or Route Handler», и там же
 * — «Setting cookies is not supported during Server Component rendering». Значит убрать cookie
 * можно только отсюда.
 *
 * **Что этот выход делает и чего не делает.** Он убирает cookie **из браузера** того, кто
 * нажал. Украденная копия остаётся годной до конца своих двенадцати часов: наша cookie
 * подписана и не опирается на хранимое состояние, а значит отзыву по одной штуке не поддаётся.
 * Отозвать всё разом можно только сменой секрета подписи — это выбьет и всех остальных.
 * Хранимые сессии закрыли бы это, и в кусок они не входят: решение, а не недосмотр.
 *
 * Сторожа здесь нет нарочно, и это не забывчивость. Выход ничего не отдаёт и ничего не пишет:
 * он убирает cookie у того, кто пришёл. Постороннему, у которого cookie нет, удалять нечего, и
 * ответ ему тот же самый — страница входа.
 */
export async function logoutAction(): Promise<never> {
  const хранилище = await cookies()
  хранилище.delete(SESSION_COOKIE)
  redirect('/login')
}
