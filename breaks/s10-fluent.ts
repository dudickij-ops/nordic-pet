/**
 * Список сломов куска S10 — оформление экрана по Fluent 2.
 *
 * Своих сломов у куска мало нарочно. Кусок меняет только то, **как** показано, и разметку не
 * открывает вовсе: переводов якорей прежних кусков в нём ноль, и доказывается это не сломом, а
 * пустым диффом по разметке — слом, которого не было, доказывать нечем.
 *
 * **Почему сломов пятнадцать, а не два.** Два круга проверки кода подряд нашли один и тот же класс
 * дефекта: сторож написан, а на настоящем пути молчит. Сперва сторожей звали из мест, которых не
 * касалась ни одна проверка; потом сторожей вынесли в распорядителей и накрыли проверками
 * распорядителей — а вызов самих распорядителей из `собратьСнимки` снова остался недоказанным.
 * Беда не двигалась, двигалась граница проверенного.
 *
 * Владелец выставил условие приёмки механически: **в генераторе не остаётся ни одного сторожа без
 * слома.** Сторожей генератора одиннадцать — значит и сломов на него одиннадцать; плюс четыре на проверку чисел таблицы стилей.
 *
 * **Что доказывает каждый слом.** Он выедает тело сторожа. Краснеет его собственная проверка
 * (`__tests__/screens/guards.test.ts`) — про то, что сторож умеет отказывать, — и, у девяти из
 * одиннадцати, краснеет проверка настоящего пути (`__tests__/screens/generator.test.ts`), которая
 * гоняет `собратьСнимки` целиком на подставном браузере. Вторая и доказывает, что сторож позван
 * **оттуда, откуда его зовут в работе**.
 *
 * **Два сторожа этой второй проверки не имеют, и это названо здесь, а не в общей фразе.**
 * `сверитьВыходБраузера` зовётся внутри захода в настоящий Chrome. `сверитьНаличиеПар` зовётся
 * внутри разбора картинок, и проверка настоящего пути его не достаёт: чтобы пар не осталось,
 * пришлось бы менять опись картинок. Оба места вызова проходит только `npm run screens`.
 *
 * **Замороженное ограничение прибора, названное владельцем.** Сторожа снимков сравнивают стороны
 * между собой, и ни одна из сторон не привязана к источнику; перепутанные темы они не поймают.
 * Третий круг проверки кода показал это наблюдением: перестановка двух веток разводит темы по
 * неверным сторонам, и весь набор остаётся зелёным. Владелец заморозил прибор — три круга ушли на
 * измеритель, а оформления не написано ни строки, — и закрытие ушло отложенной задачей.
 *
 * **Чего в списке нет и почему.** У правила фокуса слома нет: это правило показа, и проверка,
 * читающая его в исходном тексте, доказывала бы наличие строки, а не наличие обводки. По той же
 * причине нет сломов у типографики, карточек и теней. Слома «таблица стилей подключена» нет тоже.
 * Нет и сторожа на «картинки те же, что приняты»: после правки оформления они обязаны измениться,
 * и такой сторож был бы ложью — что на нетронутом виде они не менялись, показано `git diff`.
 * Всё это названо вслух — здесь, в плане, в теле pull request и в отчёте.
 *
 * **Четыре слома проверки чисел таблицы стилей — задача 3.** Первые два сторожат выписанное:
 * подменённая величина перестаёт совпадать с числом из документации. Третий — закрывающий: он
 * показывает, что проверка ловит и то, чего первые два не видят, — постороннюю величину, которой
 * нет ни в одном утверждении по имени. Первые два красят заодно и его: подменённое число
 * одновременно перестаёт совпадать с выписанным и оказывается вне набора.
 */

