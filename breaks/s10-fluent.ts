/**
 * Список сломов куска S10 — оформление экрана по Fluent 2.
 *
 * Своих сломов у куска мало нарочно. Кусок меняет только то, **как** показано, и разметку не
 * открывает вовсе: переводов якорей прежних кусков в нём ноль, и доказывается это не сломом, а
 * пустым диффом по разметке — слом, которого не было, доказывать нечем.
 *
 * **Почему сломов девять, а не два.** Два круга проверки кода подряд нашли один и тот же класс
 * дефекта: сторож написан, а на настоящем пути молчит. Сперва сторожей звали из мест, которых не
 * касалась ни одна проверка; потом сторожей вынесли в распорядителей и накрыли проверками
 * распорядителей — а вызов самих распорядителей из `собратьСнимки` снова остался недоказанным.
 * Беда не двигалась, двигалась граница проверенного.
 *
 * Владелец выставил условие приёмки механически: **в генераторе не остаётся ни одного сторожа без
 * слома.** Сторожей девять — значит и сломов девять.
 *
 * **Что доказывает каждый слом.** Он выедает тело сторожа. Краснеет его собственная проверка
 * (`__tests__/screens/guards.test.ts`) — про то, что сторож умеет отказывать, — и краснеет
 * проверка настоящего пути (`__tests__/screens/generator.test.ts`), которая гоняет `собратьСнимки`
 * целиком на подставном браузере. Вторая и доказывает, что сторож позван **оттуда, откуда его
 * зовут в работе**.
 *
 * **Единственное исключение названо.** У `сверитьВыходБраузера` нет проверки настоящего пути: он
 * зовётся внутри захода в настоящий Chrome. Его слом красит только собственную проверку, и место
 * вызова обычным прогоном не доказывается — только `npm run screens`.
 *
 * **Чего в списке нет и почему.** У правила фокуса слома нет: это правило показа, и проверка,
 * читающая его в исходном тексте, доказывала бы наличие строки, а не наличие обводки. По той же
 * причине нет сломов у типографики, карточек и теней. Слома «таблица стилей подключена» нет тоже.
 * Нет и сторожа на «картинки те же, что приняты»: после правки оформления они обязаны измениться,
 * и такой сторож был бы ложью — что на нетронутом виде они не менялись, показано `git diff`.
 * Всё это названо вслух — здесь, в плане, в теле pull request и в отчёте.
 *
 * Сломы проверки чисел таблицы стилей добавляются задачей 3 и здесь пока не стоят.
 */

