/**
 * Разрыв времени в прогоне сломов — **отказ прибора, а не строка в отчёте**. Прогон, переживший
 * сон машины, недействителен целиком: соединение с базой сна не переживает, и десяток сломов подряд
 * получает «ломает больше, чем объявлено» из-за красных проверок, которым нужна база. Поймать это
 * можно только по времени, и прибор ловит сам.
 *
 * Порог считается по самому прогону, а не выдуман: берётся середина (медиана) длительностей уже
 * сделанных сломов, и подозрительным считается слом, который шёл дольше **десяти** таких середин и
 * при этом дольше минуты. Оба числа — наши: десять кратностей — запас против честного разброса
 * (самый долгий слом набора идёт вшестеро дольше самого быстрого), минута — пол, ниже которого
 * кратность ничего не значит на коротких сломах.
 *
 * Вынесено в свой модуль в круге проверки кода 3: сам прибор при импорте начинает работу, и
 * проверке было не за что ухватиться — сторож не мог покраснеть ни при какой правке. Поведение
 * при выносе не менялось.
 */
export function разрывВремени(секунды: number, длительности: readonly number[]): string | null {
  if (длительности.length < 3) return null
  const середина = [...длительности].sort((a, b) => a - b)[Math.floor(длительности.length / 2)]
  const порог = Math.max(60, середина * 10)
  return секунды > порог
    ? `слом шёл ${Math.round(секунды)} с при середине ${Math.round(середина)} с — это разрыв времени, а не работа`
    : null
}
