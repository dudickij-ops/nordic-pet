/**
 * Слом — это утверждение о механизме, записанное так, чтобы его можно было запустить.
 *
 * Зачем это данными, а не прозой в плане. Прежде таблица «что ломаем — что обязано
 * покраснеть» жила в одном месте, а запуски сломов — в другом, и синхронизировались они
 * руками. Сверялись при этом размеры списков, а не состав: три строки таблицы не имели
 * слома вовсе, а у одной слом отрицал не то, что обещала строка. Отчёт «каждый слом
 * покраснел» оказался утверждением автора, а не наблюдением.
 *
 * Теперь список один. Прогон читает его же, таблица отчёта порождается из вывода прогона,
 * и «каждый слом покраснел» становится наблюдаемым фактом.
 */
export type Break = {
  /** Короткое имя для ссылок. */
  id: string
  /** Строка таблицы: что именно ломаем. Формулировка — та же, что уходит в отчёт. */
  claim: string
  /**
   * Часть имени проверки, которая обязана покраснеть **из-за этого слома**.
   *
   * Это главное поле. Красное вообще ничего не доказывает: сломанный код почти всегда
   * что-нибудь роняет. Доказывает только красное у той проверки, которая сторожит именно
   * это утверждение.
   */
  mustRedden: string
  /** Файл, который правим. */
  file: string
  /** Что заменить. Должно встречаться в файле ровно один раз — иначе слом двусмысленный. */
  find: string
  /** Чем заменить. */
  replace: string
  /**
   * Проверки, которые покраснеют **заодно**, и причина у каждой.
   *
   * Слом обязан объявить весь ожидаемый набор красного, а не только свою проверку.
   * Иначе слом, который ломает больше, чем обещает, засчитывается доказательством:
   * своя покраснела — и ладно, а что рядом упало ещё три, никто не увидел.
   *
   * Причина пишется у каждой строки нарочно. Без неё список побочных превращается в
   * место, куда сметают лишнее красное, и вся затея теряет смысл.
   */
  alsoRedden?: Array<{ name: string; why: string }>
  /**
   * Вторая правка того же файла, если утверждение строки нельзя отрицать одной.
   *
   * Нужна там, где строка говорит про **порядок**: «цель названа до работы» отрицается
   * переносом называния, а не его удалением. Удаление краснит любую проверку и потому
   * ничего не доказывает — именно на этом подмене механизма и держалась ложная отчётность.
   */
  andThen?: { find: string; replace: string }
  /** Какой набор проверок гонять: путь к файлу проверок или `все` — весь `npm test`. */
  tests: string
  /** Нужно ли пересоздать базу: сломы миграций иначе не применятся. */
  resetDb?: boolean
  /** Нужно ли снести кэш длительностей: сломы, зависящие от порядка файлов прогона. */
  clearCache?: boolean
}

export type BreakVerdict =
  | 'своё'
  | 'чужое'
  | 'зелено'
  | 'не применился'
  | 'двусмысленный'
  /**
   * Имя, которое слом обещает покраснить, подходит сразу к нескольким проверкам набора.
   *
   * Это находка, а не мелочь: с семейством проверок — а они появляются от каждого
   * `describe.each` — красное у соседки засчиталось бы вместо красного у своей, и слом
   * защиты у одной таблицы «доказывался» бы проверкой другой.
   */
  | 'ожидание двусмысленно'
  /** Имя, которое слом обещает покраснить, не подходит ни к одной проверке: опечатка. */
  | 'такой проверки нет'
  /**
   * Покраснело больше, чем слом объявил.
   *
   * Значит слом ломает шире, чем обещает его строка, и «покраснела своя» доказывало бы
   * не то утверждение, которое написано. Лишнее красное либо объявляется в `alsoRedden`
   * с причиной, либо слом сужается.
   */
  | 'ломает больше обещанного'

export type BreakResult = {
  Break: Break
  verdict: BreakVerdict
  exitCode: number
  reddened: string[]
}
