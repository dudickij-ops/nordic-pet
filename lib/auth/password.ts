import { createHash, timingSafeEqual } from 'node:crypto'

/**
 * Сравнение пароля, не выдающее длину совпавшего начала.
 *
 * Обычное сравнение строк выходит наружу на первом расхождении. Разница во времени между
 * «не совпал первый знак» и «не совпали первые десять» мала, но измерима, и по ней пароль
 * подбирается знак за знаком — задача на терпение, а не на перебор.
 *
 * Поэтому сравниваются не строки, а их свёртки: они одной длины при любом вводе, и
 * `timingSafeEqual` из `node:crypto` проходит их целиком. Свёртка здесь — не хранение
 * пароля и не защита от чтения переменной окружения; её единственная работа — привести обе
 * стороны к одной длине, потому что `timingSafeEqual` на буферах разной длины отказывает
 * (так написано в документации Node.js, раздел `crypto.timingSafeEqual`), а сам отказ на
 * разной длине уже был бы ответом «пароли разной длины».
 */

/** Способ сравнить два буфера. Настоящий — стойкий ко времени; подставляется ради проверки. */
export type Сравнение = (левое: Buffer, правое: Buffer) => boolean

/** Свёртка постоянной длины: тридцать два байта при любом вводе. */
function свёртка(строка: string): Buffer {
  return createHash('sha256').update(строка, 'utf8').digest()
}

/**
 * Совпали ли строки. Ничего не печатает и ничего не возвращает, кроме да и нет:
 * ни длины, ни места расхождения, ни самих строк наружу не уходит.
 */
export function совпалоСкрытно(
  данное: string,
  ожидаемое: string,
  сравнить: Сравнение = timingSafeEqual,
): boolean {
  return сравнить(свёртка(данное), свёртка(ожидаемое))
}
