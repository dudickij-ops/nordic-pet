import { connectToDatabase } from '../facts/build.ts'
import { resolveIngestTarget } from '../ingest/target.ts'
import {
  войти,
  непроставленныеПеременныеВхода,
  type ИсходВхода,
  type Окружение,
  type ХранилищеCookie,
} from './login.ts'

/**
 * Замок на подбор пароля.
 *
 * Дашборд висит на открытом адресе с одним общим паролем. Без замка подбирать можно с любой
 * скоростью, и никто об этом не узнает; замок делает подбор бессмысленным, не запирая надолго
 * того, кто просто забыл пароль.
 *
 * **Счёт живёт в базе, а не в памяти процесса.** На бессерверном хостинге процессов много и
 * они умирают между запросами: счётчик в памяти означал бы «считаем иногда», то есть замок,
 * который иногда не заперт. Таблица и правило её чистки — в миграции `20260905090000_meta.sql`.
 */

/**
 * Числа — решение владельца от 5 сентября 2026 года, а не общепринятая норма и не вывод из
 * документации. Довод владельца: десять попыток человек руками по ошибке не наберёт, а
 * пятнадцать минут делают перебор бессмысленным и не запирают надолго забывшего пароль.
 * Названы числами затем, чтобы их можно было оспорить.
 */
export const ПОРОГ = 10
export const ОКНО_МИНУТ = 15

/** То же окно словами базы: и срок запирания, и срок жизни записей о попытках. */
export const ОКНО = `${ОКНО_МИНУТ} minutes`

/**
 * Ведро для случая, когда адреса нет.
 *
 * На местной работе заголовка с адресом не бывает. Молчаливого пропуска здесь нет нарочно:
 * счёт идёт, просто общий, и ведро названо явно — чтобы читающий таблицу видел, что это не
 * чей-то адрес, а «адрес неизвестен».
 */
export const ОБЩЕЕ_ВЕДРО = 'адрес неизвестен'

/**
 * Адрес посетителя из заголовка.
 *
 * На нашем хостинге заголовок ставит сам хостинг: «The public IP address of the client that
 * made the request», и там же — «we currently overwrite the `X-Forwarded-For` header and do not
 * forward external IPs. This restriction is in place to prevent IP spoofing»
 * (vercel.com/docs/headers/request-headers). Значит подделать его посетитель не может.
 *
 * Заголовок может нести список адресов через запятую — берётся первый, это и есть клиент.
 */
export function адресПосетителя(заголовок: string | null | undefined): string {
  const первый = (заголовок ?? '').split(',')[0].trim()
  return первый === '' ? ОБЩЕЕ_ВЕДРО : первый
}

export type СостояниеЗамка = {
  заперто: boolean
  /** Сколько минут осталось до отпирания. Ноль, когда не заперто. */
  черезМинут: number
}

/**
 * Заперт ли адрес — чистое решение, без базы и без часов внутри.
 *
 * Запирает **число неудач в окне**, а отпускает время: самая ранняя из них уходит из окна
 * первой, и после этого счёт падает ниже порога сам собой. Отдельного «срока наказания» нет —
 * он был бы вторым сроком, который надо согласовывать с первым.
 */
export function состояниеЗамка(
  неудач: number,
  самаяРанняя: Date | null,
  сейчас: number,
): СостояниеЗамка {
  if (неудач < ПОРОГ || самаяРанняя === null) return { заперто: false, черезМинут: 0 }
  const отпустит = самаяРанняя.getTime() + ОКНО_МИНУТ * 60_000
  const осталось = Math.max(0, Math.ceil((отпустит - сейчас) / 60_000))
  return осталось === 0 ? { заперто: false, черезМинут: 0 } : { заперто: true, черезМинут: осталось }
}

/**
 * Отказ запертому. Говорит, что случилось, когда отпустит и что это не поломка: человек,
 * который этого не знает, полезет чинить исправное.
 */
export function текстЗапертого(черезМинут: number): string {
  return (
    `Слишком много неудачных попыток входа с этого адреса. Вход закрыт примерно на ` +
    `${черезМинут} мин. Это не поломка, а защита от подбора пароля: подождите и попробуйте снова`
  )
}

/** Что умеет счёт попыток. Настоящий ходит в базу; в проверках подставляется. */
export type СчётПопыток = {
  неудачи: (адрес: string) => Promise<{ неудач: number; самаяРанняя: Date | null }>
  записатьНеудачу: (адрес: string) => Promise<void>
  обнулить: (адрес: string) => Promise<void>
  закрыть: () => Promise<void>
}

/**
 * Настоящий счёт: одно соединение на одну попытку входа.
 *
 * Среда называется тем же способом, что и у загрузчиков, — переменной, а не догадкой по тому,
 * какие ключи заполнены. Соединение закрывается всегда, и это работа зовущего.
 */
export async function счётВБазе(): Promise<СчётПопыток> {
  const цель = resolveIngestTarget()
  const клиент = await connectToDatabase(цель.connection)

  return {
    неудачи: async (адрес) => {
      const ответ = await клиент.query('select n, oldest from meta.failures($1, $2::interval)', [
        адрес,
        ОКНО,
      ])
      const строка = ответ.rows[0] as { n: number; oldest: Date | null } | undefined
      return { неудач: строка?.n ?? 0, самаяРанняя: строка?.oldest ?? null }
    },
    записатьНеудачу: async (адрес) => {
      await клиент.query('select meta.record_failure($1, $2::interval)', [адрес, ОКНО])
    },
    обнулить: async (адрес) => {
      await клиент.query('select meta.clear_failures($1)', [адрес])
    },
    закрыть: () => клиент.release(),
  }
}

/**
 * Вход через замок — та же сверка, но за запертой дверью.
 *
 * Порядок здесь и есть механизм, и он такой:
 *
 * 1. Ненастроенный вход отвечается **до** всякого счёта: он говорит не о пароле, а о
 *    незаполненных переменных, и человек, который чинит настройку, не должен запирать себе
 *    дверь. Отличается по самому условию, а не по тексту отказа.
 * 2. Запертому отказывают **до сверки пароля**. Это и есть «дверь заперта»: за ней не важно,
 *    какой пароль принесли — годный тоже не пускает.
 * 3. Пока заперто, новые попытки не записываются. Иначе окно наполнялось бы заново от каждой
 *    попытки, и забывший пароль сидел бы под замком, пока не перестанет стучаться, — а нам
 *    нужно, чтобы отпустило через окно после десятой неудачи.
 * 4. Удача обнуляет счёт, неудача его двигает.
 */
export type ЗависимостиЗамка = {
  счёт: СчётПопыток
  env: Окружение
  now: number
  cookies: ХранилищеCookie
  адрес: string
}

export async function войтиЧерезЗамок(
  логин: string,
  пароль: string,
  deps: ЗависимостиЗамка,
): Promise<ИсходВхода> {
  const общее = { env: deps.env, now: deps.now, cookies: deps.cookies }

  if (непроставленныеПеременныеВхода(deps.env).length > 0) return войти(логин, пароль, общее)

  const { неудач, самаяРанняя } = await deps.счёт.неудачи(deps.адрес)
  const замок = состояниеЗамка(неудач, самаяРанняя, deps.now)
  if (замок.заперто) return { ok: false, text: текстЗапертого(замок.черезМинут) }

  const исход = войти(логин, пароль, общее)

  if (исход.ok) await deps.счёт.обнулить(deps.адрес)
  else await deps.счёт.записатьНеудачу(deps.адрес)

  return исход
}
