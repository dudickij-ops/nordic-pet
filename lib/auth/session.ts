import { createHmac, timingSafeEqual } from 'node:crypto'

/**
 * Подписанная cookie входа: чеканка, проверка и срок жизни.
 *
 * Здесь нет ни одного обращения к окружению исполнения — ни к запросу, ни к часам, ни к
 * `process.env` мимо явного довода. Секрет, «сейчас» и сама cookie приходят доводами, а
 * ответ — слово. Всё, что знает про запрос Next, живёт в `lib/auth/guard.ts` и в `proxy.ts`.
 *
 * **В cookie нет ничего, кроме срока годности.** Ни логина, ни пароля, ни признака прав:
 * вход в дашборде один на всех, и возить в cookie нечего. Чего в ней нет, то не утечёт.
 *
 * Подпись — HMAC-SHA256 секретом из переменной окружения. Секрета нет ни в коде, ни в
 * репозитории ни в каком виде: секрет в git — это секрет, которого больше нет.
 */

/** Имя cookie. Одно на всё приложение: и чеканка, и оба сторожа берут его отсюда. */
export const SESSION_COOKIE = 'nordic_pet_session'

/**
 * Срок жизни — двенадцать часов, и это решение владельца, принятое до работы.
 *
 * Дашборд смотрят рабочими подходами, а не держат открытым неделями. Двенадцать часов
 * покрывают рабочий день с запасом и не переживают ночь: меньше — человек будет входить
 * посреди работы, больше — забытая вкладка на чужой машине остаётся входом дольше суток.
 */
export const SESSION_HOURS = 12

const SESSION_MS = SESSION_HOURS * 60 * 60 * 1000

/** Имя переменной с секретом подписи. Живёт в переменных Vercel и в `.env.local`, не в git. */
const SECRET = 'NORDIC_PET_SESSION_SECRET'

/** Метка вида cookie. Меняется, когда меняется её устройство: старые перестают разбираться. */
const ВИД = 'v1'

/**
 * Состояние cookie одним словом.
 *
 * Пускает только `годна`; все прочие — отказ. Слов несколько, а не «да/нет», потому что
 * отличать «человек не входил» от «подпись чужая» полезно и стороже, и проверкам, а разные
 * ответы наружу из этого не делаются: посетителю во всех случаях показывается вход.
 */
export type Состояние = 'годна' | 'нет cookie' | 'не разбирается' | 'подпись чужая' | 'просрочена' | 'нет секрета'

/** Окружение процесса: имя переменной — значение. */
type Окружение = Record<string, string | undefined>

/**
 * Секрет подписи из окружения.
 *
 * Отказ называет переменную и говорит, что сделать: отказ, который человек может исправить
 * руками, обязан называть, что именно исправить, иначе это тупик, а не защита. Самого
 * значения в отказе нет и быть не может — его как раз и нет.
 */
export function секретПодписи(env: Окружение = process.env): string {
  const секрет = env[SECRET]
  if (секрет === undefined || секрет === '') {
    throw new Error(
      `${SECRET} не задана, а без неё подписывать вход нечем. Заведите её в переменных ` +
        'проекта Vercel (Settings → Environment Variables) и в .env.local для местной ' +
        'работы: случайная строка не короче 32 байт, например из `openssl rand -base64 32`',
    )
  }
  return секрет
}

/** Подпись тела cookie. Наружу не отдаётся отдельно ни в каком виде. */
function подпись(тело: string, секрет: string): string {
  return createHmac('sha256', секрет).update(тело, 'utf8').digest('hex')
}

/**
 * Чеканит cookie на двенадцать часов вперёд от названного мгновения.
 *
 * Срок годности лежит в самой cookie **и** подписан вместе с ней. Полагаться на срок,
 * который браузер обещает соблюдать, нельзя: браузер чужой, а cookie возвращается такой,
 * какой её пришлют. Поэтому срок проверяется нами при каждом заходе.
 */
export function начеканить(
  сейчас: number,
  секрет: string,
): { value: string; expiresAt: Date } {
  const срок = сейчас + SESSION_MS
  const тело = `${ВИД}.${срок}`
  return { value: `${тело}.${подпись(тело, секрет)}`, expiresAt: new Date(срок) }
}

/**
 * Что за cookie принесли.
 *
 * Порядок решений важен. Сначала секрет: без него проверить подпись нечем, и это отказ, а
 * не проход. Потом разбор. Потом **подпись** — и только после неё срок годности: срок лежит
 * в теле, которое прислал посетитель, и до проверки подписи это не число, а чужое
 * утверждение. Проверка срока раньше подписи означала бы, что продлённая на год cookie
 * читается как «годная, но просроченная» — то есть что мы поверили подделанному числу.
 */
export function проверить(
  cookie: string | undefined,
  секрет: string | undefined,
  сейчас: number,
): Состояние {
  if (секрет === undefined || секрет === '') return 'нет секрета'
  if (cookie === undefined || cookie === '') return 'нет cookie'

  const части = cookie.split('.')
  if (части.length !== 3) return 'не разбирается'
  const [вид, срок, принесённая] = части
  if (вид !== ВИД) return 'не разбирается'
  if (!/^[0-9]+$/.test(срок)) return 'не разбирается'

  const своя = подпись(`${вид}.${срок}`, секрет)
  // Длины сверяются до `timingSafeEqual`: на разной длине он отказывает, а его отказ сам по
  // себе был бы ответом «подпись не той длины». Своя подпись всегда одной и той же длины,
  // так что сравнение длин ни о чём принесённом не рассказывает.
  if (принесённая.length !== своя.length) return 'подпись чужая'
  if (!timingSafeEqual(Buffer.from(принесённая, 'utf8'), Buffer.from(своя, 'utf8')))
    return 'подпись чужая'

  if (сейчас > Number(срок)) return 'просрочена'
  return 'годна'
}
