import { совпалоСкрытно } from './password.ts'
import { SESSION_COOKIE, ИМЯ_СЕКРЕТА, начеканить } from './session.ts'

/**
 * Вход: сверка названного логина и пароля и выдача подписанной cookie.
 *
 * Здесь нет ни одного обращения к запросу Next и ни одного к часам: окружение, «сейчас» и
 * хранилище cookie приходят доводами. Настоящее хранилище подставляет серверное действие
 * `app/login/action.ts` — тонкая обёртка, которая сама ничего не решает.
 *
 * **Ответ на любой неверный ввод один и тот же.** Ни «такого логина нет», ни «пароль не
 * подошёл»: разные ответы говорят подбирающему, какая половина уже угадана, и превращают
 * перебор двух неизвестных в перебор одного. Поэтому обе сверки идут всегда — обе, даже
 * когда первая уже не совпала, — а решение принимается по ним разом.
 */

/** Имя переменной с логином. Значение придумывает владелец и кладёт в переменные проекта. */
const ИМЯ_ЛОГИНА = 'NORDIC_PET_LOGIN'

/** Имя переменной с паролем. Там же. */
const ИМЯ_ПАРОЛЯ = 'NORDIC_PET_PASSWORD'

/**
 * Один и тот же ответ на любой неверный ввод. Ни пароля, ни логина, ни секрета в нём нет:
 * текст отказа уходит в чужие руки — в браузер того, кто как раз и не вошёл.
 */
const ОТКАЗ = 'Логин или пароль не подошли'

/** Окружение процесса: имя переменной — значение. */
export type Окружение = Record<string, string | undefined>

export type ИсходВхода = { ok: true } | { ok: false; text: string }

/** Настройки cookie входа. Ни одна из них не на усмотрение браузера. */
export type НастройкиCookie = {
  httpOnly: true
  secure: true
  sameSite: 'lax'
  path: '/'
  expires: Date
}

/** То, куда кладут cookie. Настоящее — из `next/headers`; в проверках подставляется. */
export type ХранилищеCookie = {
  set: (имя: string, значение: string, настройки: НастройкиCookie) => void
}

export type ЗависимостиВхода = {
  env: Окружение
  /** «Сейчас» числом: от него отсчитывается срок жизни cookie. */
  now: number
  cookies: ХранилищеCookie
}

/**
 * Сверяет вход и при совпадении кладёт cookie.
 *
 * Отказ ненастроенного входа — свой, отдельный от отказа неверного ввода, и называет
 * недостающие переменные поимённо. Это не подсказка подбирающему: заполнить переменные
 * окружения может только тот, у кого есть доступ к настройкам проекта, а человеку с таким
 * доступом отказ обязан сказать, что именно чинить, иначе это тупик, а не защита.
 *
 * `sameSite: 'lax'`, а не `'strict'`: при `strict` cookie не посылается даже при переходе
 * по ссылке на дашборд с другой страницы, и вошедший человек увидит вход снова. `lax`
 * закрывает то, ради чего эта настройка заведена, — чужую форму, отправляющую запрос за нас.
 */
/**
 * Какие переменные входа не заполнены. Пустой список — вход настроен.
 *
 * Вынесено наружу для замка на подбор (S8): отказ ненастроенного входа за попытку не
 * считается, и отличать его надо по самому условию, а не по тексту отказа. Текст — вещь
 * переменная, и проверка, которая ловит отказ по словам, однажды поймает не тот отказ.
 */
export function непроставленныеПеременныеВхода(env: Окружение): string[] {
  return [ИМЯ_ЛОГИНА, ИМЯ_ПАРОЛЯ, ИМЯ_СЕКРЕТА].filter((имя) => {
    const значение = env[имя]
    return значение === undefined || значение === ''
  })
}

export function войти(логин: string, пароль: string, deps: ЗависимостиВхода): ИсходВхода {
  const пропали = непроставленныеПеременныеВхода(deps.env)
  if (пропали.length > 0) {
    return {
      ok: false,
      text:
        `Вход не настроен: не заданы ${пропали.join(', ')}. Заведите их в переменных проекта ` +
        'Vercel (Settings → Environment Variables) и в .env.local для местной работы. ' +
        'Значения придумывает владелец; в код и в репозиторий они не попадают',
    }
  }

  // Обе сверки идут до всякого решения: выход по первой несовпавшей сказал бы подбирающему,
  // какая половина уже угадана — и по времени ответа, и по тому, что вторая не считалась.
  const логинСовпал = совпалоСкрытно(логин, deps.env[ИМЯ_ЛОГИНА] as string)
  const парольСовпал = совпалоСкрытно(пароль, deps.env[ИМЯ_ПАРОЛЯ] as string)
  if (!логинСовпал || !парольСовпал) return { ok: false, text: ОТКАЗ }

  const { value, expiresAt } = начеканить(deps.now, deps.env[ИМЯ_СЕКРЕТА] as string)
  deps.cookies.set(SESSION_COOKIE, value, {
    httpOnly: true,
    secure: true,
    sameSite: 'lax',
    path: '/',
    expires: expiresAt,
  })
  return { ok: true }
}
