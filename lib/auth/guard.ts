import { cookies } from 'next/headers'

import { SESSION_COOKIE, ИМЯ_СЕКРЕТА, проверить } from './session.ts'

/**
 * Сторож пути — второй слой закрытия.
 *
 * Первый слой (`proxy.ts`) закрывает всё, о чём никто не подумал. Этот стоит у каждого
 * пути, который отдаёт числа или делает работу, и нужен ровно потому, что общий слой —
 * допущение: «Always verify authentication and authorization inside each Server Function
 * rather than relying on Proxy alone» (nextjs.org/docs/app/api-reference/file-conventions/proxy,
 * «Execution order»), и там же — почему: перенос серверного действия на другой путь или
 * правка образца молча выводят его из-под общего слоя.
 *
 * **Правило устройства: нет запроса — нет доступа.** Вне запроса Next чтение cookie
 * отказывает; ответ на это — отказ, и никаких условий. Разрешающая ветка, включающаяся по
 * значению переменной среды, сегодня недостижима в бою, а завтра приложение соберут с другой
 * средой — и единственным, что стоит между посторонним и деньгами, окажется настройка
 * окружения. Ветвиться защите можно только в сторону отказа.
 */

export type Доступ = 'пускать' | 'отказать'

/** Способ достать cookie входа. Настоящий — из запроса Next; в проверках подставляется. */
export type ЧтениеCookie = () => Promise<string | undefined>

/** Окружение процесса: имя переменной — значение. */
type Окружение = Record<string, string | undefined>

/**
 * Так отказывает `cookies()`, позванная вне запроса. Текст проверен запуском, а не взят из
 * памяти; страницы документации на эту ошибку нет, есть адрес в самом тексте отказа.
 */
const ВНЕ_ЗАПРОСА = 'was called outside a request scope'

async function изЗапроса(): Promise<string | undefined> {
  return (await cookies()).get(SESSION_COOKIE)?.value
}

/**
 * Пускать ли дальше.
 *
 * Отсутствие запроса отвечается **отказом**, а не падением: отказ определён и одинаков, а
 * необработанное падение отдало бы посетителю страницу ошибки хостинга, по которой не
 * понять, закрыто тут или сломано. Любой другой отказ чтения — чужой, настоящий, и он
 * летит наружу нетронутым: глотать незнакомые отказы в стороже — это способ однажды
 * проглотить поломку и счесть её закрытым состоянием.
 */
export async function проверитьДоступ(
  читатьCookie: ЧтениеCookie = изЗапроса,
  env: Окружение = process.env,
  сейчас: number = Date.now(),
): Promise<Доступ> {
  let cookie: string | undefined
  try {
    cookie = await читатьCookie()
  } catch (отказ) {
    if (отказ instanceof Error && отказ.message.includes(ВНЕ_ЗАПРОСА)) return 'отказать'
    throw отказ
  }

  return проверить(cookie, env[ИМЯ_СЕКРЕТА], сейчас) === 'годна' ? 'пускать' : 'отказать'
}
