/** Имя базы этого проекта. Ни с какой другой мы не работаем. */
const PROJECT_DATABASE = 'nordic_pet'

/** Порт, на котором живёт база проекта. */
const LOCAL_PORT = '5432'

/** Локальный хост во всех написаниях, в которых его отдаёт разбор адреса. */
const LOCAL_HOSTS = new Set(['127.0.0.1', 'localhost', '::1', '[::1]'])

/**
 * Имя пользователя принимается только из букв, цифр и подчёркиваний. Всё прочее
 * пришлось бы перекодировать при сборке адреса заново, а перекодирование — это ещё
 * одно место, где написанное и понятое клиентом базы могут разойтись.
 */
const PLAIN_USER = /^[A-Za-z0-9_]+$/

/**
 * Адрес локальной базы проекта.
 *
 * `sslmode=disable` стоит здесь потому, что локальный Postgres шифрования не предлагает,
 * а Supabase CLI считает любой адрес удалённым и по умолчанию требует его.
 * В адрес облачной базы это не переносится никогда: там шифрование обязательно,
 * и отключать его нельзя ни для проверки, ни «на минутку».
 */
export const LOCAL_DATABASE_URL = 'postgresql://postgres@127.0.0.1:5432/nordic_pet?sslmode=disable'

/**
 * Разбирает адрес на пять частей — схема, пользователь, хост, порт, имя базы, — требует,
 * чтобы каждая была названа явно и была той самой, и отдаёт адрес, **собранный заново**
 * из этих пяти проверенных частей. Всё, что было в адресе сверх них, не доезжает до
 * клиента базы. В любом другом случае поднимается ошибка.
 *
 * Зачем это нужно. Пересоздание базы сносит в ней всё, что создано человеком.
 * На сервере разработчика рядом живут другие работы — другие базы того же сервера, —
 * и опечатки в переменной окружения хватило бы, чтобы стоить одной из них.
 * Поэтому здесь именно отказ, а не предупреждение: предупреждение можно не заметить,
 * а команду, которая не выполнилась, не заметить нельзя.
 *
 * Почему адрес пересобирается, а не возвращается как есть. Прежняя защита проверяла
 * строку и эту же строку отдавала клиенту, а клиент по правилам libpq дочитывает
 * недостающее сам: параметр `?dbname=` перекрывает имя базы из пути, текст после решётки
 * разбор адреса отрезает, а клиент — нет, пустой порт берётся из `PGPORT`, пустой хост —
 * из `PGHOST`, а `?service=` уводит вообще в файл `pg_service.conf`. Каждый такой обход
 * закрывался отдельной заплатой, и каждая следующая проверка кода находила следующий.
 * Список известных обходов не бывает полным. Собранный заново адрес закрывает их все
 * разом и вперёд: подставлять нечего, потому что в отданной строке ничего чужого нет.
 */
export function assertProjectDatabase(url: string): string {
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    throw new Error(`адрес базы не разбирается: ${url}`)
  }

  if (parsed.protocol !== 'postgres:' && parsed.protocol !== 'postgresql:') {
    throw new Error(`адрес базы должен быть postgresql://…, а не ${parsed.protocol}//…`)
  }

  const host = parsed.hostname
  if (host === '') {
    throw new Error(
      'в адресе базы не назван хост: клиент базы взял бы его из переменной PGHOST, ' +
        'и проверенным оказался бы один сервер, а соединение ушло бы на другой',
    )
  }
  if (!LOCAL_HOSTS.has(host)) {
    throw new Error(
      `база ${PROJECT_DATABASE} пересоздаётся только на локальном хосте, ` +
        `а адрес указывает на ${host}`,
    )
  }

  const port = parsed.port
  if (port === '') {
    throw new Error(
      'в адресе базы не назван порт: клиент базы взял бы его из переменной PGPORT, ' +
        'а другой порт на том же хосте — другой сервер и чужие данные',
    )
  }
  if (port !== LOCAL_PORT) {
    throw new Error(
      `база ${PROJECT_DATABASE} живёт на порту ${LOCAL_PORT}, а адрес указывает на ` +
        `${port}: другой порт — другой сервер`,
    )
  }

  const name = parsed.pathname.replace(/^\//, '')
  if (name === '') {
    throw new Error(
      'в адресе базы не названа база: клиент взял бы имя из переменной PGDATABASE, ' +
        `а разрешена только ${PROJECT_DATABASE}`,
    )
  }
  if (name !== PROJECT_DATABASE) {
    throw new Error(
      `адрес указывает на базу «${name}», а разрешена только ` +
        `${PROJECT_DATABASE}: рядом на этом сервере живут чужие базы`,
    )
  }

  const user = parsed.username
  if (user === '') {
    throw new Error(
      'в адресе базы не назван пользователь: клиент взял бы его из переменной PGUSER',
    )
  }
  if (!PLAIN_USER.test(user)) {
    throw new Error(
      `в адресе базы непростое имя пользователя «${user}»: разрешены буквы, цифры ` +
        'и подчёркивание, чтобы адрес собирался заново без перекодирования',
    )
  }

  // Адрес собирается заново из пяти проверенных частей. Пароля здесь нет намеренно:
  // хост локальный, и локальная база проекта работает без пароля — и на машине
  // разработчика, и в проверке `ci`.
  return `postgresql://${user}@${host}:${LOCAL_PORT}/${PROJECT_DATABASE}?sslmode=disable`
}

/**
 * Адрес, по которому работают и проверки, и пересоздание базы.
 * Берётся из окружения, а если его там нет — локальный адрес по умолчанию.
 * Через проверку проходит в любом случае: непроверенного адреса в проекте нет.
 */
export function projectDatabaseUrl(): string {
  return assertProjectDatabase(process.env.DATABASE_URL ?? LOCAL_DATABASE_URL)
}

/** Окружение процесса: имя переменной — значение. */
type Environment = Record<string, string | undefined>

/**
 * Снимает из окружения все переменные `PG*` и отдаёт то же окружение.
 *
 * Это второй замок, и он закрывает то же, что и пересборка адреса, только с другой
 * стороны. Проверенный адрес защищает лишь тот вызов, которому он передан; всё
 * остальное, что запускается рядом — сам `supabase`, `psql` внутри него, любой клиент
 * libpq, — читает окружение самостоятельно. `PGDATABASE`, `PGHOST`, `PGPORT`, `PGUSER`,
 * `PGSERVICEFILE` в таком вызове значат ровно то же, что чужой адрес. Разрушающая
 * команда обязана уходить в окружение, где подставлять нечего.
 */
export function clearPostgresEnvironment(env: Environment = process.env): Environment {
  for (const key of Object.keys(env)) {
    if (key.startsWith('PG')) delete env[key]
  }
  return env
}
