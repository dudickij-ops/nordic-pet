import { DATABASE_COMMANDS, type DatabaseCommand } from '../commands.ts'
import { connectToDatabase } from '../facts/build.ts'
import { resolveIngestTarget } from '../ingest/target.ts'

/**
 * Кнопка «Обновить данные» — задача 8.
 *
 * Три шага в жёстком порядке: загрузка Таблицы → загрузка папки → разбор. Каждый шаг —
 * своя транзакция, доставшаяся от S2, S3 и S4, и отсюда щель, названная в контракте S4
 * заранее: если хоть один шаг успел записать, а следующий отказался, сырьё частично новое,
 * а факты — вчерашние, и по фактам этого не видно.
 *
 * Щель есть тогда, когда хоть один шаг успел записать (контракт S5, «Кнопка „Обновить
 * данные“ и щель между загрузкой и разбором»): отказ Таблицы щели не создаёт — записать
 * никто не успел, — а отказ папки и отказ разбора создают, потому что Таблица к этому
 * моменту уже записана своей транзакцией. `stale: true` — это и есть отметка щели: её
 * обязана показать панель, а не только текст.
 *
 * Своей дороги в базу у кнопки нет: она не импортирует ни `ingestSheets`, ни
 * `ingestAdsFolder`, ни `buildFacts` напрямую, а ищет в списке команд (`DATABASE_COMMANDS`
 * по умолчанию, подставка — через `deps.commands`) записи `ingest:sheets`, `ingest:ads`,
 * `facts` по имени и зовёт их боевое поле `real`. Имени, которого в списке нет, — отказ,
 * и это не операционный отказ вида `RefreshOutcome`, а падение до всякой работы: это
 * ошибка устройства, а не то, что случается на бою.
 */

export type RefreshOutcome =
  | { ok: true }
  | { ok: false; step: 'Таблица' | 'папка' | 'разбор'; text: string; stale: boolean }
  /**
   * Обновление уже идёт — задача 6 куска S8.
   *
   * Отдельный вид, а не отказ шага: ни один шаг не отказал, потому что ни один и не начался.
   * `stale: false` здесь честно: мы ничего не тронули, и числа на экране такие же, какими
   * были, — не свежее и не устарелее.
   */
  | { ok: false; занято: true; text: string; stale: false }

/**
 * Длительность аренды замка — решение автора, а не выведенное число.
 *
 * Замок живёт строкой в таблице, и сам он не отпустится: процесс, убитый посреди обновления,
 * оставил бы кнопку запертой навсегда. Аренда — срок, после которого замок считается брошенным.
 * Десять минут: по нашим прогонам обновление занимает около минуты (три шага, пять с половиной
 * сотен строк) — это наблюдение, а не измерение, — и десять минут дают запас примерно в десять
 * раз. Работающее дольше аренды обновление никто не останавливает: оно пойдёт внахлёст со
 * следующим, и это названо в README как принятая цена, а не закрытая беда.
 *
 * Меньше — рискуем отобрать замок у работающего обновления;
 * больше — человек ждёт впустую после падения. Число названо числом, чтобы его можно было
 * оспорить.
 */
export const АРЕНДА_ЗАМКА = '10 minutes'

/** Взятый замок умеет только одно — отпуститься. */
export type Замок = { взят: boolean; отпустить: () => Promise<void> }

/**
 * Настоящий замок — строка в таблице `meta.refresh_lock`.
 *
 * **Почему не совещательный замок PostgreSQL, хотя контракт называл именно его.** Совещательный
 * замок сеансового уровня в бою не работает: боевой адрес идёт через объединитель соединений в
 * транзакционном режиме, а его карта возможностей отвечает про сеансовые совещательные замки
 * «Never» и предупреждает — «This mode breaks a few session-based features of PostgreSQL»
 * (pgbouncer.org/features.html). Взятие ушло бы на один задний конец, отпускание — на другой, и
 * кнопка закрылась бы навсегда после первого нажатия. Транзакционный совещательный замок сюда
 * тоже не годится: три шага кнопки — три отдельные транзакции, а такой замок, по справочнику
 * PostgreSQL, держится «until the current transaction ends». Найдено проверкой кода; местная
 * база этого не показывает никогда — там прямое соединение.
 *
 * Строка в таблице сеансового состояния не требует и работает через любой объединитель. Ценой
 * идёт аренда: таблица сама не отпустится, и брошенный замок освобождается по её истечении.
 *
 * Способ открыть соединение подставляется — иначе отказ **самого отпускания** нечем показать:
 * настоящая база отпускает исправно, а проверять надо, что мы делаем, когда она откажет.
 * Значение по умолчанию настоящее: вызов без доводов идёт настоящим путём.
 */
export async function замокВБазе(
  открыть: () => Promise<{
    query: (sql: string, params?: unknown[]) => Promise<{ rows: unknown[] }>
    release: () => Promise<void>
  }> = async () => connectToDatabase(resolveIngestTarget().connection),
): Promise<Замок> {
  const клиент = await открыть()

  // Спрашивается вне транзакции, то есть на уровне «read committed»: там `update` перечитывает
  // условие после чужой правки и честно отвечает «занято». Внутри `repeatable read` та же
  // функция вместо отказа получила бы ошибку сериализации — поэтому замок берётся здесь, до
  // всякой работы, а не изнутри чужой транзакции. Названо проверкой кода.
  const ответ = await клиент.query('select meta.take_refresh_lock($1::interval) as жетон', [
    АРЕНДА_ЗАМКА,
  ])
  const жетон = (ответ.rows[0] as { жетон: string | null } | undefined)?.жетон ?? null

  return {
    взят: жетон !== null,
    отпустить: async () => {
      // Отказ самого отпускания не должен ни оставлять соединение открытым, ни подменять собой
      // настоящий исход обновления: `отпустить` зовётся в `finally`, и брошенная отсюда ошибка
      // заменила бы собой и удачу, и читаемый отказ шага. Поэтому она только записывается в
      // журнал. Замок при этом провисит до конца аренды — это названо в README. Найдено
      // проверкой кода.
      try {
        // Отпускаем **свой** замок: жетон не совпадёт, если его уже отобрали по истечении
        // аренды, и тогда трогать строку нельзя — она принадлежит другому прогону.
        if (жетон !== null) {
          await клиент.query('select meta.release_refresh_lock($1)', [жетон])
        }
      } catch (отказ) {
        console.error('замок обновления не отпустился — провисит до конца аренды:', отказ)
      } finally {
        await клиент.release().catch(() => {})
      }
    },
  }
}

export type RefreshDeps = {
  /** Куда дошли — говорится до всякой работы, а не после. */
  announce: (line: string) => void
  /** Список команд, из которого шаги берутся по имени. По умолчанию — боевой список. */
  commands: DatabaseCommand[]
  /** Как брать замок. По умолчанию — настоящий, в базе. */
  замок: () => Promise<Замок>
  ingestSheets: () => Promise<unknown>
  ingestAds: () => Promise<unknown>
  buildFacts: () => Promise<unknown>
}

type StepName = 'ingest:sheets' | 'ingest:ads' | 'facts'

/** Как шаг называется человеку — те самые три слова из контракта. */
const STEP_LABEL: Record<StepName, 'Таблица' | 'папка' | 'разбор'> = {
  'ingest:sheets': 'Таблица',
  'ingest:ads': 'папка',
  facts: 'разбор',
}

/**
 * Щель есть тогда, когда хоть один шаг успел записать до отказавшего. Таблица идёт первой
 * — на её отказе щели нет; папка и разбор идут после уже записавшей Таблицы — на их отказе
 * щель есть.
 */
const STEP_STALE: Record<StepName, boolean> = {
  'ingest:sheets': false,
  'ingest:ads': true,
  facts: true,
}

/**
 * Ищет боевой вызов работы по имени в списке команд.
 *
 * Разрешается до всякой работы, а не в момент вызова шага: имени, которого в списке нет, —
 * это ошибка устройства кнопки, и обнаружить её до того, как что-то успело перечитаться
 * наполовину, лучше, чем после.
 */
function stepFromCommands(commands: DatabaseCommand[], name: StepName): () => Promise<unknown> {
  const command = commands.find((entry) => entry.name === name)
  if (command === undefined) {
    throw new Error(`команды ${name} нет в списке — обход списка невозможен по построению`)
  }
  return command.real
}

function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}

/** Отказ — читаемым текстом: какой шаг, что случилось, и что сделать. */
function refusal(step: StepName, error: unknown): RefreshOutcome {
  const reason = messageOf(error)
  const what =
    step === 'ingest:sheets'
      ? `загрузка Google Таблицы не удалась: ${reason}. Папка и разбор не запускались, ` +
        'числа ниже не менялись.'
      : step === 'ingest:ads'
        ? `Таблица перечитана, но загрузка папки ads-exports не удалась: ${reason}. Разбор ` +
          'не запускался, числа ниже — от прежнего удачного разбора и устарели.'
        : `источники перечитаны, но разбор не удался: ${reason}. Числа ниже — от прежнего ` +
          'удачного разбора и устарели.'
  return {
    ok: false,
    step: STEP_LABEL[step],
    text: `${what} Нажмите «Обновить данные» ещё раз.`,
    stale: STEP_STALE[step],
  }
}

/**
 * Зовёт три шага по порядку. Отказ Таблицы щели не создаёт — сырьё и факты остаются
 * согласованными, — а отказ папки и отказ разбора создают: Таблица к этому моменту уже
 * записана своей транзакцией. Показывается всё тремя одинаковым способом, и у каждого шага
 * своя проверка отказа.
 */
export async function refreshEverything(deps: Partial<RefreshDeps> = {}): Promise<RefreshOutcome> {
  const announce = deps.announce ?? (() => {})
  const commands = deps.commands ?? DATABASE_COMMANDS

  const ingestSheets = deps.ingestSheets ?? stepFromCommands(commands, 'ingest:sheets')
  const ingestAds = deps.ingestAds ?? stepFromCommands(commands, 'ingest:ads')
  const buildFacts = deps.buildFacts ?? stepFromCommands(commands, 'facts')

  // Замок берётся **до первого шага**, а не внутри них: второе нажатие обязано не начать
  // работу вовсе, а не отказаться на середине. Прежде два нажатия внахлёст ложились в базу
  // параллельно, и Postgres отвечал на это взаимной блокировкой — отказом, из которого
  // человеку не понять ничего.
  const замок = await (deps.замок ?? замокВБазе)()
  if (!замок.взят) {
    await замок.отпустить()
    return {
      ok: false,
      занято: true,
      text:
        'Обновление уже идёт — его запустили секунду назад. Подождите, пока оно закончится, ' +
        'и обновите страницу: числа появятся сами. Второй раз нажимать не нужно.',
      stale: false,
    }
  }

  try {
    announce('Таблица')
    try {
      await ingestSheets()
    } catch (error) {
      return refusal('ingest:sheets', error)
    }

    announce('папка')
    try {
      await ingestAds()
    } catch (error) {
      return refusal('ingest:ads', error)
    }

    announce('разбор')
    try {
      await buildFacts()
    } catch (error) {
      return refusal('facts', error)
    }

    return { ok: true }
  } finally {
    // Отпускается в любом исходе: иначе один отказ запер бы кнопку до перезапуска процесса.
    await замок.отпустить()
  }
}
