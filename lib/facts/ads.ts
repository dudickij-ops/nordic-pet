/**
 * Реклама: площадка из имени файла и свёртка копий выгрузки.
 *
 * Обе задачи оставлены S3 нарочно. Сырой слой площадку не выводит и копию не опознаёт,
 * потому что и то, и другое — толкование: первое приписывает строке то, чего в источнике
 * нет, второе решает, какие деньги считать настоящими. Слой фактов и есть слой толкований,
 * и оба решения здесь видны — сырьё осталось нетронутым, у каждого факта есть адрес
 * исходной строки, а свёрнутый файл называется в отчёте команды.
 */

/** Строка выгрузки после разбора значений. */
export type AdsRow = {
  rowNo: number
  date: string
  campaign: string
  spend: string | null
}

/** Файл выгрузки: имя, выведенная площадка и разобранные строки. */
export type AdsFile = {
  fileName: string
  platform: string
  rows: AdsRow[]
}

/** Файл, признанный копией другого: чей он экземпляр и сколько строк не пошло в факты. */
export type FoldedFile = {
  fileName: string
  copyOf: string
  rows: number
}

/**
 * Площадка — часть имени файла до первого знака подчёркивания, в нижнем регистре.
 *
 * В источнике площадка не названа ни одной колонкой: она известна только по тому, из
 * какого кабинета выгрузку принесли, а это записано в имени файла. Имя, из которого
 * площадку не вывести, — отказ: рекламу без площадки не отнести ни к одной строке экрана,
 * а посчитанная в общей куче, она молча растворилась бы среди чужих денег.
 */
export function platformOf(fileName: string): string {
  const name = fileName.trim()
  const underscore = name.indexOf('_')
  const platform = underscore === -1 ? '' : name.slice(0, underscore).trim().toLowerCase()

  if (platform === '') {
    throw new Error(
      `из имени файла «${fileName}» не вывести площадку. Имя выгрузки начинается с названия ` +
        'площадки и знака подчёркивания: meta_2026-03.csv, google_2026-03.csv',
    )
  }

  return platform
}

/**
 * Отпечаток файла: площадка и упорядоченный список разобранных строк — **без адресов**.
 *
 * Без адресов нарочно. Экземпляр, у которого посреди файла лишняя пустая строка, несёт те
 * же значения и другие номера; опознавай мы копию по адресам, он копией бы не считался, и
 * расход площадки удвоился бы, выглядя при этом безупречно.
 *
 * Площадка в отпечаток входит, и это не «опознание по имени». Площадка — часть содержимого
 * строки факта, такая же, как дата и кампания. Без неё два файла разных кабинетов со
 * случайно совпавшими числами оказались бы копиями, и свёртка стёрла бы расход целой
 * площадки вместо лишнего экземпляра одной.
 */
function fingerprintOf(file: AdsFile): string {
  const rows = [...file.rows].sort((a, b) => a.rowNo - b.rowNo)
  return JSON.stringify([file.platform, rows.map((row) => [row.date, row.campaign, row.spend])])
}

/**
 * Какое имя переживает свёртку. Содержимое у копий одинаково, и выбор не меняет ни одного
 * числа — он меняет только то, какое имя файла будет стоять адресом у строк фактов. Нужен
 * он ради повторяемости: иначе адреса прыгали бы от прогона к прогону, а вместе с ними —
 * след, по которому число на экране возводится к строке источника.
 *
 * Сравнение по длине, потом по порядку кодовых знаков. Не по языковым правилам сравнения:
 * их порядок зависит от настроек машины, и на другой машине ответ был бы другим.
 */
function survivorOf(names: string[]): string {
  return [...names].sort((a, b) => (a.length !== b.length ? a.length - b.length : a < b ? -1 : 1))[0]
}

/**
 * Делит файлы папки на те, что идут в факты, и те, что признаны копиями.
 *
 * Копия — файл, у которого отпечаток совпал с отпечатком другого. Ни имя, ни время правки
 * на Диске в опознании не участвуют: время говорит о том, когда человек нажал кнопку, а не
 * о том, какие деньги настоящие. Перезалив тот же файл, он поменял бы «истину», не поменяв
 * ни цифры.
 *
 * Копии, совпавшие не целиком, а частично, здесь не ловятся — их ловит проверка делового
 * ключа при сборке: площадка, дата и кампания.
 */
export function foldCopies(files: AdsFile[]): { kept: AdsFile[]; folded: FoldedFile[] } {
  const groups = new Map<string, AdsFile[]>()
  for (const file of files) {
    const fingerprint = fingerprintOf(file)
    const group = groups.get(fingerprint)
    if (group === undefined) groups.set(fingerprint, [file])
    else group.push(file)
  }

  const kept: AdsFile[] = []
  const folded: FoldedFile[] = []

  for (const group of groups.values()) {
    const survivor = survivorOf(group.map((file) => file.fileName))
    for (const file of group) {
      if (file.fileName === survivor) kept.push(file)
      else folded.push({ fileName: file.fileName, copyOf: survivor, rows: file.rows.length })
    }
  }

  // Порядок ответа не зависит от порядка входа: он и сам по себе полезен для вывода,
  // и не даёт свёртке молча переставлять адреса строк между прогонами.
  kept.sort((a, b) => (a.fileName < b.fileName ? -1 : a.fileName > b.fileName ? 1 : 0))
  folded.sort((a, b) => (a.fileName < b.fileName ? -1 : a.fileName > b.fileName ? 1 : 0))

  return { kept, folded }
}
