import { GoogleAuth } from 'google-auth-library'

/**
 * Поход в Google — один на оба загрузчика.
 *
 * Здесь только чтение по адресу: ни способа задать метод, ни способа передать тело.
 * Запрос, меняющий что-нибудь у Google, этим договором просто не выражается.
 *
 * Способности не складываются в один объект нарочно. Загрузчик Таблицы собирает себе
 * доступ из одного `googleGet`, загрузчик Диска — из `googleGet` и `googleGetBytes`,
 * потому что список папки приезжает разобранным телом, а файл — байтами. Отдать обоим
 * один объект пошире значило бы выдать загрузчику Таблицы способность, которой он не
 * пользуется, — а лишнее право однажды окажется использованным.
 */

/** Ответ Google: код и уже разобранное тело. */
export type GoogleAnswer = {
  status: number
  body: unknown
}

/** Ответ Google байтами: код и содержимое файла, не тронутое раскодированием. */
export type GoogleBytesAnswer = {
  status: number
  bytes: Uint8Array
}

/** То, что отдаёт клиент Google: код и уже прочитанное тело в поле `data`. */
type GoogleRawAnswer = { status: number; data: unknown }

/**
 * Способ сходить в Google. Настоящий — авторизация из `google-auth-library`: она
 * подписывает запрос ключом служебного аккаунта и отдаёт не веб-ответ, а свой объект,
 * у которого тело уже прочитано и лежит в поле `data`.
 *
 * Форм вызова две, и обе — те, что объявляет сама библиотека: адресом строкой, либо
 * настройками одним объектом. Смешанной формы «адрес и настройки двумя доводами» у неё
 * нет: второй довод там — веб-настройки, а не её собственные. Живьём такой вызов
 * срабатывает, но опираться на неназванное поведение нельзя, и типы это показали.
 */
export type GoogleTransport = {
  fetch: {
    (url: string): Promise<GoogleRawAnswer>
    (options: { url: string; responseType: 'arraybuffer' }): Promise<GoogleRawAnswer>
  }
}

/**
 * Окружение, из которого берётся ключ служебного аккаунта.
 *
 * Обе переменные названы поимённо, хотя читается только первая: вторую читает сама
 * библиотека, и в договоре она стоит для того, чтобы вызывающий видел обе двери сразу
 * и не гадал, откуда взялся ключ, которым подписан запрос. Остальные имена приняты
 * россыпью, иначе настоящее `process.env` этому договору не подошло бы.
 */
type ОкружениеКлюча = {
  GOOGLE_SERVICE_ACCOUNT_KEY?: string
  GOOGLE_APPLICATION_CREDENTIALS?: string
  [остальные: string]: string | undefined
}

/**
 * Что человеку сделать руками, если ключ значением не разобрался. Довесок к каждому
 * отказу: отказ без указания, что чинить, — тупик, а не защита.
 */
const ЧТО_ПОЛОЖИТЬ =
  'положите в переменную GOOGLE_SERVICE_ACCOUNT_KEY содержимое JSON-файла ключа служебного' +
  ' аккаунта целиком, одной строкой, вместе с полями client_email и private_key'

/**
 * Авторизация ровно на одну названную область доступа.
 *
 * Ключ служебного аккаунта приходит одним из двух способов. Значением переменной
 * `GOOGLE_SERVICE_ACCOUNT_KEY` — этот способ старше, потому что на Vercel файла ключа
 * нет и путь к нему указать негде: без значения кнопка «Обновить данные» в бою до Google
 * не дошла бы вовсе. Иначе — прежним путём: библиотека читает файл сама по переменной
 * `GOOGLE_APPLICATION_CREDENTIALS`, и наш код ключа не касается.
 *
 * Окружение приходит доводом, чтобы старшинство можно было проверить, не трогая
 * настоящее окружение прогона. Библиотеке довод не передаётся: путь к файлу она читает
 * из настоящего `process.env` сама, и подменить его нам нечем.
 *
 * Разбор ключа отказывает сразу здесь, а не позже при `getClient()`: негодный ключ —
 * это ошибка настройки, и человек должен увидеть её в тот момент, когда её ещё можно
 * связать с тем, что он вписал в панель хостинга. В тексте отказа названы переменная и
 * недостающее поле, но ни куска содержимого: сообщение уезжает в журнал, секрет — нет.
 */
export function googleAuth(scope: string, env: ОкружениеКлюча = process.env): GoogleAuth {
  const значением = env.GOOGLE_SERVICE_ACCOUNT_KEY
  if (значением) {
    let разобранное: unknown
    try {
      разобранное = JSON.parse(значением)
    } catch {
      // Родной SyntaxError не назвал бы ни переменной, ни того, что делать, зато мог бы
      // притащить в сообщение кусок разбираемой строки — то есть кусок ключа.
      throw new Error(
        `GOOGLE_SERVICE_ACCOUNT_KEY: значение не разбирается как JSON — ${ЧТО_ПОЛОЖИТЬ}`,
      )
    }
    // `null` и число — тоже законный JSON, и без этой проверки поиск полей в них дал бы
    // не наш отказ, а чужую ошибку обращения к полю.
    if (typeof разобранное !== 'object' || разобранное === null) {
      throw new Error(`GOOGLE_SERVICE_ACCOUNT_KEY: значение не похоже на ключ — ${ЧТО_ПОЛОЖИТЬ}`)
    }
    const ключ = разобранное as { client_email?: string; private_key?: string }
    for (const поле of ['client_email', 'private_key'] as const) {
      if (!ключ[поле]) {
        throw new Error(`GOOGLE_SERVICE_ACCOUNT_KEY: в ключе нет поля ${поле} — ${ЧТО_ПОЛОЖИТЬ}`)
      }
    }
    return new GoogleAuth({
      scopes: [scope],
      credentials: { client_email: ключ.client_email, private_key: ключ.private_key },
    })
  }
  return new GoogleAuth({ scopes: [scope] })
}

/** Читает по адресу разобранное тело. */
export function googleGet(transport: GoogleTransport): (url: string) => Promise<GoogleAnswer> {
  return async (url) => {
    const response = await transport.fetch(url)
    return { status: response.status, body: response.data }
  }
}

/**
 * Читает по адресу байты.
 *
 * Вид ответа называется явно, и это не перестраховка: проверено походом на Диск —
 * без него тело файла `text/csv` приезжает уже раскодированной строкой. По строке
 * нельзя ни сверить размер с тем, что назвал Диск, ни увидеть метку порядка байтов,
 * ни отличить один конец строки от другого без догадок о том, что сделал транспорт.
 */
export function googleGetBytes(
  transport: GoogleTransport,
): (url: string) => Promise<GoogleBytesAnswer> {
  return async (url) => {
    const response = await transport.fetch({ url, responseType: 'arraybuffer' })
    return { status: response.status, bytes: new Uint8Array(response.data as ArrayBuffer) }
  }
}
