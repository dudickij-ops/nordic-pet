import { projectDatabaseUrl } from '../db-url.ts'

/**
 * Куда загрузчик пишет прямо сейчас. Среда называется словом и только словом:
 * ни из наличия ключей, ни из признаков хостинга она не выводится. Косвенный признак
 * однажды совпадёт не с тем, и запись уйдёт не в ту базу, ничем себя не выдав.
 */

/** Боевое соединение: шесть полей, ни одного на усмотрение драйвера. */
export type ProductionConnection = {
  host: string
  port: number
  user: string
  password: string
  database: string
  ssl: { rejectUnauthorized: true; ca?: string }
}

export type IngestTarget = {
  where: 'local' | 'production'
  /**
   * То, что отдаётся драйверу. Для локальной базы — адрес, уже пересобранный запертой
   * проверкой S1 из пяти проверенных частей. Для боевой — разобранные поля.
   */
  connection: string | ProductionConnection
  /** Строка «куда пишем» для вывода команды. Пароля в ней нет никогда. */
  label: string
}

/** Имя переменной, в которой среда названа. */
const TARGET = 'NORDIC_PET_DB_TARGET'

/** Имя переменной с адресом боевой базы. Живёт в переменных Vercel, не в git. */
const PRODUCTION_URL = 'SUPABASE_DB_URL'

/** Имя переменной с корневым сертификатом боевой базы, если он не публично доверенный. */
const PRODUCTION_CA = 'SUPABASE_DB_CA'

/**
 * Самые частые написания локального хоста. Список нужен ради внятного сообщения на
 * обычной опечатке, а не как замок: замок — проверка вида хоста ниже.
 */
const LOCAL_HOSTS = new Set(['127.0.0.1', 'localhost', '::1', '[::1]'])

/**
 * Хост боевой базы обязан выглядеть именем в сети, и это проверяется положительно.
 *
 * Перечень запрещённых написаний не поспевал дважды. Сначала мимо него прошла
 * перекодированная запись `%31%32%37.0.0.1`. Потом — и это опаснее — раскодирование
 * открыло путь к сокету: хост `/var/run/postgresql` драйвер считает не именем в сети,
 * а путём к сокету на этой же машине (проверено запуском, `isDomainSocket = true`), то
 * есть «бой» соединился бы с базой на машине разработчика. Написаний петлевого адреса
 * больше, чем можно перечислить: `127.1`, `2130706433`, `0x7f.0.0.1`, `127.000.000.001`,
 * `127.0.0.1.` — все приводят туда же.
 *
 * Поэтому проверяется не список запрещённого, а вид разрешённого: имя из меток
 * `[A-Za-z0-9-]`, разделённых точками, не меньше двух меток, и последняя метка содержит
 * хотя бы одну букву. Этим разом отсекаются пути к сокету (косая черта), голые адреса
 * во всех записях (последняя метка без букв), односложные имена вроде `localhost` и
 * записи IPv6 (скобки и двоеточия).
 *
 * Боевая база, названная голым адресом, отсекается заодно — и это верно: проверка
 * сертификата всё равно потребовала бы имени, на которое он выписан.
 *
 * **Чего эта проверка не делает.** Она смотрит на вид имени, а не на то, куда имя ведёт.
 * `localhost.localdomain`, `db.local`, `lvh.me` выглядят именами в сети и проходят, а
 * разрешаются в петлю. Замок здесь не этот, а обязательная проверка сертификата: у базы
 * на машине разработчика нет сертификата, выписанного на боевое имя. Узнавать, куда
 * ведёт имя, значило бы ходить в службу имён прямо из разбора адреса, а её ответ можно
 * поменять между проверкой и соединением.
 */
function looksLikeNetworkName(host: string): boolean {
  // Точка на конце — законная запись полного имени; служба имён и драйвер её принимают.
  const labels = host.replace(/\.$/, '').split('.')
  if (labels.length < 2) return false
  if (labels.some((label) => !/^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?$/.test(label))) return false
  return /[A-Za-z]/.test(labels[labels.length - 1])
}

/** Окружение процесса: имя переменной — значение. */
type Environment = Record<string, string | undefined>

/**
 * Раскодирует часть адреса. Драйвер с битой перекодировкой справляется — берёт значение
 * буквально, проверено запуском на имени `100%`. Наш разбор не имеет права падать сырым
 * `URIError` там, где драйвер работает.
 */
function decoded(value: string): string {
  try {
    return decodeURIComponent(value)
  } catch {
    return value
  }
}

/**
 * Разбирает адрес боевой базы на шесть полей, которые уйдут драйверу поимённо.
 *
 * **Строка запроса выбрасывается целиком, вместе с текстом после решётки.** Причина —
 * найденная проверкой кода дыра: разбор адреса нами и разбор адреса драйвером суть два
 * разных разборщика с разными правилами старшинства, и параметры строки запроса драйвер
 * клал поверх разобранного адреса. Проверено запуском: адрес `db.example.supabase.co:6543`
 * с хвостом `?host=127.0.0.1&user=postgres` соединял с локальной базой под другим
 * пользователем. Проверенный адрес и адрес соединения оказывались разными.
 *
 * Первым заходом хвост проверялся перечнем разрешённого. Это заплата: перечень стережёт
 * то, что известно сегодня, а разборщик драйвера меняется своей жизнью. Строки драйверу
 * больше не достаётся вовсе — переинтерпретировать нечего, и весь класс закрыт разом,
 * а не по каналу за раз.
 *
 * Отсюда же: что бы ни было написано в адресе про `sslmode`, оно не читается. Шифрование
 * решаем мы, и решаем одинаково — с проверкой сертификата.
 *
 * Ни одно сообщение об отказе не содержит адреса: в нём пароль, а ошибки уходят в журнал.
 */
export function productionConnection(url: string, env: Environment): ProductionConnection {
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    throw new Error(
      `${PRODUCTION_URL} не разбирается как адрес базы. Сам адрес здесь не показан: в нём пароль`,
    )
  }

  if (parsed.protocol !== 'postgres:' && parsed.protocol !== 'postgresql:') {
    throw new Error(
      `${PRODUCTION_URL} должен быть postgresql://…, а начинается с ${parsed.protocol}//…`,
    )
  }

  // Хост раскодируется перед сверкой со списком локальных: `%31%32%37.0.0.1` — это
  // тот же `127.0.0.1`, только записанный иначе. Без раскодировки отказ пришёл бы не
  // от нас, а от службы имён, и назвал бы не ту причину.
  const host = decoded(parsed.hostname)
  if (host === '') {
    throw new Error(`в ${PRODUCTION_URL} не назван хост`)
  }
  if (LOCAL_HOSTS.has(host)) {
    throw new Error(
      `${PRODUCTION_URL} указывает на локальный хост ${host}. Боевая база на локальном хосте ` +
        'не живёт: либо среда названа неверно, либо в переменной чужой адрес',
    )
  }
  if (!looksLikeNetworkName(host)) {
    throw new Error(
      `в ${PRODUCTION_URL} хост «${host}» не выглядит именем в сети. Боевая база называется ` +
        'именем, на которое выписан её сертификат, а не адресом и не путём к сокету',
    )
  }

  if (parsed.port === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван порт: другой порт на том же хосте — другой сервер`,
    )
  }

  const database = decoded(parsed.pathname.replace(/^\//, ''))
  if (database === '') {
    throw new Error(`в ${PRODUCTION_URL} не названа база`)
  }

  if (parsed.username === '') {
    throw new Error(`в ${PRODUCTION_URL} не назван пользователь`)
  }

  if (parsed.password === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван пароль: иначе он взялся бы из окружения или из файла ` +
        '.pgpass, и соединение зависело бы от того, что лежит на машине',
    )
  }

  // Шифрование с проверкой того, с кем говорим, а не просто «шифруй». Корневая берётся
  // системная; если у боевой базы своя — её подкладывают переменной окружения.
  const ca = env[PRODUCTION_CA]
  const ssl: ProductionConnection['ssl'] =
    ca === undefined || ca === '' ? { rejectUnauthorized: true } : { rejectUnauthorized: true, ca }

  return {
    host,
    port: Number(parsed.port),
    user: decoded(parsed.username),
    password: decoded(parsed.password),
    database,
    ssl,
  }
}

/**
 * Отвечает на вопрос «куда пишем» — и отказывается отвечать, если среда не названа.
 *
 * Загрузчику нужен то локальная база, то боевая, а замок `lib/db-url.ts` разрешает
 * единственную локальную: он писался для команды, которая базу сносит. Поэтому здесь
 * свой путь, а тот замок остаётся ровно таким, каким был.
 */
export function resolveIngestTarget(env: Environment = process.env): IngestTarget {
  const where = env[TARGET]

  if (where === 'local') {
    // Тот же адрес и та же жёсткая проверка, что у проверок и у пересоздания базы.
    const url = projectDatabaseUrl()
    const parsed = new URL(url)
    const database = parsed.pathname.replace(/^\//, '')
    return { where, connection: url, label: `цель: local, база ${database} на ${parsed.hostname}` }
  }

  if (where === 'production') {
    const url = env[PRODUCTION_URL]
    if (url === undefined || url === '') {
      throw new Error(
        `среда названа production, но ${PRODUCTION_URL} пуста. Адрес боевой базы живёт ` +
          'в переменных Vercel и никогда в git',
      )
    }
    const connection = productionConnection(url, env)
    return {
      where,
      connection,
      label: `цель: production, база ${connection.database} на ${connection.host}`,
    }
  }

  throw new Error(
    `${TARGET} обязана быть названа словом: local или production. ` +
      (where === undefined
        ? 'Сейчас она не задана вовсе'
        : `Сейчас в ней «${where}», а угадывать среду по косвенным признакам нельзя: ` +
          'ошибка вскроется записью не в ту базу'),
  )
}
