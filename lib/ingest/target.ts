import { Client } from 'pg'

import { projectDatabaseUrl } from '../db-url.ts'

/**
 * Куда загрузчик пишет прямо сейчас. Среда называется словом и только словом:
 * ни из наличия ключей, ни из признаков хостинга она не выводится. Косвенный признак
 * однажды совпадёт не с тем, и запись уйдёт не в ту базу, ничем себя не выдав.
 */
export type IngestTarget = {
  where: 'local' | 'production'
  /** Проверенный адрес базы. Для боя — вместе с паролем: печатать его нельзя. */
  url: string
  /** Строка «куда пишем» для вывода команды. Пароля в ней нет никогда. */
  label: string
}

/** Имя переменной, в которой среда названа. */
const TARGET = 'NORDIC_PET_DB_TARGET'

/** Имя переменной с адресом боевой базы. Живёт в переменных Vercel, не в git. */
const PRODUCTION_URL = 'SUPABASE_DB_URL'

/**
 * Локальный хост во всех написаниях, в которых его отдаёт разбор адреса.
 *
 * Список свой, а не взятый из `lib/db-url.ts`. Тот файл — замок на разрушающую команду
 * пересоздания базы, и он не меняется ни на строку, включая список того, что отдаёт наружу.
 * Три продублированных адреса дешевле, чем повод открыть тот файл.
 */
const LOCAL_HOSTS = new Set(['127.0.0.1', 'localhost', '::1', '[::1]'])

/** Окружение процесса: имя переменной — значение. */
type Environment = Record<string, string | undefined>

/**
 * Разбирает адрес боевой базы и отдаёт его неизменным, если он годен.
 *
 * Проверка зеркальна той, что стоит в `lib/db-url.ts`, но смотрит с другой стороны:
 * там разрешён ровно один локальный адрес, здесь запрещён любой локальный.
 *
 * Каждая часть обязана быть названа: драйвер `pg` читает те же переменные `PG*`, что и
 * libpq, и дочитывает ими недостающее. Проверено опытом — адрес без имени базы увёл
 * соединение в базу из `PGDATABASE`.
 *
 * **Но названного целиком адреса мало, и это выяснилось проверкой кода.** Разбор адреса
 * нами и разбор адреса драйвером — два разных разборщика с разными правилами старшинства:
 * параметры строки запроса драйвер кладёт ПОВЕРХ разобранного адреса. Проверено запуском
 * на установленном `pg`: адрес `db.example.supabase.co:6543` с хвостом
 * `?host=127.0.0.1&user=postgres` соединяет с `127.0.0.1` под пользователем `postgres`.
 * Проверенный адрес и адрес соединения оказывались разными.
 *
 * Перечислять запрещённые параметры бессмысленно — список известных обходов не бывает
 * полным, и ровно на этом обжёгся S1. Поэтому последнее слово здесь не за нашим разбором,
 * а за драйвером: у него спрашивают, что он понял, и сверяют с тем, что мы проверили.
 * Любой способ подмены — сегодняшний или завтрашний — упирается в это сравнение.
 *
 * Ни одно сообщение об отказе не содержит адреса: в нём пароль, а ошибки уходят в журнал.
 */
export function assertProductionDatabase(url: string): string {
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    throw new Error(
      `${PRODUCTION_URL} не разбирается как адрес базы. Сам адрес здесь не показан: в нём пароль`,
    )
  }

  if (parsed.protocol !== 'postgres:' && parsed.protocol !== 'postgresql:') {
    throw new Error(
      `${PRODUCTION_URL} должен быть postgresql://…, а начинается с ${parsed.protocol}//…`,
    )
  }

  const host = parsed.hostname
  if (host === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван хост: драйвер взял бы его из переменной PGHOST, ` +
        'и проверенным оказался бы один сервер, а соединение ушло бы на другой',
    )
  }
  if (LOCAL_HOSTS.has(host)) {
    throw new Error(
      `${PRODUCTION_URL} указывает на локальный хост ${host}. Боевая база на локальном хосте ` +
        `не живёт: либо среда названа неверно, либо в переменной чужой адрес`,
    )
  }

  if (parsed.port === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван порт: драйвер взял бы его из переменной PGPORT, ` +
        'а другой порт на том же хосте — другой сервер',
    )
  }

  const name = parsed.pathname.replace(/^\//, '')
  if (name === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не названа база: драйвер взял бы имя из переменной PGDATABASE, ` +
        'и запись ушла бы в базу, которую никто не проверял',
    )
  }

  if (parsed.username === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван пользователь: драйвер взял бы его из переменной PGUSER`,
    )
  }

  if (parsed.password === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван пароль: драйвер взял бы его из переменной PGPASSWORD ` +
        'или из файла .pgpass, и соединение зависело бы от того, что лежит на машине',
    )
  }

  // Адрес идёт по публичной сети. Отключённое шифрование означает пароль и данные
  // открытым текстом — это запрещено контрактом S1 и не обсуждается «на минутку».
  const sslmode = parsed.searchParams.get('sslmode')
  if (sslmode === null || sslmode === '') {
    throw new Error(
      `в ${PRODUCTION_URL} не назван sslmode: без него драйвер соединяется вообще без ` +
        'шифрования, и пароль уходит по публичной сети открытым текстом',
    )
  }
  if (sslmode === 'disable') {
    throw new Error(
      `в ${PRODUCTION_URL} стоит sslmode=disable: боевой адрес идёт по публичной сети, ` +
        'и без шифрования пароль и данные уходят открытым текстом',
    )
  }

  // В адресе не должно быть ничего, кроме sslmode. Это список разрешённого, а не
  // запрещённого, и разница здесь решающая: список запрещённого перечисляет обходы,
  // известные сегодня, и на этом обжёгся S1. Часть хвостов драйвер сегодня и правда
  // не читает — `dbname` и `service` он игнорирует, проверено запуском, — но `options`
  // доезжает до сервера целиком и меняет путь поиска, а значит и то, какая функция
  // отзовётся на `raw.replace_orders`. Завтрашняя версия драйвера прочтёт ещё что-нибудь.
  for (const [key] of parsed.searchParams) {
    if (key !== 'sslmode') {
      throw new Error(
        `в ${PRODUCTION_URL} есть лишний параметр «${key}». В адресе боевой базы ` +
          'разрешён только sslmode: всё прочее либо меняет соединение мимо проверки, ' +
          'либо будет менять его в следующей версии драйвера',
      )
    }
  }

  assertDriverReadsTheSameAddress(url, {
    host,
    port: parsed.port,
    database: name,
    user: decodeURIComponent(parsed.username),
  })

  return url
}

/** Части адреса в том виде, в каком их проверил наш разбор. */
export type AddressParts = {
  host: string
  port: string
  database: string
  user: string
}

/**
 * Спрашивает у драйвера, что он понял, и сверяет с тем, что проверили мы.
 *
 * Всё, проверенное выше, проверено нашим разборщиком, а соединение пойдёт по тому, что
 * понял его разборщик, — и правила у них разные. Проверено запуском: параметры строки
 * запроса драйвер кладёт поверх адреса, а текст после решётки наш разбор отрезает, тогда
 * как драйвер читает спрятанный там `?sslmode=disable` и соединяется без шифрования.
 *
 * Перечислять такие каналы бессмысленно — список известных обходов не бывает полным, на
 * этом обжёгся S1. Поэтому сверяется не список, а итог: если два прочтения разошлись
 * хоть в чём-то, адрес отвергается, каким бы способом расхождение ни было устроено.
 *
 * Ложных отказов не даёт: сверено запуском на хосте заглавными буквами, на пользователе
 * с точкой (так выглядит имя в пулере Supabase), на перекодированном пользователе и на
 * имени базы с дефисом — все четыре сошлись.
 */
export function assertDriverReadsTheSameAddress(url: string, checked: AddressParts): void {
  let seen: Client
  try {
    seen = new Client({ connectionString: url })
  } catch {
    throw new Error(`${PRODUCTION_URL} не принят драйвером базы как адрес соединения`)
  }

  const understood: Array<[string, unknown, unknown]> = [
    ['хост', seen.host, checked.host],
    ['порт', String(seen.port), checked.port],
    ['базу', seen.database, checked.database],
    ['пользователя', seen.user, checked.user],
  ]
  for (const [part, driver, ours] of understood) {
    if (driver !== ours) {
      throw new Error(
        `проверенный адрес и адрес соединения разошлись: мы проверили ${part} «${ours}», ` +
          `а драйвер понял «${driver}». Лишнему в адресе базы делать нечего`,
      )
    }
  }

  if (!seen.ssl) {
    throw new Error(
      `драйвер понял адрес как соединение без шифрования, хотя sslmode в нём назван. ` +
        'Так бывает, когда отключение спрятано после решётки: наш разбор её отрезает, ' +
        'а драйвер читает',
    )
  }
}

/** Хост и имя базы из адреса — то, что можно назвать вслух. Пароль сюда не попадает. */
function announceable(url: string): { host: string; database: string } {
  const parsed = new URL(url)
  return { host: parsed.hostname, database: parsed.pathname.replace(/^\//, '') }
}

/**
 * Отвечает на вопрос «куда пишем» — и отказывается отвечать, если среда не названа.
 *
 * Загрузчику нужен то локальная база, то боевая, а замок `lib/db-url.ts` разрешает
 * единственную локальную: он писался для команды, которая базу сносит. Поэтому здесь
 * свой путь, а тот замок остаётся ровно таким, каким был.
 */
export function resolveIngestTarget(env: Environment = process.env): IngestTarget {
  const where = env[TARGET]

  if (where === 'local') {
    // Тот же адрес и та же жёсткая проверка, что у проверок и у пересоздания базы.
    const url = projectDatabaseUrl()
    const { host, database } = announceable(url)
    return { where, url, label: `цель: local, база ${database} на ${host}` }
  }

  if (where === 'production') {
    const url = env[PRODUCTION_URL]
    if (url === undefined || url === '') {
      throw new Error(
        `среда названа production, но ${PRODUCTION_URL} пуста. Адрес боевой базы живёт ` +
          'в переменных Vercel и никогда в git',
      )
    }
    const checked = assertProductionDatabase(url)
    const { host, database } = announceable(checked)
    return { where, url: checked, label: `цель: production, база ${database} на ${host}` }
  }

  throw new Error(
    `${TARGET} обязана быть названа словом: local или production. ` +
      (where === undefined
        ? 'Сейчас она не задана вовсе'
        : `Сейчас в ней «${where}», а угадывать среду по косвенным признакам нельзя: ` +
          'ошибка вскроется записью не в ту базу'),
  )
}
