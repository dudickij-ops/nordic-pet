/**
 * Голова прогона против нынешней головы — решающая часть сторожа сдачи, без походов наружу.
 *
 * Обещание «ворота сняты на голове заявки» соврало дважды подряд, поэтому его утверждает команда,
 * а не текст: голова из строк прогона сверяется с нынешней, а всё, что менялось после прогона,
 * обязано быть только отчётом и самим файлом прогона — в них исполняемого кода нет.
 *
 * Вынесено в свой модуль в круге проверки кода 3: сама команда при импорте начинает работу, и
 * проверке было не за что ухватиться — сторож не мог покраснеть ни при какой правке. Походы в git
 * остались у вызывающего, сюда приходит уже снятый список тронутых путей. Поведение не менялось.
 *
 * Возвращает текст отказа или `null`, если сверка прошла.
 */
export function сверитьГолову(
  головаПрогона: string,
  сейчас: string,
  тронуто: string,
  файлы: { прогон: string; отчёт: string },
): string | null {
  if (сейчас === головаПрогона) return null
  const список = тронуто.trim()
  if (список === '') return null
  return (
    `прогон и ворота сняты на ${головаПрогона.slice(0, 7)}, а голова — ${сейчас.slice(0, 7)}, и между ними менялось не только ` +
    `«${файлы.прогон}» и «${файлы.отчёт}»:\n  ${список.split('\n').join('\n  ')}\nПрогоните ворота и приборы на этой голове.`
  )
}
