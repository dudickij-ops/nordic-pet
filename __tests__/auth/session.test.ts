import { afterEach, expect, test } from 'vitest'

import { SESSION_COOKIE, начеканить, проверить, секретПодписи } from '@/lib/auth/session'

/**
 * Подписанная cookie — задача 1 куска S6.
 *
 * Здесь всё чистое: на вход даются строка cookie, секрет и «сейчас» числом, на выходе —
 * состояние словом. Ни запроса Next, ни настоящих часов, ни окружения этим проверкам не
 * нужно, поэтому и подставлять нечего: время приходит доводом, а не подменяется.
 *
 * Секрет заведомо ненастоящий и назван так, чтобы это было видно с первого взгляда:
 * настоящие логин, пароль и секрет придумывает владелец и кладёт их в переменные проекта,
 * в код и в проверки они не попадают никогда.
 */

const СЕКРЕТ = 'не-настоящий-секрет-подписи-для-проверок-0123456789'
const СЕЙЧАС = Date.UTC(2026, 8, 3, 12, 0, 0)
const ДВЕНАДЦАТЬ_ЧАСОВ = 12 * 60 * 60 * 1000

test('имя cookie одно и то же во всех местах', () => {
  expect(SESSION_COOKIE).toBe('nordic_pet_session')
})

test('срок жизни cookie — двенадцать часов', () => {
  const { expiresAt } = начеканить(СЕЙЧАС, СЕКРЕТ)

  expect(expiresAt.getTime() - СЕЙЧАС).toBe(ДВЕНАДЦАТЬ_ЧАСОВ)
})

test('cookie с чужой подписью не пускает', () => {
  const { value } = начеканить(СЕЙЧАС, СЕКРЕТ)
  const последний = value.slice(-1)
  const подделанная = value.slice(0, -1) + (последний === 'a' ? 'b' : 'a')

  expect(проверить(value, СЕКРЕТ, СЕЙЧАС), 'своя cookie обязана пускать').toBe('годна')
  expect(проверить(подделанная, СЕКРЕТ, СЕЙЧАС)).toBe('подпись чужая')
  expect(проверить(value, 'совсем-другой-секрет', СЕЙЧАС)).toBe('подпись чужая')
})

test('подделанный срок годности узнаётся по подписи, а не принимается на веру', () => {
  const { value } = начеканить(СЕЙЧАС, СЕКРЕТ)
  const [версия, срок, подпись] = value.split('.')
  const продлённая = [версия, String(Number(срок) + 100 * ДВЕНАДЦАТЬ_ЧАСОВ), подпись].join('.')

  expect(проверить(продлённая, СЕКРЕТ, СЕЙЧАС)).toBe('подпись чужая')
})

test('просроченная cookie не пускает', () => {
  const { value } = начеканить(СЕЙЧАС, СЕКРЕТ)

  expect(проверить(value, СЕКРЕТ, СЕЙЧАС + ДВЕНАДЦАТЬ_ЧАСОВ - 1)).toBe('годна')
  expect(проверить(value, СЕКРЕТ, СЕЙЧАС + ДВЕНАДЦАТЬ_ЧАСОВ + 1)).toBe('просрочена')
})

test('нет cookie и порченая cookie — это отказ, а не проход', () => {
  expect(проверить(undefined, СЕКРЕТ, СЕЙЧАС)).toBe('нет cookie')
  expect(проверить('', СЕКРЕТ, СЕЙЧАС)).toBe('нет cookie')
  for (const порченая of ['совсем-не-cookie', 'v1.не-число.aabb', 'v1.123', 'v2.123.aabb'])
    expect(проверить(порченая, СЕКРЕТ, СЕЙЧАС), порченая).toBe('не разбирается')
})

test('неназванный секрет подписи — отказ, называющий переменную и что сделать', () => {
  expect(() => секретПодписи({})).toThrow(/NORDIC_PET_SESSION_SECRET/)
  expect(() => секретПодписи({})).toThrow(/Vercel/)
  expect(() => секретПодписи({ NORDIC_PET_SESSION_SECRET: '' })).toThrow(
    /NORDIC_PET_SESSION_SECRET/,
  )
  expect(секретПодписи({ NORDIC_PET_SESSION_SECRET: СЕКРЕТ })).toBe(СЕКРЕТ)

  // Без секрета проверить подпись нечем — и это отказ, а не «пускаем, раз проверить нечем».
  expect(проверить(начеканить(СЕЙЧАС, СЕКРЕТ).value, undefined, СЕЙЧАС)).toBe('нет секрета')
  expect(проверить(начеканить(СЕЙЧАС, СЕКРЕТ).value, '', СЕЙЧАС)).toBe('нет секрета')
})

const сказанноеВЖурнал: string[] = []
const прежнийЖурнал = { log: console.log, error: console.error, warn: console.warn, info: console.info }

afterEach(() => {
  Object.assign(console, прежнийЖурнал)
  сказанноеВЖурнал.length = 0
})

test('секрет подписи не попадает ни в текст отказа, ни в журнал', () => {
  for (const имя of ['log', 'error', 'warn', 'info'] as const) {
    console[имя] = (...части: unknown[]) => {
      сказанноеВЖурнал.push(части.map(String).join(' '))
    }
  }

  const { value } = начеканить(СЕЙЧАС, СЕКРЕТ)
  проверить(value, СЕКРЕТ, СЕЙЧАС)
  проверить('порченая', СЕКРЕТ, СЕЙЧАС)
  проверить(value, СЕКРЕТ, СЕЙЧАС + 100 * ДВЕНАДЦАТЬ_ЧАСОВ)
  try {
    секретПодписи({})
  } catch (отказ) {
    сказанноеВЖурнал.push((отказ as Error).message)
  }

  Object.assign(console, прежнийЖурнал)
  expect(сказанноеВЖурнал.join('\n')).not.toContain(СЕКРЕТ)
})
