import {
  ОБЩЕЕ_ВЕДРО,
  ОКНО_МИНУТ,
  ПОРОГ,
  адресПосетителя,
  войтиЧерезЗамок,
  состояниеЗамка,
  type СчётПопыток,
} from '@/lib/auth/attempts'
import { SESSION_COOKIE } from '@/lib/auth/session'

/**
 * Замок на подбор пароля — задача 2 куска S8.
 *
 * Подставляется **счёт**, а не сам вход: решения — запирать ли, считать ли попытку, обнулять ли
 * счёт — принимает настоящий код, а подставка только помнит, что ей отдали, теми же правилами,
 * что и таблица в базе. Сама таблица и её правило чистки проверяются отдельно, на настоящей
 * базе (`__tests__/db/meta.test.ts`).
 *
 * Логин, пароль и секрет — заведомо ненастоящие: настоящие придумывает владелец.
 */

const СРЕДА = {
  NORDIC_PET_LOGIN: 'не-настоящий-логин',
  NORDIC_PET_PASSWORD: 'не-настоящий-пароль-для-проверок',
  NORDIC_PET_SESSION_SECRET: 'не-настоящий-секрет-подписи-для-проверок-0123456789',
}
const СЕЙЧАС = Date.UTC(2026, 8, 5, 12, 0, 0)
const АДРЕС = '203.0.113.7'
const ДРУГОЙ_АДРЕС = '198.51.100.9'

function хранилище() {
  const записи: Array<{ имя: string; значение: string }> = []
  return {
    записи,
    set: (имя: string, значение: string) => {
      записи.push({ имя, значение })
    },
  }
}

/**
 * Счёт в памяти по тем же правилам, что и таблица: неудачи копятся по адресу, старше окна не
 * учитываются, удача стирает записи своего адреса.
 */
function счёт(начальные: Record<string, number[]> = {}): СчётПопыток & {
  записи: Record<string, number[]>
  вызовы: string[]
} {
  const записи: Record<string, number[]> = { ...начальные }
  const вызовы: string[] = []
  let часы = СЕЙЧАС
  return {
    записи,
    вызовы,
    неудачи: async (адрес) => {
      вызовы.push(`неудачи ${адрес}`)
      const свежие = (записи[адрес] ?? []).filter((к) => к >= часы - ОКНО_МИНУТ * 60_000)
      return {
        неудач: свежие.length,
        самаяРанняя: свежие.length === 0 ? null : new Date(Math.min(...свежие)),
      }
    },
    записатьНеудачу: async (адрес) => {
      вызовы.push(`записать ${адрес}`)
      записи[адрес] = [...(записи[адрес] ?? []), часы]
      часы += 1000
    },
    обнулить: async (адрес) => {
      вызовы.push(`обнулить ${адрес}`)
      delete записи[адрес]
    },
    закрыть: async () => {
      вызовы.push('закрыть')
    },
  }
}

/** Счёт, у которого отказывает названное действие, — остальное работает как обычно. */
function счётСОтказом(что: 'обнулить' | 'записатьНеудачу'): СчётПопыток {
  const рабочий = счёт()
  return {
    ...рабочий,
    обнулить: что === 'обнулить' ? async () => { throw new Error('база не ответила') } : рабочий.обнулить,
    записатьНеудачу:
      что === 'записатьНеудачу'
        ? async () => {
            throw new Error('база не ответила')
          }
        : рабочий.записатьНеудачу,
  }
}

function зависимости(с: СчётПопыток, адрес = АДРЕС, env: Record<string, string> = СРЕДА) {
  const где = хранилище()
  const открытий: string[] = []
  return {
    где,
    открытий,
    deps: {
      открытьСчёт: async () => {
        открытий.push('открыт')
        return с
      },
      env,
      now: СЕЙЧАС,
      адрес,
      cookies: где,
    },
  }
}

/** Десять неудач подряд с одного адреса, каждая — настоящим вызовом входа. */
async function десятьНеудач(с: СчётПопыток, адрес = АДРЕС): Promise<void> {
  for (let i = 0; i < ПОРОГ; i += 1) {
    const { deps } = зависимости(с, адрес)
    await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, 'не тот пароль', deps)
  }
}

describe('адрес посетителя', () => {
  test('одинокий адрес и есть ведро', () => {
    expect(адресПосетителя('203.0.113.7')).toBe('203.0.113.7')
  })

  /**
   * Список появляется только там, где начало строки задаёт сам посетитель. Взять из него первый
   * значило бы дать ему выбрать себе ведро и обойти замок; в общем ведре он запирает сам себя.
   */
  test('список адресов уходит в общее ведро целиком, а не разбирается по первому', () => {
    expect(адресПосетителя('203.0.113.7, 70.41.3.18')).toBe(ОБЩЕЕ_ВЕДРО)
  })

  // Молчаливого пропуска нет: без адреса счёт идёт общим ведром, и ведро названо.
  test('без заголовка счёт идёт по названному общему ведру, а не мимо счёта', () => {
    expect(адресПосетителя(null)).toBe(ОБЩЕЕ_ВЕДРО)
    expect(адресПосетителя('   ')).toBe(ОБЩЕЕ_ВЕДРО)
  })
})

/**
 * Главное утверждение куска. Проверять неверным паролем было бы бессмысленно: он не подходит и
 * без всякого замка. Доказывает запертую дверь только **годный** пароль, который не пустили.
 */
test('после десяти неудач годный пароль не пускает', async () => {
  const с = счёт()
  await десятьНеудач(с)

  const { где, deps } = зависимости(с)
  const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, deps)

  expect(исход.ok).toBe(false)
  expect(исход.ok === false ? исход.text : '').toMatch(/попыток/i)
  expect(где.записи, 'запертому cookie не выдаётся').toEqual([])
})

test('неудачная попытка идёт в счёт', async () => {
  const с = счёт()
  const { deps } = зависимости(с)

  await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, 'не тот пароль', deps)

  expect(с.записи[АДРЕС]).toHaveLength(1)
})

test('удачный вход обнуляет счёт: девять неудач, вход, снова девять — пускает', async () => {
  const с = счёт()
  for (let i = 0; i < ПОРОГ - 1; i += 1) {
    const { deps } = зависимости(с)
    await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, 'не тот пароль', deps)
  }

  const первый = зависимости(с)
  expect((await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, первый.deps)).ok).toBe(true)
  expect(с.записи[АДРЕС], 'удача стирает записи своего адреса').toBeUndefined()

  for (let i = 0; i < ПОРОГ - 1; i += 1) {
    const { deps } = зависимости(с)
    await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, 'не тот пароль', deps)
  }

  const второй = зависимости(с)
  const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, второй.deps)

  expect(исход).toEqual({ ok: true })
  expect(второй.где.записи.map((з) => з.имя)).toEqual([SESSION_COOKIE])
})

/**
 * Запирается тот, кто перебирает. Иначе замок стал бы способом выбить владельца из его же
 * дашборда: посторонний набрал бы десять неудач, и владелец остался бы снаружи.
 */
test('запирание с одного адреса не запирает другой', async () => {
  const с = счёт()
  await десятьНеудач(с)

  const { где, deps } = зависимости(с, ДРУГОЙ_АДРЕС)
  const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, deps)

  expect(исход).toEqual({ ok: true })
  expect(где.записи.map((з) => з.имя)).toEqual([SESSION_COOKIE])
})

/**
 * Шестнадцать минут — число здесь написано прямо, а не выведено из окна. Выведенное двигалось
 * бы вместе с окном, и проверка сравнивала бы величину сама с собой: слом «растянуть окно»
 * оставался бы зелёным. Найдено прибором сломов. Владелец назвал окно в пятнадцать минут —
 * значит шестнадцатиминутные неудачи обязаны запирание отпустить.
 */
test('по истечении окна вход снова работает', async () => {
  const давно = СЕЙЧАС - 16 * 60_000
  const с = счёт({ [АДРЕС]: Array.from({ length: ПОРОГ }, () => давно) })

  const { где, deps } = зависимости(с)
  const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, deps)

  expect(исход).toEqual({ ok: true })
  expect(где.записи.map((з) => з.имя)).toEqual([SESSION_COOKIE])
})

/**
 * Отказ ненастроенного входа говорит не о пароле, а о незаполненных переменных: человек,
 * который чинит настройку, не должен запирать себе дверь. Отличается по самому условию, а не
 * по тексту отказа — текст вещь переменная.
 */
test('ненастроенный вход счёт не двигает и до счёта вообще не доходит', async () => {
  const с = счёт()
  const { deps } = зависимости(с, АДРЕС, {})

  const исход = await войтиЧерезЗамок('кто-то', 'что-то', deps)

  expect(исход.ok).toBe(false)
  expect(исход.ok === false ? исход.text : '').toContain('NORDIC_PET_LOGIN')
  expect(с.вызовы, 'счёт не спрашивали и не двигали').toEqual([])
})

/**
 * Соединение с базой не открывается, пока не выяснилось, что вход вообще настроен. Прежде оно
 * открывалось безусловно: страница входа падала там, где человек как раз и чинит настройку, и
 * каждая попытка — даже запертая — стоила нового соединения. Найдено проверкой кода.
 */
test('ненастроенный вход не открывает соединения вовсе', async () => {
  const с = счёт()
  const { deps, открытий } = зависимости(с, АДРЕС, {})

  await войтиЧерезЗамок('кто-то', 'что-то', deps)

  expect(открытий).toEqual([])
})

/**
 * Счёт недоступен — падаем в сторону «не пускать». Пустить «на всякий случай» значило бы снять
 * замок ровно тогда, когда база лежит; отказ при этом говорит, что дело не в пароле.
 */
test('недоступный счёт — отказ, а не проход с годным паролем', async () => {
  const где = хранилище()
  const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, {
    открытьСчёт: async () => {
      throw new Error('соединение не открылось')
    },
    env: СРЕДА,
    now: СЕЙЧАС,
    адрес: АДРЕС,
    cookies: где,
  })

  expect(исход.ok).toBe(false)
  expect(исход.ok === false ? исход.text : '').toMatch(/не про ваш пароль/i)
  expect(где.записи, 'при недоступном счёте cookie не выдаётся').toEqual([])
})

/** Соединение закрывается в любом исходе, иначе каждая попытка оставляла бы его висеть. */
test('счёт закрывается и после удачи, и после неудачи', async () => {
  const с = счёт()

  const удача = зависимости(с)
  await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, удача.deps)
  expect(с.вызовы.at(-1)).toBe('закрыть')

  const неудача = зависимости(с)
  await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, 'не тот', неудача.deps)
  expect(с.вызовы.at(-1)).toBe('закрыть')
})

describe('решение о запирании', () => {
  test('без неудач не заперто', () => {
    expect(состояниеЗамка(0, null, СЕЙЧАС)).toEqual({ заперто: false, черезМинут: 0 })
  })

  test('на пороге заперто и названо, сколько ждать', () => {
    const минутуНазад = new Date(СЕЙЧАС - 60_000)
    expect(состояниеЗамка(ПОРОГ, минутуНазад, СЕЙЧАС)).toEqual({
      заперто: true,
      черезМинут: ОКНО_МИНУТ - 1,
    })
  })

  test('на единицу ниже порога ещё не заперто', () => {
    expect(состояниеЗамка(ПОРОГ - 1, new Date(СЕЙЧАС), СЕЙЧАС).заперто).toBe(false)
  })
})

/**
 * Сверка стоит вне перехвата: она выдаёт cookie, и накрыв её, мы однажды сказали бы «база не
 * ответила» человеку, у которого cookie уже в браузере. Здесь проверяется именно это: учёт после
 * удачи отказал, а вход остался удачным. Найдено проверкой кода.
 */
test('сбой учёта после удачного входа не превращает удачу в отказ', async () => {
  const { где, deps } = зависимости(счётСОтказом('обнулить'))

  const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, СРЕДА.NORDIC_PET_PASSWORD, deps)

  expect(исход).toEqual({ ok: true })
  expect(где.записи.map((з) => з.имя)).toEqual([SESSION_COOKIE])
})

/**
 * Незаписанная неудача — это выключенный замок: подбирающий видел бы обычное «пароль не тот» и
 * перебирал бы сколько угодно. Поэтому здесь падаем в сторону «не пускать» и говорим правду —
 * дело не в пароле. Найдено проверкой кода: прежде этот отказ проглатывался молча.
 */
test('незаписанная неудача — отказ про базу, а не обычное «пароль не тот»', async () => {
  const прежний = console.error
  console.error = () => {}
  try {
    const { где, deps } = зависимости(счётСОтказом('записатьНеудачу'))

    const исход = await войтиЧерезЗамок(СРЕДА.NORDIC_PET_LOGIN, 'не тот пароль', deps)

    expect(исход.ok).toBe(false)
    expect(исход.ok === false ? исход.text : '').toMatch(/не про ваш пароль/i)
    expect(где.записи, 'cookie при этом не выдаётся').toEqual([])
  } finally {
    console.error = прежний
  }
})
