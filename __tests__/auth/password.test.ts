import { expect, test } from 'vitest'

import { совпалоСкрытно } from '@/lib/auth/password'

/**
 * Сравнение пароля — задача 1 куска S6.
 *
 * Посимвольное сравнение выходит наружу по первому расхождению и тем выдаёт длину
 * совпавшего начала: подобрать пароль знак за знаком становится задачей на терпение, а не
 * на перебор. Поэтому сравниваются не строки, а их свёртки — постоянной длины и целиком.
 *
 * Проверяется это не замером времени (замер шаток и краснеет от чужой нагрузки на машине),
 * а наблюдением за самим сравнением: подставленное сравнение записывает, что ему дали.
 * Длина сравниваемого не зависит от длины ввода — значит выхода по первому расхождению нет.
 * Рядом идёт проверка настоящего пути, без всякой подставки.
 */

test('сравнение пароля стойко ко времени', () => {
  const вызовы: Array<[number, number]> = []
  const шпион = (левое: Buffer, правое: Buffer): boolean => {
    вызовы.push([левое.length, правое.length])
    return левое.equals(правое)
  }

  expect(совпалоСкрытно('коротко', 'очень-длинный-пароль-совершенно-иной-длины', шпион)).toBe(
    false,
  )
  expect(совпалоСкрытно('один-и-тот-же', 'один-и-тот-же', шпион)).toBe(true)
  expect(совпалоСкрытно('почти-тот-же-пароль', 'почти-тот-же-парол', шпион)).toBe(false)

  expect(
    вызовы,
    'сравниваются свёртки постоянной длины, а не сами строки: иначе длина сравнения выдаёт длину ввода',
  ).toEqual([
    [32, 32],
    [32, 32],
    [32, 32],
  ])
})

test('сравнение идёт настоящим стойким ко времени сравнением, без подставки', () => {
  expect(совпалоСкрытно('не-настоящий-пароль-для-проверок', 'не-настоящий-пароль-для-проверок')).toBe(
    true,
  )
  expect(совпалоСкрытно('не-настоящий-пароль-для-проверок', 'не-настоящий-пароль-для-проверки')).toBe(
    false,
  )
  expect(совпалоСкрытно('', '')).toBe(true)
  expect(совпалоСкрытно('', 'что-то')).toBe(false)
})
