import { expect, test } from 'vitest'

import { проверитьДоступ } from '@/lib/auth/guard'
import { начеканить } from '@/lib/auth/session'

/**
 * Второй слой — сторож пути, задача 4 куска S6.
 *
 * Чтение cookie подставляется доводом: сам сторож при этом настоящий, подставляется только
 * запрос вокруг него. Решение владельца, которому подчинено устройство: **нет запроса — нет
 * доступа**. Разрешающих веток в стороже нет ни одной — ни по среде, ни по признаку сборки,
 * ни по какому-либо иному внешнему признаку. Недостижимость такой ветки «сегодня» держится
 * на допущении о будущем, а не на устройстве.
 */

const СЕКРЕТ = 'не-настоящий-секрет-подписи-для-проверок-0123456789'
const СРЕДА = { NORDIC_PET_SESSION_SECRET: СЕКРЕТ }
const СЕЙЧАС = Date.UTC(2026, 8, 3, 12, 0, 0)
const ГОДНАЯ = начеканить(СЕЙЧАС, СЕКРЕТ).value

/** Так отказывает `cookies()` вне запроса Next — текст проверен запуском. */
const внеЗапроса = async (): Promise<string | undefined> => {
  throw new Error('`cookies` was called outside a request scope. Read more: https://nextjs.org/docs/messages/next-dynamic-api-wrong-context')
}

test('нет cookie в запросе — отказ, годная cookie — проход', async () => {
  await expect(проверитьДоступ(async () => undefined, СРЕДА, СЕЙЧАС)).resolves.toBe('отказать')
  await expect(проверитьДоступ(async () => ГОДНАЯ, СРЕДА, СЕЙЧАС)).resolves.toBe('пускать')
})

test('отсутствие запроса — это отказ, а не проход', async () => {
  // Ни одного довода про среду: если бы сторож пускал «когда среда не боевая», то
  // единственным, что стоит между посторонним и деньгами, оказалась бы настройка окружения.
  await expect(проверитьДоступ(внеЗапроса, СРЕДА, СЕЙЧАС)).resolves.toBe('отказать')
  await expect(проверитьДоступ(внеЗапроса, { ...СРЕДА, NODE_ENV: 'production' }, СЕЙЧАС)).resolves.toBe('отказать')
  await expect(проверитьДоступ(внеЗапроса, { ...СРЕДА, NODE_ENV: 'test' }, СЕЙЧАС)).resolves.toBe('отказать')
  await expect(проверитьДоступ(внеЗапроса, { ...СРЕДА, NODE_ENV: 'development' }, СЕЙЧАС)).resolves.toBe('отказать')
})

test('чужой отказ чтения cookie летит наружу, а не считается «нет запроса»', async () => {
  const другойОтказ = async (): Promise<string | undefined> => {
    throw new Error('хранилище cookie сломалось')
  }

  await expect(проверитьДоступ(другойОтказ, СРЕДА, СЕЙЧАС)).rejects.toThrow('хранилище cookie сломалось')
})

test('просроченная, подделанная и порченая cookie сторожа не проходят', async () => {
  const подделанная = ГОДНАЯ.slice(0, -1) + (ГОДНАЯ.endsWith('a') ? 'b' : 'a')

  await expect(проверитьДоступ(async () => подделанная, СРЕДА, СЕЙЧАС)).resolves.toBe('отказать')
  await expect(проверитьДоступ(async () => ГОДНАЯ, СРЕДА, СЕЙЧАС + 13 * 60 * 60 * 1000)).resolves.toBe('отказать')
  await expect(проверитьДоступ(async () => 'совсем-не-cookie', СРЕДА, СЕЙЧАС)).resolves.toBe('отказать')
  await expect(проверитьДоступ(async () => ГОДНАЯ, {}, СЕЙЧАС), 'нет секрета — нет доступа').resolves.toBe('отказать')
})
