import { expect, test } from 'vitest'

/**
 * Живая проверка закрытого доступа — взгляд снаружи.
 *
 * Каждый слой закрытия уже сторожится своей проверкой: и первый слой (`proxy.ts`), и
 * собственные сторожа страницы отчёта и серверного действия кнопки (`lib/auth/guard.ts`).
 * Но проверки частей не заменяют одного прохода целиком: они утверждают, что каждый
 * механизм на месте, и ни одна из них не смотрит на то, что вправду отдаёт боевой адрес
 * постороннему. Здесь идёт настоящий запрос по настоящему адресу — ни подставок, ни
 * собственного сервера, ни знания о том, как всё устроено внутри.
 *
 * Cookie здесь нет нарочно, и ни логина, ни пароля в файле нет вовсе: доказывается ровно
 * то, что видит человек без ключа, — что не видно ни экрана, ни чисел. Второй заход,
 * с ключом, — ручной и в этот файл не входит: доказать, что за дверью всё работает, можно
 * только глазами на экране.
 */

/**
 * Боевой адрес называется переменной окружения, а не вписывается сюда: он меняется без
 * нашего участия, и вписанный однажды означал бы, что проверка стучится не туда, а
 * отчитывается зелёным.
 *
 * Если адрес не назван, все три проверки обязаны покраснеть, а не пропуститься: проверка,
 * исчезающая вместе со средой, создаёт видимость проверенного там, где не проверено
 * ничего. Отсюда общая склейка: без неё «нет адреса» дошло бы до сети невнятной ошибкой
 * про `undefined/health`, из которой человеку не понять, что надо сделать.
 */
const БОЕВОЙ_АДРЕС = process.env.NORDIC_PET_LIVE_URL

/**
 * Адрес пути на боевом дашборде — и единственное место, где отсутствие адреса становится
 * понятным отказом.
 *
 * Слэш на конце срезается: адрес называет человек, и названный как `https://…/` он дал бы
 * `https://…//health` — другой путь, мимо списка исключений.
 */
function адрес(путь: string): string {
  expect(БОЕВОЙ_АДРЕС, 'назовите NORDIC_PET_LIVE_URL — боевой адрес дашборда').toBeTruthy()
  // До пустой строки дело не доходит: строкой выше проверка уже покраснела. Она здесь
  // только ради проверки типов — `expect` о типе переменной ничего не сообщает.
  return `${(БОЕВОЙ_АДРЕС ?? '').replace(/\/+$/, '')}${путь}`
}

/**
 * За перенаправлением проверка нарочно не идёт (`redirect: 'manual'`): пойдя за ним, она
 * получила бы 200 и страницу входа — то же самое, что вернул бы открытый настежь дашборд,
 * если бы кто-то завтра снял сторожа и оставил ссылку на вход. Разворот доказывается сам
 * по себе, кодом ответа и заголовком перехода.
 *
 * Полей отчёта в теле разворота не должно быть ни одного: тело — второй путь наружу, и
 * числа, случайно отрисованные до разворота, уехали бы посетителю вместе с ним. Взяты три
 * поля из трёх разных разделов экрана, а не одно.
 */
test('боевой адрес без cookie не показывает ни экрана, ни чисел', async () => {
  const ответ = await fetch(адрес('/'), { redirect: 'manual' })

  expect([302, 307, 308]).toContain(ответ.status)
  expect(ответ.headers.get('location')).toContain('/login')

  const тело = await ответ.text()
  for (const слово of ['Чистая выручка', 'Себестоимость', 'Обновить данные'])
    expect(тело, 'в ответе без cookie не должно быть ни одного поля отчёта').not.toContain(слово)
})

/**
 * Серверное действие — второй вход внутрь, мимо страницы: кнопка «Обновить данные» ходит
 * в Google и пишет в базу, и открытое действие означало бы, что эту работу может запустить
 * посторонний, ни одного экрана при этом не увидев.
 *
 * Имя действия заведомо несуществующее: своего имени у настоящего действия наружу нет, его
 * выдаёт сборка. Латиница здесь не вкус, а требование к заголовкам HTTP: их значения —
 * байты не выше 255, и кириллическое имя роняет проверку до всякой сети, собственной
 * ошибкой преобразования. Красное на своей ошибке не доказывает ничего.
 *
 * Утверждений два, и второе решает главное. Одного «не 200» мало: оно проходит на любой
 * беде — на пятисотке, на разорванном соединении, на опечатке в адресе, — а значит не
 * отличает наш отказ от чужого. Разворот на `/login` тем же кодом, что и у страницы,
 * показывает, что запрос завернул именно сторож доступа. Прежняя строка остаётся: она
 * говорит отдельно и прямо, что работа не сделана.
 */
test('серверное действие кнопки без cookie работы не делает', async () => {
  const ответ = await fetch(адрес('/'), {
    method: 'POST',
    redirect: 'manual',
    headers: { 'Next-Action': 'no-such-action' },
  })

  expect(ответ.status).not.toBe(200)
  expect([302, 307, 308]).toContain(ответ.status)
  expect(ответ.headers.get('location')).toContain('/login')
})

/**
 * Единственное исключение из списка закрытого. Его открытость доказывается наравне с
 * закрытостью остального: закрытая по недосмотру `/health` молча лишила бы нас
 * единственного способа отличить «выложилось новое» от «браузер показал старое».
 *
 * Ответ обязан быть не пустым, а с номером коммита — либо настоящим, либо честным
 * «неизвестно». Пустая страница с кодом 200 означала бы, что исключение открыто впустую.
 */
test('/health открыта и отдаёт номер коммита', async () => {
  const ответ = await fetch(адрес('/health'))

  expect(ответ.status).toBe(200)
  expect(await ответ.text()).toMatch(/[0-9a-f]{7,40}|неизвестно/)
})
