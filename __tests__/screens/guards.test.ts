import { describe, expect, test } from 'vitest'

import { ОтказСнимка, сверитьТекст, сверитьТемы, сверитьШирину } from '@/docs/screens/guards'

/**
 * Три отказа генератора снимков — кусок S10.
 *
 * **Почему проверки утверждают вид отказа, а не текст сообщения.** Красное на чужой ошибке
 * ничего не доказывает: сломанный код почти всегда что-нибудь роняет, и проверка, ловящая любую
 * ошибку, зазеленела бы от совсем другой беды. Поэтому каждая проверка требует, чтобы отказ был
 * **наш** (`ОтказСнимка`) и чтобы его вид был именно тот.
 *
 * **Почему проверяется ещё и текст.** Отказ, который человек может исправить руками, обязан
 * называть, что именно сделать, — иначе это тупик, а не защита. Утверждается не формулировка
 * целиком, а то, что нужное слово в ней есть.
 *
 * **Чего эти проверки не доказывают.** Что генератор эти отказы вправду зовёт. Они сторожат сами
 * отказы, а не место их вызова; вызов виден в `docs/screens/generate.tsx` и доказывается тем,
 * что прогон снимков проходит.
 */

/** Ловит отказ и настаивает, что он наш. Чужую ошибку эта обёртка не пропустит. */
function отказ(действие: () => void): ОтказСнимка {
  try {
    действие()
  } catch (ошибка) {
    if (ошибка instanceof ОтказСнимка) return ошибка
    throw new Error(`ожидался наш отказ, а пришло: ${String(ошибка)}`)
  }
  throw new Error('ожидался отказ, а вызов прошёл молча')
}

test('генератор отказывает, когда светлый и тёмный снимок совпали', () => {
  const пойман = отказ(() => сверитьТемы('obychnyy', 'aaaa1111', 'aaaa1111'))

  expect(пойман.вид).toBe('темы совпали')
  expect(пойман.message, 'отказ называет состояние').toContain('obychnyy')
  expect(пойман.message, 'отказ говорит, куда смотреть').toContain('prefers-color-scheme: dark')

  expect(
    () => сверитьТемы('obychnyy', 'aaaa1111', 'bbbb2222'),
    'разные снимки проходят молча',
  ).not.toThrow()
})

test('генератор отказывает, когда страница свёрстана не на запрошенной ширине', () => {
  const пойман = отказ(() => сверитьШирину('03-obychnyy-uzkiy.png', 390, 500))

  expect(пойман.вид).toBe('ширина не та')
  expect(пойман.message, 'отказ называет обе ширины').toContain('390')
  expect(пойман.message).toContain('500')
  expect(пойман.message, 'отказ говорит, что делать').toContain('Просите 500 или шире')

  expect(
    () => сверитьШирину('03-obychnyy-uzkiy.png', 500, 500),
    'совпавшая ширина проходит молча',
  ).not.toThrow()
})

describe('видимый текст снимка', () => {
  const было = ['Оборот', '18 764,00 €', 'Скидки']

  test('генератор отказывает, когда видимый текст снимка разошёлся с прежним', () => {
    const пойман = отказ(() => сверитьТекст('obychnyy.html', было, ['Оборот', '1,00 €', 'Скидки']))

    expect(пойман.вид).toBe('текст разошёлся')
    expect(пойман.message, 'отказ называет снимок').toContain('obychnyy.html')
    expect(пойман.message, 'отказ называет строку расхождения').toContain('строке 2')
    expect(пойман.message, 'отказ показывает, что было').toContain('18 764,00 €')
    expect(пойман.message, 'отказ показывает, что стало').toContain('1,00 €')
    expect(пойман.message, 'отказ говорит, что это находка к владельцу').toContain('владельцу')
  })

  /**
   * Пропажа строки — не то же самое, что её подмена: длины списков расходятся, и на месте
   * пропавшей нет ничего. Отдельная проверка нужна потому, что сравнение по длине и сравнение
   * по содержимому — два разных утверждения, и одно из них однажды снимут.
   */
  test('пропажа строки с экрана тоже разводит текст', () => {
    const пойман = отказ(() => сверитьТекст('obychnyy.html', было, ['Оборот', '18 764,00 €']))

    expect(пойман.вид).toBe('текст разошёлся')
    expect(пойман.message).toContain('Было строк 3, стало 2')
    expect(пойман.message, 'на месте пропавшей строки — «ничего»').toContain('ничего')
  })

  test('совпавший текст проходит молча', () => {
    expect(() => сверитьТекст('obychnyy.html', было, [...было])).not.toThrow()
  })
})
