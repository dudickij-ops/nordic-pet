import { expect, test } from 'vitest'

import {
  ОтказСнимка,
  сверитьВеличиныТем,
  сверитьВыходБраузера,
  сверитьЕдинственностьВеличин,
  сверитьКартинки,
  сверитьРазметку,
  сверитьШирину,
  сверитьЭталон,
} from '@/docs/screens/guards'

/**
 * Семь отказов генератора снимков — кусок S10, сторона самих отказов.
 *
 * **Почему проверки утверждают вид отказа, а не текст сообщения.** Красное на чужой ошибке
 * ничего не доказывает: сломанный код почти всегда что-нибудь роняет, и проверка, ловящая любую
 * ошибку, зазеленела бы от совсем другой беды. Поэтому каждая проверка требует, чтобы отказ был
 * **наш** (`ОтказСнимка`) и чтобы вид был именно тот.
 *
 * **Почему проверяется ещё и текст.** Отказ, который человек может исправить руками, обязан
 * называть, что именно сделать, — иначе это тупик, а не защита. Утверждается не формулировка
 * целиком, а то, что нужное указание в ней есть.
 *
 * **Чего эти проверки не доказывают, и где это доказано.** Что генератор эти отказы вправду
 * зовёт. Первая редакция куска на этом и погорела: два сторожа из трёх были написаны и не
 * работали. Место вызова сторожится соседним файлом — `pipeline.test.ts`, — который гоняет
 * распорядителей генератора целиком. Исключение одно и названо вслух: `сверитьВыходБраузера`
 * зовётся там, где нужен настоящий браузер, и его место вызова обычным прогоном не проверяется.
 */

/** Ловит отказ и настаивает, что он наш. Чужую ошибку эта обёртка не пропустит. */
function отказ(действие: () => unknown): ОтказСнимка {
  try {
    действие()
  } catch (ошибка) {
    if (ошибка instanceof ОтказСнимка) return ошибка
    throw new Error(`ожидался наш отказ, а пришло: ${String(ошибка)}`)
  }
  throw new Error('ожидался отказ, а вызов прошёл молча')
}

test('отказ: у снимка нет принятого эталона', () => {
  const пойман = отказ(() => сверитьЭталон('obychnyy.html', null))

  expect(пойман.вид).toBe('нет эталона')
  expect(пойман.message, 'отказ называет снимок').toContain('obychnyy.html')
  expect(пойман.message, 'отказ говорит, что делать').toContain('внести в опись')

  expect(сверитьЭталон('obychnyy.html', '<html></html>'), 'эталон возвращается как есть').toBe(
    '<html></html>',
  )
})

test('отказ: разметка снимка разошлась с эталоном', () => {
  const пойман = отказ(() =>
    сверитьРазметку('obychnyy.html', '<p>18 764,00 €</p>', '<p>1,00 €</p>'),
  )

  expect(пойман.вид).toBe('разметка разошлась')
  expect(пойман.message, 'отказ называет снимок').toContain('obychnyy.html')
  expect(пойман.message, 'отказ показывает, что было').toContain('18 764,00 €')
  expect(пойман.message, 'отказ показывает, что стало').toContain('1,00 €')
  expect(пойман.message, 'отказ говорит, что это находка к владельцу').toContain('владельцу')

  expect(() => сверитьРазметку('obychnyy.html', '<p>же</p>', '<p>же</p>')).not.toThrow()
})

/**
 * Отдельный случай той же сверки, и он — причина, по которой сверка перестала смотреть только на
 * видимый текст. Доля честности уходит в полосу величиной `--share`, а не словами: правка,
 * переносящая число из текста в геометрию, прошла бы текстовую сверку насквозь.
 */
test('отказ ловит расхождение в атрибуте, а не только в тексте', () => {
  const пойман = отказ(() =>
    сверитьРазметку('obychnyy.html', '<div style="--share:80.3%"></div>', '<div style="--share:5%"></div>'),
  )

  expect(пойман.вид).toBe('разметка разошлась')
  expect(пойман.message, 'сказано, что видимый текст тот же').toContain('Видимый текст тот же')
  expect(пойман.message, 'показан кусок разметки').toContain('--share')
})

test('отказ: величины светлой и тёмной темы совпали', () => {
  const пойман = отказ(() => сверитьВеличиныТем('таблица стилей', '--bg:#fff', '--bg:#fff'))

  expect(пойман.вид).toBe('темы совпали')
  expect(пойман.message, 'отказ говорит, куда смотреть').toContain('prefers-color-scheme: dark')

  expect(() => сверитьВеличиныТем('таблица стилей', '--bg:#fff', '--bg:#000')).not.toThrow()
})

test('отказ: блоков величин в области не один', () => {
  const пойман = отказ(() => сверитьЕдинственностьВеличин('светлая тема', 2))

  expect(пойман.вид).toBe('величины не разобраны')
  expect(пойман.message, 'отказ называет число найденного').toContain('найдено 2')
  expect(пойман.message, 'отказ называет границу разбора').toContain('правил языка стилей не')

  expect(() => сверитьЕдинственностьВеличин('светлая тема', 1)).not.toThrow()
})

test('отказ: страница свёрстана не на запрошенной ширине', () => {
  const пойман = отказ(() => сверитьШирину('03-obychnyy-uzkiy.png', 390, 500))

  expect(пойман.вид).toBe('ширина не та')
  expect(пойман.message, 'отказ называет обе ширины').toContain('390')
  expect(пойман.message).toContain('500')
  expect(пойман.message, 'отказ говорит, что делать').toContain('Просите 500 или шире')

  expect(() => сверитьШирину('03-obychnyy-uzkiy.png', 500, 500)).not.toThrow()
})

test('отказ: светлая и тёмная картинки совпали', () => {
  const пойман = отказ(() => сверитьКартинки('obychnyy 1280×1700', 'aaaa1111', 'aaaa1111'))

  expect(пойман.вид).toBe('картинки совпали')
  expect(пойман.message, 'отказ называет состояние').toContain('obychnyy 1280×1700')
  expect(пойман.message, 'отказ говорит, что проверить').toContain('тёмные величины')

  expect(() => сверитьКартинки('obychnyy 1280×1700', 'aaaa1111', 'bbbb2222')).not.toThrow()
})

test('отказ: браузер вернул не ноль', () => {
  const пойман = отказ(() => сверитьВыходБраузера('снимок «01.png»', 1, 'no such file'))

  expect(пойман.вид).toBe('браузер отказал')
  expect(пойман.message, 'отказ называет, что делалось').toContain('01.png')
  expect(пойман.message, 'отказ передаёт слова браузера').toContain('no such file')
  expect(пойман.message, 'отказ говорит, что делать').toContain('Поставьте')

  expect(
    отказ(() => сверитьВыходБраузера('снимок «01.png»', null)).message,
    'браузера не нашлось вовсе — тоже наш отказ',
  ).toContain('вернул ничего')

  expect(() => сверитьВыходБраузера('снимок «01.png»', 0)).not.toThrow()
})
