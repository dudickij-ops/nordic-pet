test('отказ: искомого в таблице стилей найдено не одно', () => {
  const пойман = отказ(() => сверитьЕдинственность('блоков величин в светлой теме', 2))

  expect(пойман.вид).toBe('величины не разобраны')
  expect(пойман.message, 'отказ называет число найденного').toContain('найдено 2')
  expect(пойман.message, 'отказ называет границы разбора целиком').toContain('границы целиком')
  expect(
    пойман.message,
    'отказ называет то, чего разбор не видит вовсе',
  ).toContain('на `:root`, он не видит вовсе')
  expect(
    пойман.message,
    'отказ называет незакрытую скобку — на неё приходится тот же вид отказа',
  ).toContain('закрыта ли фигурная скобка')
  expect(
    пойман.message,
    'отказ называет скобку внутри значения — на ней разбор спотыкался',
  ).toContain('только в кавычках')

  expect(() => сверитьЕдинственность('блоков величин в светлой теме', 1)).not.toThrow()
})

