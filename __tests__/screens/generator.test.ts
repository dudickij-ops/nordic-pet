/**
 * Величины, стоящие **после** блока тёмной темы, прежде молча уезжали в тёмную тему: «тёмной
 * областью» считалось всё от начала медиазапроса до конца файла. Найдено проверкой кода.
 */
test('разбор берёт тёмные величины изнутри медиазапроса, а не после него', () => {
  const css =
    ':root { --bg: #ffffff; }\n' +
    '@media (prefers-color-scheme: dark) { :root { --bg: #292929; } }\n' +
    'p { color: red; }\n'

  expect(величиныТемы(css).тёмная).toBe('--bg: #292929;')
  expect(величиныТемы(css).светлая).toBe('--bg: #ffffff;')
})

/**
 * Фигурная скобка внутри значения прежде обрывала набор величин посреди объявления, и обрывала
 * молча: `--q: "}"` уносил с собой всё, что стояло дальше. Найдено проверкой кода.
 */
test('разбор не спотыкается о фигурную скобку внутри кавычек', () => {
  const css =
    ':root { --bg: #ffffff; --q: "}"; --page: 72rem; }\n' +
    '@media (prefers-color-scheme: dark) { :root { --bg: #292929; } }\n'

  expect(величиныТемы(css).светлая, 'величина после скобки в кавычках не потерялась').toContain(
    '--page: 72rem',
  )
  expect(величиныТемы(css).светлая, 'кавычки в значение возвращаются как есть').toContain('"}"')
})

test('разбор не считает :root, названный в комментарии', () => {
  const css =
    '/* величины лежат в :root { } и больше нигде */\n' +
    ':root { --bg: #ffffff; }\n' +
    '@media (prefers-color-scheme: dark) { :root { --bg: #292929; } }\n'

  expect(величиныТемы(css).светлая).toBe('--bg: #ffffff;')
})

