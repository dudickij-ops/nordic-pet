/**
 * Генератор снимков — проверка **настоящего пути**, от начала до конца.
 *
 * **Зачем этот файл существует.** Два круга проверки кода подряд нашли одно и то же: сторож
 * написан, а на настоящем пути молчит. Сперва сторожей звали из мест, которых не касалась ни одна
 * проверка. Потом сторожей вынесли в чистых распорядителей и накрыли проверками распорядителей —
 * а вызов самих распорядителей из `собратьСнимки` снова остался недоказанным. Беда не двигалась,
 * двигалась граница проверенного.
 *
 * Поэтому проверяется `собратьСнимки` целиком. Браузер приходит доводом, каталог эталонов и путь
 * к таблице стилей — тоже; всё прочее настоящее, включая отрисовку разметки приложения. Слом,
 * выедающий тело любого сторожа, красит проверку отсюда — и это доказывает, что сторож позван
 * оттуда, откуда его зовут в работе.
 *
 * **Чего здесь нет и это названо.** Настоящего браузера. Значит место вызова
 * `сверитьВыходБраузера` — внутри `настоящийБраузер` — этой проверкой не достаётся; оно проходит
 * только `npm run screens`. Второе такое же место — вызов `сверитьНаличиеПар` внутри разбора
 * картинок: чтобы пар не осталось, пришлось бы менять опись. Исключений два, а не одно, как
 * утверждала прежняя редакция этого места.
 */

const ВРЕМЕННЫЕ: string[] = []

/** Временный каталог, который сам за собой убирает. */
function временный(имя: string): string {
  const путь = mkdtempSync(join(tmpdir(), `${имя}-`))
  ВРЕМЕННЫЕ.push(путь)
  return путь
}

afterEach(() => {
  while (ВРЕМЕННЫЕ.length > 0) rmSync(ВРЕМЕННЫЕ.pop() as string, { recursive: true, force: true })
})

/** Ловит отказ и настаивает, что он наш. */
function отказ(действие: () => unknown): ОтказСнимка {
  try {
    действие()
  } catch (ошибка) {
    if (ошибка instanceof ОтказСнимка) return ошибка
    throw new Error(`ожидался наш отказ, а пришло: ${String(ошибка)}`)
  }
  throw new Error('ожидался отказ, а вызов прошёл молча')
}

/**
 * Подставной браузер.
 *
 * На замер отвечает заголовком с шириной, на снимок — файлом, содержимое которого выведено из
 * страницы. Значит светлая и тёмная картинки различаются ровно тогда, когда различаются страницы,
 * — то же самое, что делает настоящий браузер, только без него.
 */
function подставной(
  опции: {
    ширина?: number
    безЗаголовка?: boolean
    одинаковыеКартинки?: boolean
    безКартинки?: boolean
  } = {},
): Браузер {
  return (_зачем, доводы) => {
    const снимок = доводы.find((д) => д.startsWith('--screenshot='))
    const страница = (доводы[доводы.length - 1] ?? '').replace('file://', '')

    if (снимок !== undefined) {
      if (опции.безКартинки === true) return ''
      const из = опции.одинаковыеКартинки === true ? 'одно и то же' : readFileSync(страница, 'utf8')
      writeFileSync(снимок.slice('--screenshot='.length), createHash('sha256').update(из).digest('hex'))
      return ''
    }

    if (опции.безЗаголовка === true) return '<html><head></head></html>'
    const размер = /--window-size=(\d+),/.exec(доводы.join(' '))
    const ширина = опции.ширина ?? Number(размер?.[1] ?? 0)
    return `<html><head><title>${ширина}</title></head></html>`
  }
}

/** Каталог эталонов — копия принятых страниц, которую можно портить. */
function эталоны(): string {
  const каталог = временный('эталоны')
  cpSync(new URL('../../docs/screens', import.meta.url).pathname, каталог, { recursive: true })
  return каталог
}

test('генератор собирает снимки на настоящем пути', () => {
  const куда = временный('снимки')
  const итог = собратьСнимки({ куда, толькоПары: true, браузер: подставной() })

  expect(итог.страницы, 'две страницы обычного экрана').toEqual(['obychnyy.html', 'obychnyy-dark.html'])
  expect(итог.картинки, 'три картинки пары').toHaveLength(3)
  expect(readFileSync(join(куда, 'obychnyy.html'), 'utf8'), 'страница вправду легла на диск').toContain(
    'Nordic Pet',
  )
})

