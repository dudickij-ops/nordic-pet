import { expect, test } from 'vitest'

import { разрывВремени } from '@/breaks/time-gap'
import { сверитьГолову } from '@/scripts/head-match'

/**
 * Сторожа приборов сдачи — кусок S11, круг проверки кода 3.
 *
 * Оба сторожа жили внутри команд, которые при импорте сразу начинают работу: проверке было не за
 * что ухватиться, и покраснеть они не могли ни при какой правке. Решающая часть каждого вынесена в
 * свой модуль без изменения поведения, и здесь у неё есть свой слом.
 */

test('разрыв времени: пока сломов меньше трёх, середины нет и прибор молчит', () => {
  expect(разрывВремени(100000, [])).toBeNull()
  expect(разрывВремени(100000, [20, 20])).toBeNull()
})

test('разрыв времени: обычная длительность при живой середине — не разрыв', () => {
  expect(разрывВремени(25, [20, 21, 22, 19])).toBeNull()
})

test('разрыв времени: слом, переживший сон машины, — отказ, и он назван своими словами', () => {
  const ответ = разрывВремени(3600, [20, 21, 22, 19])
  expect(ответ).not.toBeNull()
  expect(ответ).toContain('разрыв времени')
  expect(ответ).toContain('3600 с')
  expect(ответ).toContain('21 с')
})

test('разрыв времени: пол в минуту держит короткие сломы', () => {
  // Середина 1 с, десять середин — 10 с; без пола слом в 30 с читался бы разрывом.
  expect(разрывВремени(30, [1, 1, 1, 1])).toBeNull()
  expect(разрывВремени(61, [1, 1, 1, 1])).not.toBeNull()
})

const ФАЙЛЫ = { прогон: 'docs/сверка/прогон.md', отчёт: 'docs/ОТЧЁТ.md' }
const ГОЛОВА = 'a'.repeat(40)
const ДРУГАЯ = 'b'.repeat(40)

test('сверка головы: голова прогона совпала с нынешней — молчит, что бы ни лежало в списке', () => {
  expect(сверитьГолову(ГОЛОВА, ГОЛОВА, '', ФАЙЛЫ)).toBeNull()
  // Круг проверки кода 4: пустой список молчит и без раннего выхода, поэтому он ничего не сторожил.
  // Утверждение теперь именно про ранний выход: та же голова — жаловаться не на что, даже когда
  // список путей не пуст.
  expect(сверитьГолову(ГОЛОВА, ГОЛОВА, 'lib/metrics/sql.ts\napp/page.tsx\n', ФАЙЛЫ)).toBeNull()
})

test('сверка головы: голова другая, но менялись только отчёт и файл прогона — молчит', () => {
  expect(сверитьГолову(ГОЛОВА, ДРУГАЯ, '\n', ФАЙЛЫ)).toBeNull()
})

test('сверка головы: после прогона менялся код — отказ, и он говорит, что делать', () => {
  const ответ = сверитьГолову(ГОЛОВА, ДРУГАЯ, 'lib/metrics/sql.ts\napp/page.tsx\n', ФАЙЛЫ)
  expect(ответ).not.toBeNull()
  expect(ответ).toContain('aaaaaaa')
  expect(ответ).toContain('bbbbbbb')
  expect(ответ).toContain('lib/metrics/sql.ts')
  expect(ответ).toContain('app/page.tsx')
  expect(ответ).toContain('Прогоните ворота и приборы на этой голове')
})
