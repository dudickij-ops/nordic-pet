import { renderToStaticMarkup } from 'react-dom/server'
import { expect, test, vi } from 'vitest'

import { RefreshView } from '@/app/refresh-panel'
import { ТЕКСТ_ДАННЫЕ_НЕ_ЧИТАЮТСЯ as ТЕКСТ_СТРАНИЦЫ } from '@/app/page'
import { ТЕКСТ_ДАННЫЕ_НЕ_ЧИТАЮТСЯ as ТЕКСТ_МЕТРИК } from '@/lib/metrics/report'

/**
 * Что человек вправду видит — задачи 4 и 6 куска S8.
 *
 * Прежде исход «обновление уже идёт» проверялся только возвращённым значением: убери его показ с
 * экрана — и не покраснело бы ничто. Найдено проверкой кода.
 */

vi.mock('next/cache', () => ({ revalidatePath: vi.fn() }))

test('«обновление уже идёт» человек видит на экране, а не только в возвращённом значении', () => {
  const разметка = renderToStaticMarkup(
    <RefreshView
      outcome={{ ok: false, занято: true, text: 'Обновление уже идёт — подождите.', stale: false }}
      pending={false}
    >
      <p>числа</p>
    </RefreshView>,
  )

  expect(разметка).toMatch(/уже идёт/i)
  expect(разметка, 'это не отказ шага — шага у него нет').not.toMatch(/Шаг «/)
})

test('отказ шага по-прежнему называет свой шаг', () => {
  const разметка = renderToStaticMarkup(
    <RefreshView
      outcome={{ ok: false, step: 'папка', text: 'папка не прочиталась', stale: true }}
      pending={false}
    >
      <p>числа</p>
    </RefreshView>,
  )

  expect(разметка).toMatch(/Шаг «папка»/)
})

/**
 * Текст отказа «данные не читаются» написан в двух местах: страница не берёт на экран ничего из
 * сообщения отказа, и это единственный способ сделать утечку адреса базы невозможной по
 * построению. Раз строк две — они обязаны совпадать, и это сторожит проверка, а не обещание в
 * комментарии. Найдено проверкой кода: прежде комментарий обещал сторожа, которого не было.
 */
test('текст отказа на экране и в слое метрик — один и тот же', () => {
  expect(ТЕКСТ_СТРАНИЦЫ).toBe(ТЕКСТ_МЕТРИК)
})
