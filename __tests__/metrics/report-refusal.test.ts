import { expect, test } from 'vitest'

import { monthlyReport, ТЕКСТ_ДАННЫЕ_НЕ_ЧИТАЮТСЯ, ОтказОтчёта } from '@/lib/metrics/report'

/**
 * Свой вид у отказа отчёта — задача 4 куска S8, сторона слоя метрик.
 *
 * Отчёт настоящий, без подставок модуля: подставленный отчёт доказывал бы, что подставка
 * умеет бросать, а не что наш отказ называет свой вид.
 */

const АДРЕС_БАЗЫ = 'postgresql://пользователь-базы:пароль@внутренний-хост.example:5432/nordic_pet'

test('кривой месяц — отказ своего вида, и текст прежний', async () => {
  const отказ = await monthlyReport('boom').catch((о: unknown) => о)

  expect(отказ).toBeInstanceOf(ОтказОтчёта)
  expect((отказ as ОтказОтчёта).вид).toBe('кривой месяц')
  expect((отказ as ОтказОтчёта).message).toMatch(/форме ГГГГ-ММ/)
})

/**
 * Отказ соединения несёт в себе адрес базы, а текст на экран мы составляем сами. Проверяется
 * не слово «ошибка», а сам адрес и имя пользователя: утечка выглядит именно так.
 */
test('сбой базы — отказ своего вида, и адреса базы в нём нет', async () => {
  // Среда называется словом до всякой работы (S2), иначе отчёт откажет раньше, чем дойдёт до
  // соединения, — и проверка мерила бы не то. Значение возвращается на место следом.
  const прежняя = process.env.NORDIC_PET_DB_TARGET
  process.env.NORDIC_PET_DB_TARGET = 'local'

  const отказ = await monthlyReport('2026-03', {
    connect: async () => {
      throw new Error(`не удалось соединиться: ${АДРЕС_БАЗЫ}`)
    },
  }).catch((о: unknown) => о)

  if (прежняя === undefined) delete process.env.NORDIC_PET_DB_TARGET
  else process.env.NORDIC_PET_DB_TARGET = прежняя

  expect(отказ).toBeInstanceOf(ОтказОтчёта)
  expect((отказ as ОтказОтчёта).вид).toBe('данные не читаются')

  // Сообщение отказа остаётся подлинным: его печатает команда в терминале, и человек,
  // который чинит настройку, обязан видеть, что именно сломалось. На экран оно не идёт —
  // экран печатает свой постоянный текст, и это сторожит `screen-refusal.test.tsx`.
  expect((отказ as ОтказОтчёта).message).toContain('внутренний-хост.example')
  expect(String((отказ as ОтказОтчёта).cause)).toContain('внутренний-хост.example')
})

/**
 * Текст для экрана — постоянный и адреса базы не содержит по построению. Это утверждение о
 * самой строке, а не о разметке: разметку сторожит проверка экрана.
 */
test('текст для экрана не составляется из чужого сообщения', () => {
  expect(ТЕКСТ_ДАННЫЕ_НЕ_ЧИТАЮТСЯ).not.toMatch(/postgres|@|:\/\//)
  expect(ТЕКСТ_ДАННЫЕ_НЕ_ЧИТАЮТСЯ).toMatch(/не читаются/)
})

/**
 * Неназванная среда — это тоже «данные не читаются»: посетителю она непочинима так же, как
 * недоступная база, и знать он должен то же самое — числа не показаны нарочно.
 */
test('неназванная среда — тот же вид отказа, а не падение наружу', async () => {
  const прежняя = process.env.NORDIC_PET_DB_TARGET
  delete process.env.NORDIC_PET_DB_TARGET

  const отказ = await monthlyReport('2026-03').catch((о: unknown) => о)

  if (прежняя !== undefined) process.env.NORDIC_PET_DB_TARGET = прежняя

  expect(отказ).toBeInstanceOf(ОтказОтчёта)
  expect((отказ as ОтказОтчёта).вид).toBe('данные не читаются')
  expect(String((отказ as ОтказОтчёта).cause)).toContain('NORDIC_PET_DB_TARGET')
})
