import { describe, expect, test } from 'vitest'

import { count, money, percent, ratio } from '../../lib/metrics/format.ts'

/**
 * Формат чисел — задача 6. Ни одна из проверок не трогает базу: `money`, `percent`
 * и `count` только переставляют символы в уже готовой строке. Округление и арифметика —
 * дело SQL, и последняя проверка в каждом блоке нарочно ловит их отсутствие: если формат
 * когда-нибудь начнёт округлять или считать сам, здесь это станет красным.
 */

describe('money: деньги', () => {
  test('деньги: разряды неразрывным пробелом, запятая, знак евро', () => {
    expect(money('1234.50')).toBe('1 234,50 €')
    expect(money('0.00')).toBe('0,00 €')
    expect(money('-133.80')).toBe('−133,80 €')
    expect(money('18764.00')).toBe('18 764,00 €')
  })

  test('формат ничего не округляет и не досчитывает', () => {
    expect(money('1.005')).toBe('1,005 €')
  })
})

describe('percent: проценты', () => {
  test('проценты: запятая и знак, а нет данных — словами', () => {
    expect(percent('80.3')).toBe('80,3 %')
    expect(percent(null)).toBe('нет данных')
  })

  test('формат процентов ничего не округляет', () => {
    expect(percent('80.34')).toBe('80,34 %')
  })
})

describe('ratio: окупаемость', () => {
  // Окупаемость — отношение, а не проценты: оборот больше рекламы в 4,23 раза — это
  // «4,23 ×», а не «4,23 %». Знак стоит после числа через неразрывный пробел, как и у
  // денег со знаком евро, но здесь это ×, а не %, — перепутать их и значит повторить
  // найденный на приёмке дефект.
  test('окупаемость: разряды, запятая, знак × после числа, нет данных словами', () => {
    expect(ratio('4.23')).toBe('4,23 ×')
    expect(ratio(null)).toBe('нет данных')
  })

  test('формат окупаемости ничего не округляет', () => {
    expect(ratio('423.456')).toBe('423,456 ×')
  })
})

describe('count: штуки', () => {
  test('штуки: разряды неразрывным пробелом, без знака и без запятой', () => {
    expect(count('1234')).toBe('1 234')
    expect(count('0')).toBe('0')
    expect(count('18764')).toBe('18 764')
  })

  test('формат штук ничего не округляет и не досчитывает', () => {
    expect(count('1234.50')).toBe('1 234,50')
  })
})
