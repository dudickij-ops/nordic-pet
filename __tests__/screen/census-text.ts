/**
 * Способ снятия переписи — вынесен из файла переписи куском S12 и **не изменён ни на символ**.
 *
 * Причина выноса: проверки нового куска тоже снимают видимый текст, а ввоз из файла проверок
 * заставлял бы саму перепись прогоняться в каждом из них заново. Второго способа снять текст при
 * этом не заведено — он по-прежнему один, просто лежит рядом.
 */
export function текстПоПорядку(html: string): string[] {
  return html
    .replace(/<[^>]*>/g, '\n')
    .split('\n')
    .map((кусок) => кусок.trim())
    .filter((кусок) => кусок !== '')
}
