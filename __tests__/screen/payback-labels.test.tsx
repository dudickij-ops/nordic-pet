import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, test } from 'vitest'

import { Dashboard } from '@/app/page'
import { ПЕРЕПИСЬ } from './fixture.ts'

/**
 * Подписи блока окупаемости — кусок S12, задача 3.
 *
 * **Чем это проверяется и чем не проверяется.** Перенос подписи на пять строк — свойство браузера
 * на узком экране, и доказывается он снимком и глазом, как весь вид в этом проекте. Здесь
 * сторожатся две причины того переноса, а не он сам, и обе — устройство разметки:
 *
 *   1. в ячейке значения не лежит предложение — прежде там стояла фраза на сто с лишним знаков, и
 *      она задавала ширину всего столбца значений, сжимая подписи **всех** строк блока;
 *   2. ни одна подпись сама не несёт пояснения — длина держится ниже предела.
 *
 * Предел — тридцать два знака, и это **наш выбор по замеру**, а не выписка откуда-либо: на узком
 * снимке (500 пикселей) подпись «Окупаемость рекламы (по обороту)» ровно этой длины укладывалась в
 * строку, когда столбец значений узкий. Проверка честно слабая и названа слабой: она сторожит
 * длину, а не перенос.
 */

const ПРЕДЕЛ_ПОДПИСИ = 32

function блокОкупаемости(): string {
  const html = renderToStaticMarkup(<Dashboard report={ПЕРЕПИСЬ} tab="dengi" />)
  const начало = html.indexOf('<section class="block payback">')
  expect(начало).toBeGreaterThan(-1)
  return html.slice(начало, html.indexOf('</section>', начало))
}

const все = (разметка: string, образец: RegExp) =>
  [...разметка.matchAll(образец)].map((м) => м[1])

describe('подписи блока окупаемости', () => {
  test('ни одна подпись не длиннее предела', () => {
    const подписи = все(блокОкупаемости(), /<dt>([^<]*)<\/dt>/g)
    expect(подписи).toHaveLength(4)
    expect(подписи.filter((п) => п.length > ПРЕДЕЛ_ПОДПИСИ)).toEqual([])
  })

  test('в ячейке значения лежит значение, а не предложение', () => {
    const значения = все(блокОкупаемости(), /<dd[^>]*>([^<]*)<\/dd>/g)
    expect(значения).toHaveLength(4)
    for (const значение of значения) {
      expect(значение).not.toContain('.')
      expect(значение.length).toBeLessThanOrEqual(40)
    }
  })

  test('пометка «наш счёт» стоит в подписях наших же величин, а не только в пояснении', () => {
    const подписи = все(блокОкупаемости(), /<dt>([^<]*)<\/dt>/g)
    expect(подписи.filter((п) => п.includes('наш счёт'))).toEqual([
      'Вклад с евро оборота — наш счёт',
      'Порог от вклада — наш счёт',
    ])
    expect(блокОкупаемости()).toContain('Вклад и порог — наши определения.')
  })

  test('подпись порога называет свою базу, а противопоставление ушло в пояснение', () => {
    const разметка = блокОкупаемости()
    expect(разметка).toContain('<dt>Порог от вклада — наш счёт</dt>')
    expect(разметка).toContain('Порог — 100 ÷ вклад, а не от маржи')
  })
})
