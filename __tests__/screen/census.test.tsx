test('на экране все одиннадцать видов неполноты, каждый со своим числом', () => {
  const страница = renderToStaticMarkup(<Dashboard report={ПЕРЕПИСЬ} />)
  // Кусок S13, задача 13: все виды — под раскрытием неполноты; ищутся внутри него. Нет раскрытия — отказ.
  const начало = страница.indexOf('<details class="gaps-more">')
  if (начало === -1) throw new Error('раскрытия неполноты (details.gaps-more) на экране нет')
  const html = страница.slice(начало, страница.indexOf('</details>', начало))
  ОДИННАДЦАТЬ.forEach((вид, i) => {
    expect(html, `вид «${вид}» пропал с экрана`).toContain(`${вид}: ${i + 1}`)
  })
})
