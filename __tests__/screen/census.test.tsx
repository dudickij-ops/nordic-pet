/**
 * Сеть безопасности куска S9 — ставится **до первого тронутого тега**.
 *
 * Кусок меняет только то, как показано, и ничего из того, что показано. Главный его риск —
 * показанное поехало, а в слое метрик не поехало ничего. Прежние проверки экрана этот риск не
 * закрывают: они написаны через `toContain`, то есть слепы к порядку, к повтору и к пропаже
 * одного значения из двенадцати.
 *
 * **Первая редакция этой переписи снимала только числа, и этого оказалось мало.** Проверка кода
 * показала дыру, и дыра была подтверждена наблюдением: если переставить местами две подписи —
 * «Скидки» и «Возвраты», оставив значения на местах, — экран начинает показывать скидки под
 * словом «Возвраты», а **все 741 проверка остаются зелёными**. Числа-то на месте и в прежнем
 * порядке; поехала их привязка к подписям, а числовая перепись подписей не видит.
 *
 * Поэтому перепись снимает **весь видимый текст** по порядку: подписи, заголовки, числа, строки
 * неполноты. Она краснеет от перестановки значений, от перестановки подписей, от пропажи любой
 * строки, от лишнего повтора и от смены порядка товаров.
 *
 * Цена у этого честная и названа вслух: всякое сознательное добавление текста на экран требует
 * правки списка ниже. Это не дефект, а плата — правка видна в диффе и обязана быть объяснена.
 */

/**
 * Весь видимый текст страницы, по порядку.
 *
 * Теги заменяются переносом строки, а не пустотой: иначе соседние ячейки таблицы слиплись бы в
 * одну строку, и перестановка двух значений внутри строки прошла бы незамеченной.
 */
export function текстПоПорядку(html: string): string[] {
  return html
    .replace(/<[^>]*>/g, '\n')
    .split('\n')
    .map((кусок) => кусок.trim())
    .filter((кусок) => кусок !== '')
}

