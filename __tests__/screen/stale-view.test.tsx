import { renderToStaticMarkup } from 'react-dom/server'
import { expect, test, vi } from 'vitest'

vi.mock('next/cache', () => ({ revalidatePath: vi.fn() }))

import { RefreshView } from '@/app/refresh-panel'

/**
 * Гашение устаревших чисел — кусок S9, сторона разметки.
 *
 * Требование прежнего куска: после отказа кнопки прежние числа обязаны менять **вид**, а не
 * только сопровождаться текстом. Человек, увидевший прежние числа в прежнем виде, прочитает
 * отказ как «ничего не изменилось».
 *
 * **Зачем эта проверка, если та же щель уже сторожится принятыми проверками прошлого куска.**
 * Кусок S9 перенёс гашение со встроенного стиля на класс. Принятые проверки утверждают признак
 * `data-stale` и слово «устарели» — про вид в них нет ничего, и после переезда утверждение
 * «изменённый вид чисел» перестало соответствовать тому, что они вправду проверяют. Найдено
 * проверкой кода. Эта проверка возвращает утверждению его смысл настолько, насколько его вообще
 * можно вернуть без браузера: обёртка чисел обязана получать **отдельный** класс, когда числа
 * устарели, и не получать его, когда они свежие.
 *
 * **Чего она не доказывает, и это названо вслух.** Что класс вправду гасит — она не знает: это
 * правило таблицы стилей, а таблица стилей в этом куске сломом не сторожится вовсе. Удаление
 * правила из таблицы стилей эта проверка не поймает. Проверяется связь разметки с состоянием,
 * а не вид.
 */

function вид(stale: boolean): string {
  return renderToStaticMarkup(
    <RefreshView
      outcome={stale ? { ok: false, step: 'разбор', text: 'разбор отказал', stale: true } : { ok: true }}
      pending={false}
    >
      <p>ЧИСЛА</p>
    </RefreshView>,
  )
}

test('устаревшие числа получают свой класс, свежие — не получают', () => {
  const устарели = вид(true)
  expect(устарели, 'числа со страницы не пропадают, а меняют вид').toContain('ЧИСЛА')
  expect(устарели, 'обёртка устаревших чисел помечена своим классом').toMatch(
    /class="[^"]*\bstale\b[^"]*"/,
  )

  const свежие = вид(false)
  expect(свежие).toContain('ЧИСЛА')
  expect(свежие, 'свежие числа отдельного класса не несут').not.toMatch(
    /class="[^"]*\bstale\b[^"]*"/,
  )
})
