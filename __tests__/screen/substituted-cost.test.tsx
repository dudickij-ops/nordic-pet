import { renderToStaticMarkup } from 'react-dom/server'
import { describe, expect, test } from 'vitest'

import { Dashboard } from '@/app/page'
import { ПЕРЕПИСЬ } from './fixture.ts'
import { текстПоПорядку } from './census-text.ts'

/**
 * Пометка подставленной себестоимости в строке товара — кусок S12, задача 2.
 *
 * Пометка стоит там, где по числу принимают решение, — в самой строке, а не только на другой
 * вкладке. И она ведёт туда, где лежит её размер: число подставленных строк продаж живёт в блоке
 * неполноты, и пометка обязана к нему вести, иначе сообщает тревогу без меры.
 */

const отчёт = (подстановки: Array<'вся' | 'часть' | undefined>) => ({
  ...ПЕРЕПИСЬ,
  items: ПЕРЕПИСЬ.items.map((строка, i) => ({ ...строка, подстановка: подстановки[i] })),
})

const разметка = (подстановки: Array<'вся' | 'часть' | undefined>) =>
  renderToStaticMarkup(<Dashboard report={отчёт(подстановки)} tab="tovary" />)

describe('пометка подставленной себестоимости', () => {
  test('строка с настоящей ценой не помечена ничем', () => {
    const текст = текстПоПорядку(разметка([undefined, undefined]))
    expect(текст.filter((с) => с.includes('подставлена'))).toEqual([])
  })

  test('подставленная целиком и подставленная частью названы разными словами', () => {
    const текст = текстПоПорядку(разметка(['вся', 'часть']))
    expect(текст.filter((с) => с.includes('подставлена'))).toEqual([
      'подставлена — см. «Качество данных»',
      'подставлена частью — см. «Качество данных»',
    ])
  })

  /**
   * Круг проверки кода 1. Первая редакция искала адрес во **всей** разметке и покраснеть не могла:
   * такая же ссылка всегда стоит в полосе вкладок. Теперь адрес ищется в самой пометке — рецензент
   * показал прогоном, что с изуродованным адресом прежняя проверка оставалась зелёной.
   */
  test('пометка ведёт на вкладку, где лежит её размер, и несёт месяц отчёта', () => {
    const пометки = [...разметка(['вся', undefined]).matchAll(/<a class="substituted" href="([^"]*)"/g)]
    expect(пометки.map((м) => м[1])).toEqual(['/?m=2026-03&amp;tab=kachestvo'])
  })

  test('помечена ровно та строка, у которой подстановка, а не соседняя', () => {
    const текст = текстПоПорядку(разметка([undefined, 'вся']))
    const где = текст.findIndex((с) => с.includes('подставлена'))
    const первый = текст.indexOf('NP-101')
    const второй = текст.indexOf('NP-202')
    expect(где).toBeGreaterThan(второй)
    expect(второй).toBeGreaterThan(первый)
  })
})
