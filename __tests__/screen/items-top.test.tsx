import { renderToStaticMarkup } from 'react-dom/server'
import { expect, test } from 'vitest'

import { Dashboard } from '@/app/page'
import type { MonthReport } from '@/lib/metrics/report'
import { ПЕРЕПИСЬ } from './fixture.ts'

/**
 * Товары: пятёрка и раскрытие — кусок S13, задача 12 (решение владельца Э4).
 *
 * Пятёрку выбирает слой метрик признаком `inTop`; разметка раскладывает строки по признаку и не
 * сравнивает чисел. Число артикулов в переключателе — поле отчёта, а не счёт строк.
 */

const строки = (n: number) =>
  Array.from({ length: n }, (_, i) => ({
    ...ПЕРЕПИСЬ.items[0], sku: `NP-${100 + i}`, inTop: i < 5,
  }))
const с = (items: MonthReport['items'], skusTotal = items.length) =>
  renderToStaticMarkup(<Dashboard report={{ ...ПЕРЕПИСЬ, items, itemsSummary: { ...ПЕРЕПИСЬ.itemsSummary!, skusTotal } }} />)

/**
 * Текст снимается с блока товаров, а не со всей страницы: строка вывода о приблизительной прибыли
 * (задача 10) стоит выше и называет артикулы с подстановкой — счёт по всей странице видел бы их.
 * Без блока — отказ, а не пустота.
 */
const блокТоваров = (html: string) => {
  const начало = html.indexOf('<section class="block items"')
  if (начало < 0) throw new Error('блока товаров в разметке нет')
  return html.slice(начало, html.indexOf('</section>', начало))
}

test('строки с признаком пятёрки — в первой таблице, остальные — под раскрытием', () => {
  const html = блокТоваров(с(строки(7)))
  const [видно, скрыто] = html.split('<details')
  expect((видно.match(/NP-1\d\d/g) ?? []).length).toBe(5)
  expect(скрыто).toContain('NP-105')
  expect(скрыто).toContain('NP-106')
})

test('число в переключателе — из отчёта, а не счётом строк', () => {
  expect(с(строки(7), 12)).toContain('Показать все артикулы месяца — 12')
})

test('шесть строк — переключатель есть, пять — нет', () => {
  // Только в блоке товаров: раскрытие неполноты стоит в другом блоке и сюда не попадает.
  expect(блокТоваров(с(строки(6)))).toContain('<details')
  expect(блокТоваров(с(строки(5)))).not.toContain('<details')
})

test('сумма валовой прибыли товаров не положительна — строка над таблицей называет её валовой', () => {
  const html = renderToStaticMarkup(
    <Dashboard report={{ ...ПЕРЕПИСЬ, itemsSummary: { productsProfit: '-20.00', skusTotal: 2, skusFor80: null, negativeCount: 1 } }} />,
  )
  expect(блокТоваров(html)).toContain('Валовая прибыль товаров — выручка минус себестоимость, −20,00\u00A0€ — не положительна')
})

test('у двух таблиц одно описание колонок', () => {
  const html = с(строки(7))
  const колонки = html.match(/<colgroup>.*?<\/colgroup>/g) ?? []
  expect(колонки).toHaveLength(2)
  expect(колонки[0]).toBe(колонки[1])
})

test('колонка называется «Валовая прибыль», слово «Прибыль» отдельным заголовком не стоит', () => {
  const html = с(строки(6))
  expect(html).toContain('>Валовая прибыль</th>')
  expect(html).not.toContain('>Прибыль</th>')
})

/**
 * Полоска доли — то же условие владельца, что у полосы честности (кусок S9): текст и полоска берут
 * одно значение из одного места, разметка над ним ничего не делает. Долей две разные: с одной
 * постоянная длина, случайно совпавшая с числом, прошла бы зелёной.
 */
test('полоска доли берёт ту же величину, что напечатана в ячейке', () => {
  for (const [доля, текст] of [['37.5', '37,5 %'], ['91.25', '91,25 %']]) {
    const html = renderToStaticMarkup(
      <Dashboard report={{ ...ПЕРЕПИСЬ, items: [{ ...ПЕРЕПИСЬ.items[0], profitSharePct: доля }] }} />,
    )
    const блок = блокТоваров(html)
    expect(блок, 'число печатается').toContain(текст)
    expect(блок.replace(/\s/g, ''), 'полоска получает то же значение').toContain(`--item-share:${доля}%`)
  }
})

/**
 * Кусок S13, задача 17, правка по итоговой проверке (находка И1). Договор, утверждение 8: экран не
 * сравнивает, и ловушку договор называет сам — `slice` и счёт длины в разметке. В раскладке выше
 * признак стоит ровно у первых пяти по индексу, а артикулы идут по возрастанию: там разметка
 * `items.slice(0, 5)` и переключатель по `items.length > 5` неотличимы от честного чтения признака.
 *
 * Здесь признак стоит вразброс, а у строк разные числа. Правка по проверке правок задачи 17: прежде все восемь
 * строк были копией одной строки переписи, и устойчивая сортировка разметкой по прибыли, выручке или штукам
 * порядка не меняла. Теперь порядок строк не совпадает ни с одной сортировкой — по артикулу, штукам, чистой
 * выручке, себестоимости, валовой прибыли, по возрастанию и по убыванию — ни во всём списке, ни в пятёрке, ни
 * в раскрытой части; значения всех пяти столбцов в каждой из трёх последовательностей различны. Первые пять по
 * индексу — NP-305, NP-102, NP-410, NP-201, NP-503, а пятёрка по признаку — NP-102, NP-201, NP-503, NP-007, NP-333.
 */
const ВРАЗБРОС: Array<[string, boolean, string, string, string, string]> = [
  // артикул,  пятёрка, штуки, чистая выручка, себестоимость, валовая прибыль
  ['NP-305', false, '7', '420.00', '120.00', '300.00'],
  ['NP-102', true, '3', '910.00', '110.00', '800.00'],
  ['NP-410', false, '12', '250.00', '150.00', '100.00'],
  ['NP-201', true, '5', '760.00', '160.00', '600.00'],
  ['NP-503', true, '9', '330.00', '130.00', '200.00'],
  ['NP-120', false, '2', '640.00', '140.00', '500.00'],
  ['NP-007', true, '11', '180.00', '30.00', '150.00'],
  ['NP-333', true, '4', '870.00', '170.00', '700.00'],
]
const вразброс = () =>
  ВРАЗБРОС.map(([sku, inTop, units, net, cogs, profit]) => ({ ...ПЕРЕПИСЬ.items[0], sku, inTop, units, net, cogs, profit }))
const артикулы = (html: string) => html.match(/NP-\d{3}/g) ?? []
const видноИСкрыто = (html: string) => {
  const [видно, скрыто = ''] = блокТоваров(html).split('<details')
  return { видно: артикулы(видно), скрыто: артикулы(скрыто) }
}

test('пятёрка — по признаку, а не по месту в списке: признак стоит вразброс', () => {
  const { видно, скрыто } = видноИСкрыто(с(вразброс(), 8))
  expect(new Set(видно)).toEqual(new Set(['NP-102', 'NP-201', 'NP-503', 'NP-007', 'NP-333']))
  expect(видно).toHaveLength(5)
  expect(new Set(скрыто)).toEqual(new Set(['NP-305', 'NP-410', 'NP-120']))
  expect(скрыто).toHaveLength(3)
})

/**
 * Переключатель — по признаку. Две половины, и каждая ловит счёт длины со своей стороны: шесть строк
 * прежней раскладки без поля признака (все остаются в первой таблице — раскрывать нечего) и четыре
 * строки, одна из которых вне пятёрки.
 */
test('переключатель — по признаку, а не по счёту строк', () => {
  const безПризнака = Array.from({ length: 6 }, (_, i) => ({ ...ПЕРЕПИСЬ.items[0], sku: `NP-${600 + i}` }))
  expect(блокТоваров(с(безПризнака))).not.toContain('<details')
  const четыре = вразброс().slice(0, 4)
  expect(блокТоваров(с(четыре))).toContain('<details')
})

/**
 * Утверждение принятой проверки S12 (`__tests__/screen/items-order.test.tsx`, удалена в задаче 4 вместе с
 * порядками в адресе — учёт задачи 4) вернулось: разметка не сортирует. Строки вразброс, порядок
 * ожидается ровно тот, в каком они пришли, — в первой таблице и под раскрытием.
 */
test('разметка отдаёт строки в том порядке, в каком получила', () => {
  const { видно, скрыто } = видноИСкрыто(с(вразброс(), 8))
  expect(видно).toEqual(['NP-102', 'NP-201', 'NP-503', 'NP-007', 'NP-333'])
  expect(скрыто).toEqual(['NP-305', 'NP-410', 'NP-120'])
})
