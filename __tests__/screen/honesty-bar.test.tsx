import { renderToStaticMarkup } from 'react-dom/server'
import { expect, test } from 'vitest'

import { Dashboard } from '@/app/page'
import { ПЕРЕПИСЬ } from './fixture.ts'

/**
 * Полоса доли честности — кусок S9.
 *
 * **Решение владельца против рекомендации автора.** Я предлагал полосу не делать, сославшись
 * на правило проекта «экран не считает». Владелец поправил прочтение правила: оно запрещает
 * **вычислять**, а не **показывать**. Полоса получает то самое число, которое напечатано рядом
 * текстом; ни деления, ни вычитания, ни приведения в разметке не происходит.
 *
 * **Условие, выставленное вместе с разрешением:** и текст, и полоса берут одно и то же
 * значение из одного места. Пока значение одно, полоса не может разойтись с числом, а полоса,
 * разошедшаяся с числом, врёт убедительнее самого числа: её читают быстрее, чем цифры.
 *
 * **Что именно доказано, а что нет.** Проверка утверждает совпадение значений на двух разных
 * долях: ушедшее в полосу равно напечатанному. Что чтение в коде ровно одно, она не
 * доказывает — второе чтение того же поля прошло бы её зелёным. Беды в этом нет: два чтения
 * одного поля разойтись не могут. Но утверждать шире доказанного нельзя, и потому сказано.
 *
 * Доли берутся **две разные**, а не одна: с одной постоянная длина, случайно совпавшая с этим
 * числом, прошла бы зелёной.
 */

/** Отрисовка отчёта с подменённой долей. Всё прочее — раскладка переписи, значения в ней различны. */
function сДолей(доля: string | null): string {
  return renderToStaticMarkup(
    <Dashboard report={{ ...ПЕРЕПИСЬ, honesty: { sharePct: доля, skusWithoutPrice: [] } }} tab="kachestvo" />,
  )
}

test('полоса берёт ту же величину, что и напечатанное рядом число', () => {
  const первая = сДолей('37.5')
  expect(первая, 'число печатается').toContain('37,5 %')
  expect(первая.replace(/\s/g, ''), 'полоса получает то же значение').toContain('--share:37.5%')

  const вторая = сДолей('91.25')
  expect(вторая, 'число печатается').toContain('91,25 %')
  expect(вторая.replace(/\s/g, ''), 'полоса получает то же значение').toContain('--share:91.25%')
})

/**
 * Доля вне 0…100 в настоящих данных не встречалась ни разу, но арифметически возможна: чистая
 * выручка строки уходит в минус при крупном возврате, а доля считается от неё.
 *
 * Прежде значение подставлялось прямо в ширину, и отрицательная доля делала объявление негодным
 * — браузер брал ширину по умолчанию и рисовал полосу **во всю дорожку**. Замерено в браузере:
 * при −12,3 % заполнение занимало 328,8 из 328,8 пикселей. Полоса говорила «посчитано всё» там,
 * где текст рядом говорил «минус двенадцать». Найдено проверкой кода.
 *
 * Теперь значение уходит величиной, а длину из неё делает `clamp` в таблице стилей. Проверка
 * утверждает, что разметка отдаёт значение **как есть**, не трогая его: приведение к пределам —
 * дело показа, а не разметки, и число на экране остаётся тем, что вернул слой метрик.
 */
test('доля вне пределов уходит в полосу как есть, а не подправленной разметкой', () => {
  const разметка = сДолей('-12.3')
  expect(разметка, 'число печатается как есть').toContain('−12,3 %')
  expect(разметка.replace(/\s/g, ''), 'разметка значение не подправляет').toContain('--share:-12.3%')
})

test('нет доли — нет полосы, а на экране слова', () => {
  const разметка = сДолей(null)
  expect(разметка).toContain('нет данных')
  expect(
    разметка,
    'полоса нулевой длины сказала бы, что доля посчитана и равна нулю; «нет данных» — не ноль',
  ).not.toContain('share-fill')
})
