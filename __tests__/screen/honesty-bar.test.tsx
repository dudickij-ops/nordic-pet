import { renderToStaticMarkup } from 'react-dom/server'
import { expect, test } from 'vitest'

import { Dashboard } from '@/app/page'
import { ПЕРЕПИСЬ } from './fixture.ts'

/**
 * Полоса доли честности — задача 7 куска S9.
 *
 * **Решение владельца против рекомендации автора.** Я предлагал полосу не делать, сославшись на
 * правило проекта «экран не считает». Владелец поправил прочтение правила: оно запрещает
 * **вычислять**, а не **показывать**. Ширина берётся из того самого числа, которое напечатано
 * рядом текстом; ни деления, ни вычитания, ни приведения в разметке не происходит.
 *
 * **Условие, выставленное вместе с разрешением, и есть предмет этих проверок:** и текст, и
 * ширина обязаны брать одно и то же значение из одного места. Пока значение одно, полоса не
 * может разойтись с числом. Два чтения того же поля рядом друг с другом были бы двумя
 * источниками правды, и однажды они разъехались бы молча — а полоса, разошедшаяся с числом,
 * врёт убедительнее самого числа: её читают быстрее, чем цифры.
 *
 * Проверка идёт на **двух разных долях**, а не на одной. С одной долей постоянная ширина,
 * случайно совпавшая с этим числом, прошла бы зелёной.
 */

/** Отрисовка отчёта с подменённой долей. Всё прочее — раскладка переписи, значения в ней различны. */
function сДолей(доля: string | null): string {
  return renderToStaticMarkup(
    <Dashboard report={{ ...ПЕРЕПИСЬ, honesty: { sharePct: доля, skusWithoutPrice: [] } }} />,
  )
}

test('полоса берёт ту же величину, что и напечатанное рядом число', () => {
  const первая = сДолей('37.5')
  expect(первая, 'число печатается').toContain('37,5 %')
  expect(первая.replace(/\s/g, ''), 'ширина полосы — то же значение').toContain('width:37.5%')

  const вторая = сДолей('91.25')
  expect(вторая, 'число печатается').toContain('91,25 %')
  expect(вторая.replace(/\s/g, ''), 'ширина полосы — то же значение').toContain('width:91.25%')
})

test('нет доли — нет полосы, а на экране слова', () => {
  const разметка = сДолей(null)
  expect(разметка).toContain('нет данных')
  expect(
    разметка,
    'полоса нулевой длины сказала бы, что доля посчитана и равна нулю; «нет данных» — не ноль',
  ).not.toContain('share-fill')
})
