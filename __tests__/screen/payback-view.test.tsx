import { renderToStaticMarkup } from 'react-dom/server'
import { expect, test } from 'vitest'

import { Dashboard } from '@/app/page'
import type { MonthReport } from '@/lib/metrics/report'
import { ПЕРЕПИСЬ } from './fixture.ts'

/**
 * Вид блока «Окупаемость рекламы» — кусок S11, шаг 3.
 *
 * Условия владельца к блоку — прямые его слова при принятии контракта и по развилке В7: на экране
 * стоят и порог, и вклад числом; подпись порога называет, от чего он считается, — от вклада, а не от
 * маржи экрана; рядом сказано, что определения наши. Довод владельца: экран, по которому человек сам
 * получит противоположный вывод, деля сто на маржу, хуже экрана без порога вовсе.
 */

type Окупаемость = NonNullable<MonthReport['payback']>

function сОкупаемостью(окупаемость: Окупаемость | undefined): string {
  return renderToStaticMarkup(<Dashboard report={{ ...ПЕРЕПИСЬ, payback: окупаемость }} tab="dengi" />)
}

const ОКУПАЕМОСТЬ = ПЕРЕПИСЬ.payback as Окупаемость

/** Кусок разметки блока — чтобы слова соседних блоков не попадали в утверждения о нём. */
function блок(разметка: string): string {
  const начало = разметка.indexOf('<section class="block payback">')
  expect(начало, 'блок окупаемости на странице').toBeGreaterThanOrEqual(0)
  return разметка.slice(начало, разметка.indexOf('</section>', начало))
}

/**
 * Шаг вкладок, решение владельца по В7: окупаемость по обороту переехала в этот блок, и блок стоит
 * всегда — прежнее число экрана не пропадает ни при какой раскладке. От поля отчёта зависят только три
 * числа шага 3. Прежнее утверждение, дословно: «блок окупаемости рисуется только тогда, когда в отчёте
 * есть его поле» — после В7 неверно по устройству.
 */
test('окупаемость по обороту стоит в блоке всегда, а три числа шага 3 — только при своём поле', () => {
  const безПоля = блок(сОкупаемостью(undefined))
  expect(безПоля).toContain('<dt>Окупаемость рекламы (по обороту)</dt><dd class="payback-main">45,6\u00A0×</dd>')
  expect(безПоля).not.toContain('по прибыли')
  expect(блок(сОкупаемостью(ОКУПАЕМОСТЬ))).toContain('<dt>Окупаемость рекламы (по прибыли)</dt>')
})

test('подпись порога называет его базу — вклад, а не маржу экрана', () => {
  expect(блок(сОкупаемостью(ОКУПАЕМОСТЬ))).toContain('<dt>Порог окупаемости — от вклада, а не от маржи</dt>')
})

test('вклад стоит числом рядом с порогом', () => {
  expect(блок(сОкупаемостью(ОКУПАЕМОСТЬ))).toMatch(
    /<dt>Вклад с евро оборота<\/dt><dd>43,2 %<\/dd><dt>Порог окупаемости[^<]*<\/dt><dd>2,31 ×<\/dd>/,
  )
})

test('рядом с порогом сказано, что определения наши', () => {
  expect(блок(сОкупаемостью(ОКУПАЕМОСТЬ))).toContain('Вклад и порог — наши определения.')
})

test('порога нет — сказано словами, а не «нет данных» и не отрицательным порогом', () => {
  const разметка = блок(
    сОкупаемостью({ ...ОКУПАЕМОСТЬ, breakevenRoas: null, breakevenNote: 'вклад не положителен' }),
  )
  expect(разметка).toContain('<dd>порога нет: вклад не положителен</dd>')
})

test('у окупаемости по прибыли названа база — после постоянных расходов, и сказано, чем она не порог', () => {
  expect(блок(сОкупаемостью(ОКУПАЕМОСТЬ))).toMatch(
    /<dt>Окупаемость рекламы \(по прибыли\)<\/dt><dd>0,31\u00A0×<span class="payback-why">После постоянных расходов — они от рекламы не зависят, поэтому окупается ли реклама, говорит порог, а не это число\.<\/span><\/dd>/,
  )
})
