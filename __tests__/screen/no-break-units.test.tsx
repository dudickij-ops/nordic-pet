/**
 * Число не отрывается от знака € или % переносом строки — кусок S11, решение владельца.
 *
 * Общий формат денег ставит перед знаком обычный пробел (отложенная задача S5); общая починка тронула
 * бы ожидаемые строки принятых проверок нескольких кусков. Поэтому перенос запрещён по отдельности: в
 * ячейках значений и в значениях вне ячеек — таблицей стилей, в предложениях — неразрывным пробелом в
 * самой строке. Это обход, а не починка, и владелец велел его сторожить: **четвёртое место, которое
 * кто-то забудет защитить, краснеет само**. Поэтому проверка не перечисляет защищённые предложения, а
 * обходит всю разметку всех вкладок и у каждого числа со знаком через обычный пробел требует защиты.
 *
 * **Чего разбор не понимает, и это названо.** Он читает разметку, а не вёрстку: что таблица стилей
 * вправду запрещает перенос у перечисленных элементов, утверждает вторая проверка — текстом таблицы
 * стилей, слабо. Число со знаком, разорванное тегом (`12,3 <b>%</b>`), он не видит. Раскладки ниже —
 * все ветви трёх предложений: расхождение до чистой выручки и до прибыли, равенство «съедает больше
 * всего», неположительная прибыль товаров.
 */

/** Элементы, которым таблица стилей запрещает перенос. Выписаны буквально: тег, класс, родитель. */
const ПОД_ЗАПРЕТОМ = ['dd', 'td', 'span.kpi-value', 'span.waterfall-amount', 'span.waterfall-share', 'div.daily-axis > span', 'strong.share-value']

const РАСКЛАДКИ: Array<[string, MonthReport]> = [
  ['перепись', ПЕРЕПИСЬ],
  ['март', МАРТ],
  ['март без базы', МАРТ_БЕЗ_БАЗЫ],
  ['расхождение до чистой выручки', { ...ПЕРЕПИСЬ, waterfall: { ...ПЕРЕПИСЬ.waterfall!, netGap: '0.02' } }],
  [
    'равенство «съедает больше всего»',
    {
      ...ПЕРЕПИСЬ,
      waterfall: {
        ...ПЕРЕПИСЬ.waterfall!,
        steps: ПЕРЕПИСЬ.waterfall!.steps.map((с) => (с.key === 'ads' ? { ...с, largest: true } : с)),
      },
    },
  ],
  [
    'прибыль товаров не положительна',
    { ...ПЕРЕПИСЬ, itemsSummary: { productsProfit: '-20.00', skusTotal: 2, skusFor80: null, negativeCount: 1 } },
  ],
]

/** Текст разметки с цепочкой элементов вокруг: `тег.класс` от внешнего к внутреннему. */
function текстыСЦепочкой(html: string): Array<{ текст: string; цепочка: string[] }> {
  const стек: string[] = []
  const итог: Array<{ текст: string; цепочка: string[] }> = []
  for (const м of html.matchAll(/<(\/?)([a-z0-9]+)([^>]*)>|([^<]+)/g)) {
    if (м[4] !== undefined) {
      итог.push({ текст: м[4], цепочка: [...стек] })
      continue
    }
    if (м[1] === '/') {
      стек.pop()
      continue
    }
    if (/\/\s*$/.test(м[3] ?? '')) continue
    const класс = /class="([^"]*)"/.exec(м[3] ?? '')?.[1]?.split(' ')[0]
    стек.push(класс === undefined ? м[2] : `${м[2]}.${класс}`)
  }
  return итог
}

function защищено(цепочка: string[]): boolean {
  return ПОД_ЗАПРЕТОМ.some((защита) => {
    const [родитель, сам] = защита.includes(' > ') ? защита.split(' > ') : [undefined, защита]
    return цепочка.some((звено, i) => (звено === сам || звено.split('.')[0] === сам) && (родитель === undefined || цепочка[i - 1] === родитель))
  })
}

test('денежное значение внутри предложения не бывает без защиты от переноса', () => {
  const открытые: string[] = []
  let найдено = 0
  for (const [имя, отчёт] of РАСКЛАДКИ) {
    for (const tab of ['glavnoe', 'dengi', 'tovary', 'kachestvo'] as const) {
      for (const { текст, цепочка } of текстыСЦепочкой(renderToStaticMarkup(<Dashboard report={отчёт} tab={tab} />))) {
        найдено += (текст.match(/\d[ \u00A0][€%]/g) ?? []).length
        if (/\d [€%]/.test(текст) && !защищено(цепочка)) открытые.push(`${имя}, ${tab}, ${цепочка.join(' > ')}: «${текст.trim()}»`)
      }
    }
  }
  // Разбор, который ничего не нашёл, прошёл бы проверку зелёным: чисел со знаком обязано быть много.
  expect(найдено, 'чисел со знаком в разметке всех вкладок').toBeGreaterThan(100)
  expect(открытые, 'число со знаком через обычный пробел вне защиты от переноса').toEqual([])
})

/** **Проверка текста таблицы стилей — слабая, и так названа.** Доказывает наличие правил, а не вёрстку. */
test('элементам под защитой таблица стилей запрещает перенос', () => {
  const стили = readFileSync(join(process.cwd(), 'app', 'globals.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
  const правила = [...стили.matchAll(/([^{}]+)\{([^}]*)\}/g)]
    .filter(([, , тело]) => /white-space:\s*nowrap/.test(тело))
    .flatMap(([, селекторы]) => селекторы.split(',').map((с) => с.trim()))
  expect(правила).toEqual(expect.arrayContaining(['dd', 'td', '.kpi-value', '.waterfall-amount', '.waterfall-share', '.daily-axis span', '.share-value']))
})
